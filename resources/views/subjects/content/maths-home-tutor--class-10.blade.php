  <h2 id="m10-cbse">CBSE Class 10 maths 2026-27: the 14 chapters and their marks</h2>
  <p>
    The CBSE Class 10 maths paper is 80 marks, with a further 20 marks of internal assessment awarded by the school.
    The 80 theory marks are spread across seven units, and each unit maps to one or more of the 14 chapters in the NCERT
    textbook. This is the unit-wise weightage in CBSE's 2026-27 curriculum:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
