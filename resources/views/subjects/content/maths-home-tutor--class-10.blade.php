    </thead>
    <tbody>
      <tr><td>Number Systems</td><td>Real Numbers</td><td>6</td></tr>
      <tr><td>Algebra</td><td>Polynomials; Pair of Linear Equations in Two Variables; Quadratic Equations; Arithmetic Progressions</td><td>20</td></tr>
      <tr><td>Coordinate Geometry</td><td>Coordinate Geometry</td><td>6</td></tr>
      <tr><td>Geometry</td><td>Triangles; Circles</td><td>15</td></tr>
      <tr><td>Trigonometry</td><td>Introduction to Trigonometry; Some Applications of Trigonometry</td><td>12</td></tr>
      <tr><td>Mensuration</td><td>Areas Related to Circles; Surface Areas and Volumes</td><td>10</td></tr>
      <tr><td>Statistics and Probability</td><td>Statistics; Probability</td><td>11</td></tr>
      <tr><td><strong>Theory total</strong></td><td></td><td><strong>80</strong></td></tr>
