  <h2 id="m10-paper">How the CBSE Class 10 maths paper is built</h2>
  <p>
    CBSE sets the paper by the kind of thinking each question asks for, not just by topic. The 2026-27 curriculum
    gives the following design for the 80-mark, three-hour paper:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Type of question</th><th scope="col">Standard (041)</th><th scope="col">Basic (241)</th></tr>
    </thead>
    <tbody>
      <tr><td>Remembering and understanding</td><td>43 marks (about 54%)</td><td>60 marks (about 75%)</td></tr>
      <tr><td>Applying</td><td>19 marks (about 24%)</td><td>12 marks (about 15%)</td></tr>
      <tr><td>Analysing, evaluating and creating</td><td>18 marks (about 22%)</td><td>8 marks (about 10%)</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    In practice, the "applying" and "analysing" marks are where competency-based questions sit: case-study questions
    built around a real-life situation, assertion and reason items, and problems that do not look like any single
    textbook exercise. Nearly half of the Standard paper is of this kind. Students who have only practised NCERT
    exercises in order often find these questions unsettling, because the chapter is not named and the method is not
    obvious. A tutor helps most here by mixing questions from different chapters and making the student decide which
    tool to use.
  </p>
  <p>
    The 20 internal-assessment marks are split in the curriculum as 10 marks for pen-and-paper tests and multiple
    assessments, 5 for a portfolio and 5 for lab practical activities from the prescribed books. These are marks worth
    collecting in full, and a tutor can make sure the portfolio and lab activities are not left to the last week.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m10-std">Standard or Basic maths: which should your child take?</h2>
  <p>
    CBSE offers Class 10 maths at two levels. Both share the same syllabus and the same NCERT textbook; the difference
    is in the question paper. As the table above shows, the Basic paper puts much more weight on direct recall and
    understanding, while Standard asks for more application and problem-solving.
  </p>
  <ul>
    <li><strong>Choose Standard</strong> if there is any chance the student will want Mathematics in Class 11, particularly for the science stream, engineering or JEE. Standard is the route CBSE intends for students continuing with maths.</li>
    <li><strong>Consider Basic</strong> if the student is clear they will not study maths further and the subject is causing real anxiety. Check your school's current rules on which Class 11 maths course is open after Basic before deciding.</li>
    <li><strong>Do not decide on one bad test.</strong> A weak Class 9 result often reflects gaps that a few months of tutoring can close. Talk it through with the tutor after the first few weeks.</li>
  </ul>
  <p>
    Because the syllabus is shared, a tutor's teaching does not change much between the two levels until the final
    months, when practice papers should match the level the student will sit.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m10-two">The two CBSE Class 10 board exams</h2>
  <p>
    From 2026, CBSE holds two board examinations for Class 10. The first, in February and March, is the main exam and
    every student must sit it. The second, held in May, is optional: students who have appeared in the main exam can
    use it to try to improve their score in a limited number of subjects, and maths is one of them. The internal
    assessment is done only once, before the main exam.
  </p>
  <p>
    This is useful, but it should not change the plan for most students. The main exam is the one to prepare for
    properly. The second window is a safety net for a bad day or a result that falls short of a Class 11 requirement,
    not a reason to treat February as a practice run. If a student does decide to take the May exam in maths, a tutor
    can use the weeks after the first result to work specifically on the chapters and question types where marks were
    lost. Exact dates and rules are set by CBSE each year, so check the board's latest circulars.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m10-icse">ICSE Class 10 maths: what is different</h2>
  <p>
    ICSE Class 10 maths, set by CISCE, is assessed through an 80-mark written paper plus 20 marks of internal
    assessment. The written paper is three hours long, with the first fifteen minutes for reading. It has two parts:
  </p>
  <ul>
    <li><strong>Section A (40 marks), compulsory.</strong> Every question must be attempted. It includes multiple-choice items and short-answer questions from across the syllabus, so there is nowhere to hide a weak chapter.</li>
    <li><strong>Section B (40 marks), with choice.</strong> Students attempt any four questions. Each is a longer, multi-part question, and choosing well is itself a skill that a tutor should practise with the student.</li>
  </ul>
  <p>
    The ICSE syllabus is broader than CBSE in a few important ways. It includes commercial mathematics (GST, banking
    with recurring deposits, and shares and dividends), linear inequations, matrices, the remainder and factor
    theorems, reflection, the equation of a line, loci, constructions, and graphical statistics such as histograms and
    ogives, alongside the similarity, circle, trigonometry, mensuration and probability topics that CBSE students also
    study.
  </p>
  <p>
    The CISCE paper states plainly that omission of essential working will cost marks. ICSE maths therefore rewards
    students who write every step, label every diagram and state every formula used. A good ICSE tutor trains this
    habit from the first month, and plans revision so that the sheer number of chapters is covered well before the
    pre-boards. Our guide to <a href="{{ url('/blog/icse-class-10-maths-boards') }}">preparing for the ICSE Class 10
    maths board exam</a> goes through the topics in more depth.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m10-plan">A month-by-month plan from April to the boards</h2>
  <p>
    Most schools begin Class 10 in April and hold board exams from February. Here is a realistic plan a Class 10
    maths tutor might follow with a student who starts at the beginning of the year. It works for both CBSE and ICSE,
    with the chapter order adjusted to the school's timetable.
  </p>
  <ul>
    <li><strong>April.</strong> Diagnostic sessions on Class 9 foundations: algebraic identities, factorisation, linear equations, coordinate plotting and Pythagoras. Start the first chapters (Real Numbers and Polynomials for CBSE; commercial maths or algebra for ICSE, depending on the school).</li>
    <li><strong>May and June.</strong> The summer break is the most valuable time of the year. Get ahead of school on algebra: linear equations, quadratics and arithmetic progressions. Aim to finish these before school resumes.</li>
    <li><strong>July.</strong> Triangles and similarity, coordinate geometry. First short chapter tests marked with step marks.</li>
    <li><strong>August.</strong> Introduction to Trigonometry, identities and heights and distances. Identities need little and often, so they appear in every session from now on.</li>
    <li><strong>September.</strong> Circles and mensuration. Half-yearly or term exams in many schools: review the marked paper with the tutor, mistake by mistake.</li>
    <li><strong>October.</strong> Statistics and probability, and any remaining ICSE-only topics. Start mixed-chapter practice and case-study questions.</li>
    <li><strong>November.</strong> Syllabus complete. First full-length timed papers, one a week, with every paper reviewed in the next session. Rebuild the two or three weakest chapters.</li>
    <li><strong>December and January.</strong> Pre-board exams in most schools. Sample papers and previous years' papers under exam conditions; a formula and theorem-proof revision sheet the student writes themselves.</li>
    <li><strong>February and March.</strong> Board exams. Short, calm sessions: one paper every few days, targeted revision, no new material. For CBSE students, decide after the result whether the May exam is worth taking in maths.</li>
  </ul>
  <p>
    Starting later is still worthwhile. A student who begins in October needs more sessions per week and a sharper
    focus on the highest-weight chapters, but three or four months of steady one-to-one work can make a real
    difference to the final paper.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m10-session">What a Class 10 maths home tutor session looks like</h2>
  <p>
    A well-run hour with a Class 10 maths tutor usually follows the same shape, whether at home or online:
  </p>
  <ol>
    <li><strong>Five-minute recall.</strong> Two or three quick questions from earlier chapters, such as a trigonometric value, the sum formula for an AP or a tangent property. This keeps the whole syllabus warm.</li>
    <li><strong>Homework check with explanation.</strong> The student explains one answer aloud. If they cannot explain it, they do not yet own it.</li>
    <li><strong>New concept or question type.</strong> A short explanation, one worked example, then the student tries one immediately while the tutor watches the working.</li>
    <li><strong>Board-style practice.</strong> A mix of short answers, one long answer and, from October, a case-study question, marked the way the board marks.</li>
    <li><strong>Close.</strong> Homework set, next topic named, and a short note for the parent on what was covered and anything to watch.</li>
  </ol>
  <p>
    Online sessions work well for Class 10 maths provided the tutor can see the student's working. A writing tablet
    or a phone camera pointed at the notebook is essential; without it, the tutor can only check answers, not the
    steps that earn the marks.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m10-mistakes">Common mistakes that cost Class 10 maths marks</h2>
  <p>
    Most marks lost in Class 10 maths are not lost to hard questions. They are lost to habits that a tutor can spot
    and fix within weeks:
  </p>
  <ul>
    <li><strong>Skipping steps.</strong> Both boards award marks for method. A correct answer with no working may earn little; a small slip with clear working may lose only one mark.</li>
    <li><strong>No diagram.</strong> In heights and distances, coordinate geometry, circles and mensuration, a quick labelled sketch prevents most errors and often earns credit on its own.</li>
    <li><strong>Theorem proofs from memory, not understanding.</strong> Students who memorise the proof of the Basic Proportionality Theorem word for word collapse when the figure is labelled differently.</li>
    <li><strong>Sign and bracket errors in algebra.</strong> Especially when expanding, substituting into the quadratic formula or simplifying trigonometric identities.</li>
    <li><strong>Forgetting units and final statements.</strong> Areas in square units, volumes in cubic units, and a closing sentence answering the actual question in word problems.</li>
    <li><strong>Misreading case-study questions.</strong> Answering what the student expected to be asked rather than what was asked. Underlining the question is a simple fix.</li>
    <li><strong>Poor time management.</strong> Spending too long on one long answer and rushing the last section. Timed full papers from November solve this.</li>
    <li><strong>Leaving the paper unchecked.</strong> Keeping ten minutes at the end to recheck calculations is worth more than attempting one extra question.</li>
  </ul>
  </section>

