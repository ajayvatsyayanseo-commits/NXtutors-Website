  <h2 id="m10-why">Why Class 10 maths is the year to get right</h2>
  <p>
    Almost every Class 10 maths chapter is a continuation of something from Class 9 or earlier. Polynomials extend
    Class 9 algebra; coordinate geometry builds on plotting points; trigonometry leans on similar triangles and
    Pythagoras. That is why Class 10 students who struggle rarely have a Class 10 problem. They usually have an older
    gap that the new chapters expose.
  </p>
  <p>
    It is also why a one-to-one tutor helps so much in this year. In a class of forty, a teacher cannot stop to rebuild
    Class 8 factorisation for one student. A home tutor can, in two sessions, and the Class 10 chapter then makes sense.
    The other big gain is exam technique: board papers give marks for steps, and students who are taught to set out
    working the way examiners expect regularly gain marks they were losing without knowing it.
  </p>
  <p>
    Finally, the Class 10 result has consequences. For CBSE students the choice between Standard and Basic mathematics
    affects which maths course is open to them in Class 11, and in both CBSE and ICSE schools a strong maths score keeps
    the science stream, and later preparation for JEE, comfortably within reach.
  </p>
  </section>

