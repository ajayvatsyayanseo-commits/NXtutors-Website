  </table>
  </div>
  <p>
    Two things follow from this table. First, Algebra alone carries a quarter of the theory paper, and its four
    chapters feed into almost everything else, so a tutor should make sure algebra is secure early. Second, Geometry
    and Trigonometry together are worth 27 marks, and these are the chapters where proofs and diagrams trip students
    up most. A good tutor gives them time in proportion to their marks and their difficulty, not just their length.
  </p>
  <p>
    A quick word on each chapter group, and where students usually lose marks:
  </p>
  <ul>
    <li><strong>Real Numbers.</strong> The Fundamental Theorem of Arithmetic and irrationality proofs for numbers such as √2, √3 and √5. The proofs are short but must be written precisely, step by step.</li>
    <li><strong>Polynomials, Linear Equations and Quadratics.</strong> Zeros and their relationship with coefficients, solving pairs of equations graphically and by substitution or elimination, and quadratics by factorisation and the formula, including the discriminant. Word problems are where marks go missing.</li>
    <li><strong>Arithmetic Progressions.</strong> The nth term and the sum of n terms, and applying them to everyday situations. Students often confuse n with the nth term.</li>
    <li><strong>Coordinate Geometry.</strong> The distance formula and section formula. Easy marks if the student draws a rough diagram first.</li>
    <li><strong>Triangles and Circles.</strong> Similarity, the Basic Proportionality Theorem (with proof), and the two tangent theorems (with proof). Theorem proofs are regular board questions.</li>
    <li><strong>Trigonometry.</strong> Ratios, standard-angle values, identities built on sin²A + cos²A = 1, and heights and distances with angles of 30°, 45° and 60°. Identities reward practice more than any other topic.</li>
    <li><strong>Mensuration.</strong> Sectors and segments of circles, and surface areas and volumes of combined solids. The skill is visualising which surfaces are actually exposed.</li>
    <li><strong>Statistics and Probability.</strong> Mean, median and mode of grouped data, and classical probability. High-scoring if the student is careful with class intervals and arithmetic.</li>
  </ul>
