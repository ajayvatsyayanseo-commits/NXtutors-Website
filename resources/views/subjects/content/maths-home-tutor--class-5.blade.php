  <p>
    Grouped by strand, the year covers four big areas:
  </p>
  <ul>
    <li><strong>Numbers and operations.</strong> Large numbers, place value, the four operations and multi-step problems, spread across the travel and farm chapters.</li>
    <li><strong>Fractions.</strong> One chapter, but the single most important idea of the year for Class 6.</li>
    <li><strong>Shapes and space.</strong> Angles as turns, shapes and patterns, symmetry, the quilt chapter on area, and maps.</li>
    <li><strong>Measurement and data.</strong> Length, weight, capacity, time and pictorial data.</li>
  </ul>
  <p>
    The book expects children to talk, measure, fold and draw, not just fill in answers. Many "Let us do" style tasks
    make sense only if someone asks the child to explain their thinking. That is exactly where a tutor adds value:
    doing the activities properly, instead of skipping to the exercises.
  </p>
