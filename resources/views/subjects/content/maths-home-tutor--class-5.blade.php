  <section class="nx-guide__sec">
  <h2 id="m5-home">How parents can help with Class 5 maths at home</h2>
  <p>
    A tutor does the teaching, but the habits that make Class 5 maths easy are built at home, in minutes rather than
    hours. A few ideas that cost nothing:
  </p>
  <ul>
    <li><strong>Maths in the kitchen.</strong> Halving a recipe, measuring 750 ml of water, sharing a packet of biscuits equally. Fractions and capacity stop being abstract.</li>
    <li><strong>Maths on the road.</strong> Reading distances on signboards, estimating how long a 12 km drive will take, reading the car's clock in 24-hour time.</li>
    <li><strong>Money.</strong> Let your child check a shop bill or work out the change. Large numbers and decimals in rupees and paise feel real.</li>
    <li><strong>Talk, don't test.</strong> Ask "how did you work that out?" more often than "what's the answer?" It builds exactly the reasoning the new books want.</li>
    <li><strong>Stay positive.</strong> Children copy adult attitudes. "I was never good at maths either" gives permission to give up.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m5-signs">Signs your Class 5 child needs maths help</h2>
  <p>
    Not every low mark calls for a tutor. These signs, especially two or three together, suggest it is time:
  </p>
  <ul>
    <li><strong>Counting on fingers for basic facts.</strong> Still working out 7 × 8 or 13 − 6 slowly at ten years old.</li>
    <li><strong>Homework battles.</strong> Maths homework regularly ends in tears or takes far longer than it should.</li>
    <li><strong>Right method, wrong answer, every time.</strong> Careless errors that repeat usually mean a weak underlying skill, not carelessness.</li>
    <li><strong>Word problems left blank.</strong> The child can do the sum but cannot tell which sum to do.</li>
    <li><strong>"I'm bad at maths."</strong> A child who has started saying this needs a positive experience of success, quickly.</li>
    <li><strong>Teacher comments.</strong> Remarks about attention, speed or understanding in maths on the report card.</li>
    <li><strong>Moving to a new school or board.</strong> A switch between CBSE and ICSE, or a move from abroad, often leaves topic gaps.</li>
  </ul>
  <p>
    Equally, some parents look for a Class 5 tutor for a confident child who wants more challenge, such as puzzles,
    olympiad-style problems or getting ahead before middle school. A good tutor can do that too, as long as the stretch
    stays fun.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m5-choose">How to choose a maths tutor for a Class 5 child</h2>
  <p>
    At this age, how a tutor teaches matters more than how much maths they know. Any graduate can solve Class 5
    problems; far fewer can explain fractions to a nine- or ten-year-old in three different ways. Use the free demo
    class to check:
  </p>
  <ul>
    <li><strong>Does the tutor talk to your child, or at them?</strong> Good primary tutors ask lots of questions and let the child explain.</li>
    <li><strong>Do they use objects and drawings?</strong> Paper strips for fractions, a clock for time, a ruler for length. Concrete first, then symbols.</li>
    <li><strong>How do they react to a wrong answer?</strong> Look for curiosity ("show me how you got that"), not correction alone.</li>
    <li><strong>Have they looked at the textbook?</strong> They should know whether your child uses Maths Mela or an ICSE series, and ask to see the school notebook.</li>
    <li><strong>Can they spot the gap?</strong> By the end of the demo, a good tutor can tell you one or two specific things your child needs to work on.</li>
    <li><strong>Is your child comfortable?</strong> Ask your child afterwards. If they liked the session, half the battle is won.</li>
  </ul>
