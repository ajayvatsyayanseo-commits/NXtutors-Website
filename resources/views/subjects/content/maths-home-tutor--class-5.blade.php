  <h2 id="m5-mode">Home tuition or online for Class 5?</h2>
  <p>
    For most Class 5 children, home tuition is the easier start. Young children concentrate better with a person
    beside them, and hands-on activities like measuring, folding and using shapes work naturally at the table. The
    tutor can also see the child's notebook, posture and pencil grip at a glance.
  </p>
  <p>
    Online maths tuition for Class 5 can work well when:
  </p>
  <ul>
    <li><strong>The child is settled and focused</strong> and used to learning on a screen.</li>
    <li><strong>A parent is nearby</strong> for the first few sessions to help with the camera and materials.</li>
    <li><strong>Sessions are shorter,</strong> around 40 to 45 minutes, with lots of interaction.</li>
    <li><strong>The tutor uses a shared whiteboard</strong> and the child's notebook is visible on camera.</li>
  </ul>
