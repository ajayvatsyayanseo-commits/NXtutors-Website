  <h2 id="m5-year">What changes in Class 5 maths</h2>
  <p>
    Up to Class 4, most children can get by in maths with good memory and neat work. Class 5 asks for something more:
    understanding. A child now has to know why 3/4 is bigger than 2/3, not just that it is; how a turn of the body
    becomes an angle; why a long walk is better measured in kilometres than metres. Rules learnt by rote start to
    collide with each other, and the gaps show.
  </p>
  <p>
    It is also a year of independence. Homework is longer, children are expected to read word problems on their own,
    and many schools begin more formal tests. A ten-year-old who has always been "good at sums" can suddenly bring
    home a low mark on a test full of story questions, simply because the reading and the reasoning were new.
  </p>
  <p>
    The good news is that Class 5 is still a forgiving age. Gaps are small, habits are still forming, and children
    respond quickly to a patient adult who makes maths feel like a game they can win. Two sessions a week with the right
    tutor can change how a child feels about the subject for years.
  </p>
  </section>

