  <section class="nx-guide__sec">
  <h2 id="m5-icse">ICSE Class 5 maths: what to expect</h2>
  <p>
    There is no board examination at Class 5. CISCE sets a curriculum for the primary and middle years, and each ICSE
    school chooses its own textbook series to deliver it, so the chapter order and names vary from school to school.
    Ask your child's school for the syllabus sheet for the year; a tutor should always work from that.
  </p>
  <p>
    In general, ICSE Class 5 maths is more traditional in presentation and often more exercise-heavy than Maths Mela.
    Topics commonly covered include:
  </p>
  <ul>
    <li><strong>Number work.</strong> Large numbers, Roman numerals, the four operations with larger numbers, and order of operations in simple expressions.</li>
    <li><strong>Factors and multiples.</strong> Tests of divisibility, HCF and LCM, often introduced earlier than in CBSE schools.</li>
    <li><strong>Fractions and decimals.</strong> Operations on fractions, and decimals linked to money and measurement.</li>
    <li><strong>Everyday arithmetic.</strong> Unitary method, simple percentage and money problems in many series.</li>
    <li><strong>Geometry and measurement.</strong> Angles and their measurement, triangles, circles, perimeter and area, time and the calendar.</li>
    <li><strong>Data.</strong> Pictographs and bar graphs.</li>
  </ul>
  <p>
    The practical difference for parents is volume. ICSE workbooks tend to have long exercises, and children who work
    slowly can fall behind in homework even when they understand the idea. A tutor helps by teaching faster, cleaner
    methods and by choosing which questions really need doing.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m5-hard">Where Class 5 children usually get stuck</h2>
  <p>
    After years of teaching this age group, tutors see the same handful of trouble spots. Most are not about
    intelligence; they are about a missing step from Class 3 or 4.
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Place value with big numbers</h3>
      <p>Reading 4,05,060 aloud, or writing "three lakh seven thousand" in figures, exposes whether the child really understands zeros as place holders.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Tables and long division</h3>
      <p>If multiplication facts are slow, long division becomes a slog and errors multiply. This is the most common root cause of weak Class 5 marks.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Fractions as numbers</h3>
      <p>Children who think of a fraction only as "shaded parts" struggle to compare 3/5 and 2/3, or to place a fraction on a number line.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Units of measure</h3>
      <p>Mixing metres and kilometres, or grams and kilograms, in the same problem. The idea of converting before calculating has to be taught explicitly.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Word problems</h3>
      <p>Knowing how to multiply but not knowing when. Many children pick an operation by guessing from the numbers rather than reading the story.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Angles and turns</h3>
      <p>Confusing the size of an angle with the length of its arms, a misconception that follows children into Class 6 geometry if nobody corrects it.</p>
    </div>
  </div>
  </section>

