  <h2 id="m5GuideTitle">Maths home tutor for Class 5: building a confident last primary year</h2>

  <p class="nx-guide__lede">
    Class 5 is the last year of primary school, and it is the year in which maths quietly changes character. Numbers
    get bigger, fractions stop being pictures of pizza and start being numbers in their own right, and a child meets
    angles, area and data in a more formal way. Children who finish Class 5 comfortable with these ideas walk into
    Class 6 with confidence; children who finish it with shaky tables and a fear of fractions often spend the middle
    school years catching up. This guide explains what Class 5 maths covers in CBSE and ICSE schools, where children
    usually get stuck, how a tutor can help in short, playful sessions, and how to choose the right person.
  </p>

