  <h2 id="m5-week">A weekly tutoring plan for Class 5 maths</h2>
  <p>
    Ten-year-olds learn best in short, varied bursts. A session of 45 to 60 minutes, twice a week, suits most Class 5
    children. Here is how a good tutor might use a typical week:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Session</th><th scope="col">What happens</th><th scope="col">Time</th></tr>
    </thead>
    <tbody>
      <tr><td>Session 1, warm-up</td><td>Mental maths game: tables, doubling, halving, "how many tens in…"</td><td>10 min</td></tr>
      <tr><td>Session 1, main</td><td>The school's current chapter, taught with objects, drawings or measuring, then textbook questions</td><td>30 min</td></tr>
      <tr><td>Session 1, close</td><td>Two word problems read aloud together; homework set</td><td>10 min</td></tr>
      <tr><td>Session 2, warm-up</td><td>Quick recall of last session and one older topic</td><td>10 min</td></tr>
      <tr><td>Session 2, main</td><td>Gap-filling on a foundation skill (tables, division, fractions) plus school homework support</td><td>30 min</td></tr>
      <tr><td>Session 2, close</td><td>A puzzle or maths game the child enjoys; a short note to parents</td><td>10 min</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Between sessions, ten minutes a day of tables practice at home does more than an extra hour of tuition. A good
    tutor will give you a simple routine for this, not a stack of worksheets.
  </p>
  <p>
    Before school tests, the plan shifts: one session goes on revising the tested chapters and one on a short practice
    test, checked together so the child learns from each mistake.
  </p>
