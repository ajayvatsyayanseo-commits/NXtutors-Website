  <section class="nx-guide__sec">
  <h2 id="nh-ncert">What "NCERT first" looks like in a tutoring session</h2>
  <p>
    Almost every NEET teacher says "read NCERT". Our <a href="{{ url('/blog/-neet-biology-ncertfirst') }}">NCERT-first
    biology guide</a> explains the reading strategy. What a tutor adds is the checking, because students routinely
    overestimate how well they know a chapter they have read twice. In a session, NCERT-first tutoring means:
  </p>
  <ul>
    <li><strong>Closed-book recall.</strong> The tutor names a process, say the steps of a cycle or the parts of a structure, and the student writes or draws it without the book. Gaps show at once.</li>
    <li><strong>Line-level questions.</strong> Questions built from a single sentence, a table footnote or a figure caption in the NCERT chapter, since that is where fine distinctions hide.</li>
    <li><strong>Diagram labelling from memory.</strong> A blank figure, labelled and then checked against the book.</li>
    <li><strong>Only then, question banks.</strong> Once a chapter passes the recall check, timed MCQs on it, then mixed sets.</li>
    <li><strong>Physics and chemistry too.</strong> NCERT-first applies beyond biology: inorganic chemistry facts and the concepts behind physics formulas come from the NCERT text, even though physics numericals need more practice than the book's exercises provide.</li>
  </ul>
  <p>
    A tutor who only assigns reading and then moves on is not doing NCERT-first; the value is in testing what stuck.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="nh-cycles">Keeping 10 biology units alive: revision passes</h2>
  <p>
    Biology is 90 questions spread over ten units, and the problem in Class 12 is rarely learning a chapter for the
    first time. It is keeping Class 11 chapters fresh while new ones arrive. A tutor can hold the revision plan so it
    does not collapse in the busy months. One way to structure it:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>An example structure for biology revision passes</caption>
    <thead>
      <tr><th scope="col">Pass</th><th scope="col">When</th><th scope="col">What the student does</th><th scope="col">What the tutor checks</th></tr>
    </thead>
    <tbody>
      <tr><td>First reading</td><td>As the chapter is taught</td><td>Full NCERT reading, short notes on confusable points</td><td>Closed-book recall of the main processes and diagrams</td></tr>
      <tr><td>Second pass</td><td>A few weeks later</td><td>Re-read, then chapter MCQs under time</td><td>Which lines and figures were missed; error notes</td></tr>
      <tr><td>Mixed revision</td><td>Monthly, across units</td><td>Mixed-unit question sets</td><td>Whether older units are slipping</td></tr>
      <tr><td>Final passes</td><td>The last months before the exam</td><td>Fast NCERT re-reads and full mocks</td><td>Wrong answers traced back to the exact NCERT line</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The spacing matters more than the exact schedule. A chapter revisited three or four times across the year is held
    far better than one crammed twice in the final month, and a weekly recall check tells the student honestly which
    chapters need the next pass.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="nh-accuracy">Accuracy, negative marking and the attempt plan</h2>
  <p>
    Because every question carries the same +4 and −1, the arithmetic of guessing is simple: a wrong answer wipes out
    a quarter of a right one. The practical question is when a student should answer and when to leave a question.
    A tutor can make this concrete by tracking three numbers from every mock paper, for each subject:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>Numbers worth tracking after each NEET mock</caption>
    <thead>
      <tr><th scope="col">Measure</th><th scope="col">What it shows</th><th scope="col">What the tutor does with it</th></tr>
    </thead>
    <tbody>
      <tr><td>Wrong answers per subject</td><td>Where negative marking is draining the score</td><td>Targets the chapters behind them; sets a "leave it" rule for doubtful questions</td></tr>
      <tr><td>Questions left unanswered</td><td>Knowledge gaps or time running out</td><td>Distinguishes the two: reteach, or practise speed</td></tr>
      <tr><td>Time spent per section</td><td>Whether physics is eating biology's time</td><td>Adjusts the order of attempt and practises timed sections</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Over a few weeks, these numbers show whether the next month should go on content, speed or discipline in the exam
    hall. They also matter for the tie-break rules above, where a lower proportion of wrong answers counts.
  </p>
  </section>

