  <h2 id="nh-demo">How to judge a NEET tutor in the free demo</h2>
  <ol>
    <li><strong>Ask for a recall check.</strong> For a biology tutor, ask them to test the student on a chapter just read. A good tutor finds gaps within minutes.</li>
    <li><strong>Bring stuck physics questions.</strong> Watch whether the tutor asks what the student tried and guides, rather than solving on the board.</li>
    <li><strong>Ask about the pattern.</strong> How many questions, how long, and how negative marking should change the student's approach. The answer should be precise.</li>
    <li><strong>Ask how they use NCERT.</strong> "Read it again" is not an answer; line-level questioning and diagram checks are.</li>
    <li><strong>Ask about mocks.</strong> A tutor who plans to review mock papers question by question adds more than one who only teaches chapters.</li>
    <li><strong>Ask for a plan.</strong> Chapters for the next month, session frequency, and how progress will be measured.</li>
  </ol>
