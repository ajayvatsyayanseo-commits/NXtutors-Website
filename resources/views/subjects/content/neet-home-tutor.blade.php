  <section class="nx-guide__sec">
  <h2 id="nh-syllabus">The NMC syllabus in outline</h2>
  <p>
    The NMC's updated syllabus for NEET (UG) 2026 lists 20 units in physics (from physics and measurement through
    electronic devices, ending with experimental skills), 20 units in chemistry (split into physical, inorganic and
    organic chemistry, ending with principles of practical chemistry) and 10 units in biology:
  </p>
  <ol>
    <li>Diversity in Living World</li>
    <li>Structural Organisation in Animals and Plants</li>
    <li>Cell Structure and Function</li>
    <li>Plant Physiology</li>
    <li>Human Physiology</li>
    <li>Reproduction</li>
    <li>Genetics and Evolution</li>
    <li>Biology and Human Welfare</li>
    <li>Biotechnology and Its Applications</li>
    <li>Ecology and Environment</li>
  </ol>
  <p>
    The first five biology units follow the Class 11 NCERT book and the last five the Class 12 book. The physics
    experimental-skills unit lists specific practicals (vernier callipers, screw gauge, metre bridge, the p-n junction
    and Zener diode curves among them), so a tutor should teach those as exam content, not leave them to the school lab.
  </p>
  </section>

