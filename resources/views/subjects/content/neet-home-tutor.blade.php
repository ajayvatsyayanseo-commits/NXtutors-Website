  <h2 id="nhGuideTitle">NEET home tutor: planning biology, physics and chemistry as one exam</h2>

  <p class="nx-guide__lede">
    NEET (UG) looks simple on paper: one exam, one sitting, multiple-choice questions on three subjects. In practice,
    the three subjects pull in different directions. Biology is half the paper and rewards exact recall of the NCERT
    text; physics asks for numerical problem-solving at speed; chemistry needs a bit of both. A student can be strong in
    one and quietly losing the exam in another. This page is the exam-level view: what the National Testing Agency's
    bulletin and the National Medical Commission's syllabus actually say, how an NCERT-first tutor works in practice,
    why accuracy matters as much as coverage, how a home tutor fits with coaching, and how plans differ for Class 11,
    Class 12 and a repeat year.
  </p>

