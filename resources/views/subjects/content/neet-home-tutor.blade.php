  <h2 id="nh-exam">NEET (UG) as the NTA bulletin describes it</h2>
  <p>
    NEET (UG) is conducted by the NTA for admission to undergraduate medical courses; the syllabus is notified by the
    National Medical Commission. The figures below are from the NEET (UG) 2026 information bulletin, the latest
    published.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>NEET (UG) at a glance (2026 information bulletin)</caption>
    <thead>
      <tr><th scope="col">Item</th><th scope="col">What the bulletin says</th></tr>
    </thead>
    <tbody>
      <tr><td>Subjects and questions</td><td>Physics 45, Chemistry 45, Biology (Botany and Zoology) 90; all 180 questions compulsory</td></tr>
      <tr><td>Marks</td><td>720 in total</td></tr>
      <tr><td>Question type</td><td>Multiple choice, four options, one correct or most appropriate answer</td></tr>
      <tr><td>Marking</td><td>+4 for a correct answer, −1 for an incorrect one, 0 if unanswered</td></tr>
      <tr><td>Time</td><td>180 minutes</td></tr>
      <tr><td>Mode (2026)</td><td>Pen and paper, single day, single shift, as in 2025</td></tr>
      <tr><td>Language</td><td>English; Hindi as a bilingual booklet; or English plus a chosen regional language (13 languages in all)</td></tr>
      <tr><td>Age</td><td>At least 17 by 31 December of the exam year; no upper age limit</td></tr>
    </tbody>
  </table>
  </div>
  <p>Three things in the bulletin shape how a tutor should plan:</p>
  <ul>
    <li><strong>One minute a question.</strong> 180 questions in 180 minutes leaves no slack for a slow physics numerical unless biology is answered quickly.</li>
    <li><strong>Biology decides ties first.</strong> Equal scores are separated by Biology marks, then Chemistry, then Physics.</li>
    <li><strong>Wrong answers count twice.</strong> They cost a mark each, and if scores are still tied, the bulletin prefers the candidate with a lower proportion of incorrect to correct answers. Careless guessing hurts more than one mark suggests.</li>
  </ul>
  <p>
    Mode, pattern and dates are confirmed in each year's bulletin. Read the current one on neet.nta.nic.in before
    planning around any detail.
  </p>
