    </tbody>
  </table>
  </div>
  <p>Three details in these documents change how a tutor should plan, and they are often missed:</p>
  <ul>
    <li><strong>Mathematics breaks ties.</strong> The JEE (Main) bulletin resolves equal total scores by the NTA score in Mathematics first, then Physics, then Chemistry. Maths is not worth more marks, but it is the subject that settles close calls.</li>
    <li><strong>The numerical questions carry negative marks too.</strong> Section B answers are typed in as a number and rounded to the nearest integer, and a wrong entry costs a mark. Guessing a number is no longer free.</li>
    <li><strong>Getting to Advanced is a ranking, not a pass mark.</strong> For 2026, candidates had to be among the 2,50,000 highest-ranked successful candidates in Paper 1, across all categories. The Class XII eligibility rules and attempt limits are set in each year's brochure.</li>
  </ul>
  <p>
    Every rule above is set afresh each year. Before planning around a date or a detail, read the current information
    bulletin on jeemain.nta.nic.in and the current brochure on jeeadv.ac.in.
  </p>
