  <h2 id="jh-demo">How to judge a JEE tutor in the free demo</h2>
  <p>
    A JEE demo should not be a general chat or a polished lecture on an easy topic. Ask the student to bring three
    questions from their own coaching sheet or last test that they could not solve, and watch what happens.
  </p>
  <ol>
    <li><strong>Does the tutor ask what the student tried first?</strong> A good JEE tutor diagnoses the stuck point before explaining.</li>
    <li><strong>Does the student end up doing the solving?</strong> Hints and questions, not a finished solution on the board.</li>
    <li><strong>Can the tutor show a faster route?</strong> In JEE, the second, shorter method matters as much as the first correct one.</li>
    <li><strong>Do they know the current pattern?</strong> Ask how negative marking in the numerical section should change a student's approach. The answer should be specific.</li>
    <li><strong>Do they talk about tests?</strong> A tutor who plans to review the student's mock papers is worth more than one who only teaches chapters.</li>
    <li><strong>Can they fit the board in?</strong> Ask how they would handle the weeks before pre-boards.</li>
    <li><strong>Do they propose a plan?</strong> Which chapters in the next month, and how progress will be measured.</li>
  </ol>
