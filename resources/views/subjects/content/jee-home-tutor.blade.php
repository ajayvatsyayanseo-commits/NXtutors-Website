  <h3>Class 11: the year that decides the rest</h3>
  <p>
    Much of each JEE syllabus is Class 11 content, and Class 12 physics and maths lean on it throughout. The
    common trap is to treat Class 11 as a warm-up and discover in Class 12 that vectors, rotational motion or basic
    calculus were never secure. A tutor in Class 11 should test fundamentals regularly, keep an error log from the
    first month, and make sure the student can solve standard problems without looking at worked examples. See our
    <a href="{{ url('/maths-home-tutor/class-11') }}">Class 11 maths</a>, <a href="{{ url('/physics-home-tutor/class-11') }}">Class 11 physics</a>
