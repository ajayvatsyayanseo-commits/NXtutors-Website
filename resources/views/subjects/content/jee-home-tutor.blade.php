  <h2 id="jh-exams">JEE Main and JEE Advanced, as the official documents describe them</h2>
  <p>
    "JEE" is really two exams run by two different bodies. JEE (Main) is conducted by the NTA. Its Paper 1 is used for
    B.E. and B.Tech. admission to the NITs, IIITs, other centrally funded technical institutions and participating
    state institutions, and it is also the eligibility test for JEE (Advanced). JEE (Advanced) is conducted by the IITs
    for admission to their undergraduate programmes. The table below uses the 2026 documents, the latest published.
  </p>
