  <h2 id="jh-syllabus">What the JEE Main syllabus covers</h2>
  <p>
    The NTA's JEE (Main) 2026 syllabus lists 14 units in mathematics (from sets, relations and functions through
    calculus, coordinate and three-dimensional geometry, vectors, statistics and probability, and trigonometry), 20
    units in physics (from units and measurement to electronic devices, with a final unit on experimental skills) and 20
    units in chemistry (physical, inorganic and organic, ending with principles of practical chemistry). The units span
    both school years: in physics, for instance, the first ten are Class 11 topics and the next nine Class 12.
  </p>
  <p>
    The syllabus sits close to the NCERT books but it is not the school board syllabus. Some topics that a board
    trims or examines lightly are still listed for JEE, and the experimental-skills units expect a student to know
    standard practicals well enough to answer questions on them. A tutor should work from the NTA syllabus document
    itself, not from the school's chapter list, and flag the gaps early in Class 11.
  </p>
  <p>
    For Advanced, the brochure publishes its own syllabus annexure. It overlaps heavily with JEE Main, but the depth
    of questioning is what differs: problems that chain several ideas, and marking rules that change from section to
    section.
  </p>
  </section>

