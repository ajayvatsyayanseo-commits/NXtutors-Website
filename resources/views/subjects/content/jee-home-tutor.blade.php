  <p>
    The tutor-only route suits students who cannot fit coaching hours, who learn much faster or slower than a batch,
    or who are in a school timetable that clashes. It needs more discipline from the family, because nobody else is
    setting the pace. The hybrid route suits students who are in coaching but not converting it into test scores. A
    tutor who simply re-teaches coaching lectures adds little in either case; the value is in the student's own
    unsolved problems and mistakes.
  </p>
