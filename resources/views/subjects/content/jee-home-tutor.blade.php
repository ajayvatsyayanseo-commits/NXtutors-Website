  <h2 id="jh-one-or-three">One tutor for all three subjects, or a specialist for each?</h2>
  <p>
    Parents often ask for "a JEE tutor", meaning one person for everything. For Class 11 foundations, and for
    JEE Main-level work, some tutors can genuinely teach all three subjects, or at least maths and physics together.
    For JEE Advanced-level problem-solving, one person with real depth in all three is rare, and most students
    are better served by a specialist in the subject that is holding them back.
  </p>
