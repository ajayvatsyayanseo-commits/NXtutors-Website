  <h3>Class 12: syllabus, tests and the board</h3>
  <p>
    Class 12 has three demands in one year: new chapters, the first JEE Main session, and the school board. The tutor's
    job is to protect time for Class 11 revision (which students drop first), move to full-length timed papers well
    before the January session, and switch to board-style written answers in the weeks before pre-boards. The
    <a href="{{ url('/maths-home-tutor/class-12') }}">Class 12 maths</a>, <a href="{{ url('/physics-home-tutor/class-12') }}">Class 12 physics</a>
