      <tr><td>Questions</td><td>Per subject: 20 multiple-choice (Section A) and 5 numerical-value (Section B); 75 questions, 300 marks</td><td>Designed to test comprehension, reasoning and analytical ability; question types and marking are given in the paper's instructions</td></tr>
