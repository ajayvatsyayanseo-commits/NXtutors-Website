      <div class="nx-guide__card">
  <h3>A repeat year: diagnose first</h3>
  <p>
    Under the 2026 bulletin, JEE (Main) has no age limit and accepts students who passed Class XII in the two previous
    years, so a repeat year is possible for Main. JEE (Advanced) is tighter: the 2026 brochure allows at most two
    attempts in two consecutive years, tied to the year the student first appeared for Class XII. Check the current
    rules before deciding. In the year itself, start with a diagnosis of last year's test papers, then rebuild
    the chapters that cost the most marks, and take many full-length papers. Motivation dips mid-year; a fixed weekly
    tutor session helps keep the routine.
