  <p>
    Chemistry is often the subject that gives the fastest return per hour, because inorganic and much of organic
    reward regular revision rather than insight. Physics is usually the slowest to move, because the gap is in how the
    student approaches a problem, which takes weeks to change. Maths sits in between but punishes lost practice quickly:
    two weeks without timed problem-solving shows up in the next test. A good plan puts tutor time where the gap is,
    not in equal thirds.
  </p>
