  <section class="nx-guide__sec">
  <h2 id="ign-signs">Signs it is time to find an IGCSE maths tutor</h2>
  <p>
    Not every IGCSE student needs a tutor. These are the situations where one usually makes a clear difference:
  </p>
  <ul>
    <li><strong>A board or school change.</strong> Joining a Cambridge or Edexcel school from CBSE or ICSE, or moving between Cambridge and Edexcel, leaves gaps in topics and question style.</li>
    <li><strong>A tier decision is coming.</strong> A student in a Core or Foundation set who wants to move up has a limited window to show it in school tests.</li>
    <li><strong>Additional Maths on top of 0580.</strong> Two maths IGCSEs in parallel is a heavy load, and the 0606 pace can leave 0580 revision behind.</li>
    <li><strong>Test scores that do not match classwork.</strong> A student who understands in class but scores poorly under time usually has an exam-technique problem, not a knowledge problem.</li>
    <li><strong>A clear plan for Grade 11.</strong> Students heading for IB Higher Level maths or A Level maths benefit from stronger algebra and functions before they arrive.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ign-past">Past-paper strategy after the 2025 changes</h2>
  <p>
    Past papers are the most useful practice material for IGCSE maths, but the 2025 change to Cambridge 0580 means the
    old routine needs adjusting. Before 2025, Cambridge candidates did not sit a dedicated non-calculator paper, so older
    papers do not give practice in the conditions of today's Paper 1 or Paper 2.
  </p>
  <p>
    This is how I would build a past-paper plan for a Cambridge student now:
  </p>
  <ol>
    <li><strong>Start with the specimen papers.</strong> Cambridge published specimen papers for first assessment in 2025, including the non-calculator Paper 1 and Paper 2. They show the new style clearly.</li>
    <li><strong>Use real papers from 2025 onwards as the core bank.</strong> These match the current structure exactly. Save the most recent ones for the final weeks.</li>
    <li><strong>Use older papers by topic, not as full papers.</strong> They are still excellent practice, but pick questions carefully: skip removed topics, and do not treat an old calculator-allowed paper as practice for the non-calculator paper.</li>
    <li><strong>Practise non-calculator questions without a calculator,</strong> even when they come from an older paper where one was allowed. Many of them work well by hand.</li>
    <li><strong>Mark strictly with the mark scheme.</strong> Method marks, accuracy marks and independent marks tell the student exactly where credit is earned and lost.</li>
    <li><strong>Log every lost mark and redo it a week later.</strong> The redo, without the solution in sight, is where most of the learning happens.</li>
  </ol>
  <p>
    For Edexcel 4MA1 students, the picture is simpler: both papers at each tier allow a calculator, and the two-paper,
    two-hour format has been in place since first examination in 2018. Pearson publishes past papers, mark schemes and examiner reports. Remember that Higher papers
    before the code change are labelled 3H and 4H. With both boards, full papers should be sat in real time, with the
    right tier, and in the right calculator conditions. An untimed, open-book paper is revision, not a mock.
  </p>
  </section>

