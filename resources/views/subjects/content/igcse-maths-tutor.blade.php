  <h2 id="ign-next">After IGCSE: the jump to IB, A Level, ISC or CBSE Class 11</h2>
  <p>
    The step from Grade 10 to Grade 11 is the biggest in school maths, whichever route follows. Knowing the route early
    changes how IGCSE should be taught.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>IB Diploma</h3>
  <p>
    Students choose Mathematics: Analysis and Approaches or Mathematics: Applications and Interpretation, each at
    Standard or Higher Level. Analysis and Approaches, especially at Higher Level, leans hard on the algebra, functions
    and trigonometry from Extended 0580, and 0606 helps a great deal. See our
    <a href="{{ url('/ib-maths-tutor') }}">IB maths tutor</a> page.
  </p>
      </div>
      <div class="nx-guide__card">
