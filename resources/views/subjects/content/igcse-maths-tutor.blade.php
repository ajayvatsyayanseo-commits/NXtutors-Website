  <section class="nx-guide__sec">
  <h2 id="ign-0580">Cambridge IGCSE Mathematics 0580: the current papers</h2>
  <p>
    The 0580 syllabus in use now covers exams in 2025, 2026 and 2027. The next syllabus, for exams in 2028, 2029 and
    2030, has already been published, and Cambridge states there are no significant changes that affect teaching. So a
    student starting Grade 9 today is preparing for the same paper pattern either way.
  </p>
  <p>
    Every candidate sits two papers. From the 2025 exams onwards, one paper at each tier is taken without a calculator.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>Cambridge IGCSE Mathematics 0580 papers, exams 2025 to 2030</caption>
    <thead>
      <tr><th scope="col">Tier</th><th scope="col">Paper</th><th scope="col">Calculator</th><th scope="col">Time</th><th scope="col">Marks</th><th scope="col">Weighting</th></tr>
    </thead>
    <tbody>
      <tr><td>Core</td><td>Paper 1</td><td>Not allowed</td><td>1 hour 30 minutes</td><td>80</td><td>50%</td></tr>
      <tr><td>Core</td><td>Paper 3</td><td>Scientific calculator required</td><td>1 hour 30 minutes</td><td>80</td><td>50%</td></tr>
      <tr><td>Extended</td><td>Paper 2</td><td>Not allowed</td><td>2 hours</td><td>100</td><td>50%</td></tr>
      <tr><td>Extended</td><td>Paper 4</td><td>Scientific calculator required</td><td>2 hours</td><td>100</td><td>50%</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Three features of this structure matter for tuition:
  </p>
  <ul>
    <li><strong>The two papers are balanced.</strong> Cambridge made the two papers at each tier equal in length, marks, weighting and style. The non-calculator paper is not a short warm-up; it is half the grade.</li>
    <li><strong>A formula list is printed on page 2 of each paper,</strong> but not every formula is given. The syllabus notes say which ones students must know. Students need practice in picking the right formula from the list, not just recalling it.</li>
    <li><strong>The Extended content contains all of the Core content.</strong> An Extended student can still lose marks on Core-level questions, and often does, through rushing.</li>
  </ul>
  <p>
    The syllabus has nine topic areas: number; algebra and graphs; coordinate geometry; geometry; mensuration;
    trigonometry; transformations and vectors; probability; and statistics. Cambridge designs the course around roughly
    130 guided learning hours, spread across two school years in most Indian schools.
  </p>
  <p>
    For the 2025 syllabus, Cambridge added surds, exact trigonometric values and domain and range to the Extended content,
    and removed topics such as linear programming and box-and-whisker plots. No new content was added at Core. Older
    textbooks and pre-2025 past papers are still useful, but students should skip the questions on removed topics.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ign-grades">A* to G or 9 to 1: which grade scale applies?</h2>
  <p>
    Cambridge runs the same mathematics on two grade scales, under two syllabus codes. Parents are often unsure which
    one appears on the certificate, so it is worth checking.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>0580: A* to G</h3>
  <p>
    Core candidates are eligible for grades C to G. Extended candidates are eligible for A* to E. The 0580 syllabus can
    be taken in the June and November series, and schools in India can also enter candidates in March. This is the
    version most Cambridge schools in India use.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>0980: 9 to 1</h3>
  <p>
    The (9–1) syllabus reports grades 9 (highest) to 1. Core candidates are eligible for grades 5 to 1 and Extended
    candidates for 9 to 3. It runs in June and November only, and Cambridge notes that it is not available in every
    administrative zone, so ask the school before assuming it applies.
  </p>
      </div>
    </div>
  <p>
    Cambridge also says that once the entries deadline has passed, a candidate cannot switch between the two grading
    scales. For tutoring, the scale makes little difference: the papers follow the same pattern and the preparation is
    the same. What matters is the tier.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ign-tier">Core or Extended (Foundation or Higher): how to decide</h2>
  <p>
    The tier sets the ceiling. On 0580, a Core candidate cannot score above a C. On Edexcel 4MA1, a Foundation candidate
    cannot score above a 5. Cambridge's own guidance is that candidates aiming for grades A* to C should study the
    Extended content, and those expected to achieve a D or below should be entered for Core.
  </p>
  <p>
    Schools normally make the final entry in Grade 10, usually after mock exams. The decision is often shaped much
    earlier, by which teaching set the student is placed in during Grade 9. These questions help families think it
    through:
  </p>
  <ol>
    <li><strong>What comes after Grade 10?</strong> IB Diploma maths at any level, A Level maths, a science stream, or economics with a quantitative element all point firmly to Extended or Higher.</li>
    <li><strong>How secure is the algebra?</strong> Extended papers are longer, less guided and more algebraic. A student who can factorise, rearrange formulae and solve simultaneous equations reliably by the end of Grade 9 is usually ready.</li>
    <li><strong>How is the non-calculator work?</strong> Extended Paper 2 lasts two hours without a calculator and includes surds, indices and exact trigonometric values. Weak arithmetic is fixable, but it takes a term or more.</li>
    <li><strong>What do the mock results actually show?</strong> Look at which questions were lost, not just the total. Lost marks on Extended-only topics are a different problem from lost marks on basics.</li>
  </ol>
  <p>
    If a student is in a Core set but wants Extended, raise it with the school early in Grade 9 or at the start of
    Grade 10. Moving up means learning the Extended-only content and adjusting to longer questions, and that is months of
    steady work. Moving down late is also costly in a different way, because it caps the grade. Our
    <a href="{{ url('/blog') }}">blog</a> has more on tier choices.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ign-0606">Cambridge IGCSE Additional Mathematics 0606</h2>
  <p>
    Additional Mathematics is a separate IGCSE, usually taken alongside 0580 by strong students. Cambridge describes it
    as a syllabus that stretches more able candidates and gives a smooth transition to AS and A Level Mathematics. It has
    no tiers: all candidates take the same two papers, and grades A* to E are available. There are no F or G grades, so a
    candidate below the E threshold is unclassified.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>Cambridge IGCSE Additional Mathematics 0606 papers</caption>
    <thead>
      <tr><th scope="col">Paper</th><th scope="col">Calculator</th><th scope="col">Time</th><th scope="col">Marks</th><th scope="col">Weighting</th></tr>
    </thead>
    <tbody>
      <tr><td>Paper 1</td><td>Not allowed</td><td>2 hours</td><td>80</td><td>50%</td></tr>
      <tr><td>Paper 2</td><td>Scientific calculator required</td><td>2 hours</td><td>80</td><td>50%</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The syllabus covers fourteen topics: functions; quadratic functions; factors of polynomials; equations,
    inequalities and graphs; simultaneous equations; logarithmic and exponential functions; straight-line graphs;
    coordinate geometry of the circle; circular measure; trigonometry; permutations and combinations; series; vectors in
    two dimensions; and calculus. For exams from 2025, indices and surds became assumed knowledge rather than a topic of
    their own, the geometry of the circle was added, and Paper 1 became a non-calculator paper. The syllabus for
    2028 to 2030 is already published and, according to Cambridge, has no significant changes that affect teaching.
  </p>
  <p>
    Two points for families. First, because surds and indices are assumed, a student with shaky 0580 Extended algebra
    will struggle with 0606 from the first week. Second, the calculus and logarithms in 0606 give a real head start in
    IB Maths Analysis and Approaches or A Level maths. A tutor who teaches both 0580 and 0606 can sequence them so they
    support each other rather than compete for time.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ign-edexcel">Pearson Edexcel International GCSE Mathematics A (4MA1)</h2>
  <p>
    Some schools in India follow Pearson Edexcel rather than Cambridge. The maths course is International GCSE
    Mathematics (Specification A), code 4MA1. It is a linear qualification: both papers are taken in the same series at
    the end of the course.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>Pearson Edexcel International GCSE Mathematics A (4MA1) papers</caption>
    <thead>
      <tr><th scope="col">Tier</th><th scope="col">Papers</th><th scope="col">Time each</th><th scope="col">Marks each</th><th scope="col">Weighting each</th><th scope="col">Grades</th></tr>
    </thead>
    <tbody>
      <tr><td>Foundation</td><td>1F and 2F</td><td>2 hours</td><td>100</td><td>50%</td><td>5 to 1</td></tr>
      <tr><td>Higher</td><td>1H and 2H</td><td>2 hours</td><td>100</td><td>50%</td><td>9 to 4 (grade 3 allowed)</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The key difference from Cambridge: a calculator may be used on both 4MA1 papers. There is no non-calculator paper,
    so the time a Cambridge tutor spends on mental and written arithmetic can go instead into problem solving and
    longer multi-step questions. A formulae sheet is included for each tier. Higher tier questions assume knowledge of
    the Foundation content.
  </p>
  <p>
    Older Higher tier papers were coded 3H and 4H; Pearson renamed them 1H and 2H. If you download past papers, both
    codes refer to the same tier. For very strong students, Pearson's International GCSE Further Pure Mathematics (4PM1)
    plays a similar role to Cambridge 0606.
  </p>
  <p>
    Students who switch between Edexcel and Cambridge, often after a school change, need a short audit. Topics overlap
    heavily, but question style, paper length and calculator rules differ, and a Cambridge student will have to rebuild
    non-calculator skills quickly.
  </p>
  </section>

