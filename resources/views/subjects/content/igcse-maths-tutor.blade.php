  <h2 id="ign-marks">Where IGCSE maths marks are usually lost</h2>
  <p>
    Most students who fall short of their target grade in IGCSE maths do not lack ability. They lose marks in a small
    number of predictable places, and each has a practical fix.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>Common causes of lost marks, and what a tutor does about them</caption>
    <thead>
      <tr><th scope="col">Problem</th><th scope="col">How it shows up</th><th scope="col">The fix</th></tr>
