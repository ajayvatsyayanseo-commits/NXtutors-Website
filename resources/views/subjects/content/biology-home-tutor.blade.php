  <h2 id="bio-mode">Home or online biology tuition?</h2>
  <p>
    Biology works well online for most senior students: diagrams can be drawn on a tablet or shown to a camera, and
    past-paper and mock analysis suit a shared screen. Home tuition suits students who drift on a screen, younger
    students, and families who want the tutor to see practical records and project work on paper. For NEET and IB,
    where specialists are fewer, online widens the choice considerably. Many families use a hybrid: one home session a
    week, with online sessions for tests and doubt-clearing.
  </p>
