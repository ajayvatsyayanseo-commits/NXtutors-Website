  <h2 id="bio-why">Why biology needs its own kind of tutoring</h2>
  <p>
    Physics and chemistry marks are lost mostly in method and calculation. Biology marks are lost in different places,
    and a tutor needs to know where:
  </p>
  <ul>
    <li><strong>Precise language.</strong> Examiners look for specific terms. "The cell gets bigger" and "the cell increases in volume by osmosis" are not worth the same marks, and a student who understands the idea but writes loosely loses marks on every paper.</li>
    <li><strong>Diagrams.</strong> Labelled diagrams of a flower, a nephron or a heart are asked for directly, and drawing one well is also the fastest way to learn the structure.</li>
    <li><strong>Processes in sequence.</strong> Photosynthesis, respiration, protein synthesis, the menstrual cycle and the nerve impulse all have steps that must come in the right order with the right cause and effect.</li>
    <li><strong>Data and experiments.</strong> Every board now asks students to read a graph, interpret an experiment, identify variables or suggest an improvement. Students who only read the textbook find these questions hardest.</li>
    <li><strong>Volume.</strong> Senior biology has a lot of content. Without a revision system, a student who understood a chapter in July cannot recall it in February.</li>
  </ul>
  </section>

