  <section class="nx-guide__sec">
  <h2 id="bio-ib">IB Diploma biology</h2>
  <p>
    The IB Biology course first assessed in 2025 is organised around four themes, unity and diversity, form and
    function, interaction and interdependence, and continuity and change, each studied across levels of organisation
    from molecules to ecosystems. The recommended teaching time is 150 hours at SL and 240 at HL. Exam papers make up
    80% of the grade and the scientific investigation, an individual piece of research, the other 20%.
  </p>
  <p>
    Because the course is built on themes rather than separate chapters, IB students are expected to connect ideas: to
    use what they know about cell membranes when answering about nerve impulses, or about evolution when discussing
    classification. A tutor helps by making those links explicit and by practising data-based questions. For the
    investigation, a tutor may discuss the research question and challenge the method, but the work must be the
    student's own. Our <a href="{{ url('/blog/ib-igcse-tutoring-gurgaon-parents-guide') }}">parents' guide to IB and
    IGCSE tutoring</a> explains what support is appropriate.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="bio-method">How good biology tutors teach it</h2>
  <p>
    Across boards, the tutors who get results in biology tend to share a few habits:
  </p>
  <ol>
    <li><strong>Explain, then draw, then recall.</strong> A new process is explained, the student draws and labels it, and at the next session redraws it from memory before anything new is taught.</li>
    <li><strong>Active recall instead of rereading.</strong> Short oral quizzes, blank diagrams and flashcards the student writes in their own words. Rereading notes feels productive and rarely is.</li>
    <li><strong>Spaced revision.</strong> Each chapter comes back after a week, a month and again before exams, so Class 11 content is still there for Class 12 and for NEET.</li>
    <li><strong>Command words.</strong> "State", "describe", "explain" and "suggest" ask for different answers. Students who learn the difference gain marks on every board.</li>
    <li><strong>Data practice.</strong> Graphs, tables and experimental set-ups in most sessions from Class 9 onwards, because application questions are where the gap between students is widest.</li>
    <li><strong>Marking like an examiner.</strong> Answers checked against the mark scheme or marking scheme, point by point, so the student sees exactly which phrase earned or lost the mark.</li>
  </ol>
  </section>

  <section class="nx-guide__sec">
  <h2 id="bio-signs">Signs your child could use a biology tutor</h2>
  <ul>
    <li><strong>Knows it, cannot write it.</strong> Your child can explain a process out loud but the written answer loses marks for vague wording or missing steps.</li>
    <li><strong>Diagrams avoided or copied.</strong> Labels in the wrong place, or diagrams left out of answers that ask for them.</li>
    <li><strong>Data questions left blank.</strong> Graph, table and experiment questions skipped or answered from general knowledge instead of from the data given.</li>
    <li><strong>Everything forgotten by the exam.</strong> Good chapter tests but a weak half-yearly or mock, which usually means there is no revision system.</li>
    <li><strong>Genetics trouble.</strong> Crosses, pedigrees and probability in inheritance are a common sticking point in Classes 10 and 12, and often the reason biology marks dip.</li>
    <li><strong>A new course.</strong> The move from Class 10 science to Class 11 biology, from ICSE to ISC, or from IGCSE to the IB, is where a few months of one-to-one help does the most good.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="bio-year">A two-year plan for Classes 11 and 12</h2>
  <p>
    Senior biology spans two years of content, and Class 11 chapters return in Class 12 board revision and in NEET.
    A workable rhythm with a tutor, to adjust to your school's calendar:
  </p>
  <ol>
    <li><strong>Class 11, through the year:</strong> keep pace with school, make short notes and diagram sheets for each chapter, and revise every chapter again a month after finishing it.</li>
    <li><strong>Class 11, end of year:</strong> a full revision of Human Physiology and Cell, which carry heavy weight and underpin Class 12 topics.</li>
    <li><strong>Class 12, first half:</strong> Genetics and Evolution early and thoroughly, with inheritance problems every week; practical record and project kept current.</li>
    <li><strong>Class 12, second half:</strong> full papers under time, answer-writing against the marking scheme, and one cycle of Class 11 revision for students also sitting NEET.</li>
  </ol>
  </section>

