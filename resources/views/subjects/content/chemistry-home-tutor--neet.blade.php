  <h2 id="cn-coaching">How a home tutor works alongside coaching</h2>
  <p>
    Most NEET aspirants already attend a coaching programme. A home tutor does not replace it and should not repeat
    it. The useful roles are:
  </p>
  <ul>
    <li><strong>Doubt clearing.</strong> Coaching classes move on whether or not a student understood. A weekly session to work through saved doubts stops gaps from piling up.</li>
    <li><strong>Catch-up.</strong> After an illness or a module that did not land, a tutor can rebuild the chapter quickly and one-to-one.</li>
    <li><strong>Test analysis.</strong> Going through coaching test papers mistake by mistake, and setting targeted practice from them.</li>
    <li><strong>Board balance.</strong> For Class 12 students, making sure CBSE-specific requirements such as practicals and descriptive answers are not neglected. Our <a href="{{ url('/chemistry-home-tutor/class-12') }}">Class 12 chemistry guide</a> covers the board side.</li>
  </ul>
  <p>
    The tutor should follow the coaching sequence and see the coaching material, so that the student is not taught
    two different methods for the same problem.
