  <section class="nx-guide__sec">
  <h2 id="cn-mcq">MCQ strategy and negative marking</h2>
  <p>
    Knowing chemistry and scoring in NEET chemistry are not the same thing. A tutor should teach the format
    explicitly:
  </p>
  <ul>
    <li><strong>Attempt chemistry in a planned order.</strong> Many students do quick recall questions first, then organic, then numericals, so easy marks are banked early. The order matters less than having one and practising it.</li>
    <li><strong>Eliminate before choosing.</strong> In statement-based and "which is incorrect" questions, crossing out options one by one prevents the most common slip, which is answering the opposite of what was asked.</li>
    <li><strong>Think about guessing.</strong> With +4 for a right answer and −1 for a wrong one, a blind guess is a poor bet, but a guess between two remaining options is usually worth taking. Students should decide this rule before the exam, not in the hall.</li>
    <li><strong>Analyse every test.</strong> After each mock, sort mistakes into "did not know", "knew but slipped" and "ran out of time". Each needs a different fix, and a tutor is well placed to do this analysis with the student.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="cn-traps">Common NEET chemistry traps</h2>
  <p>
    Across mock tests, the same errors cost NEET students chemistry marks again and again. Most can be fixed in a few
    weeks once they are named:
  </p>
  <ul>
    <li><strong>Reading "incorrect" as "correct".</strong> Statement questions often ask which option is wrong. Circling the key word before reading the options stops this.</li>
    <li><strong>Unit slips in numericals.</strong> Millilitres left unconverted, kJ and J mixed, or the wrong gas constant chosen. The distractor options are often built from exactly these slips.</li>
    <li><strong>Half-remembered exceptions.</strong> Knowing that there is an exception to a trend but not which way it goes. Exceptions need to be learned with their reason.</li>
    <li><strong>Over-thinking inorganic.</strong> Reasoning past what NCERT actually says. When the textbook states a fact, that is usually the answer NEET is looking for.</li>
    <li><strong>Spending too long on one question.</strong> A stubborn numerical should be marked and left, not fought for four minutes.</li>
    <li><strong>Neglecting practical chemistry.</strong> Salt analysis, functional-group tests and titration questions are straightforward marks that under-prepared students give away.</li>
  </ul>
  </section>

