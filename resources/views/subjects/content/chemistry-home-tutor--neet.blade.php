  <section class="nx-guide__sec">
  <h2 id="cn-inorganic">Inorganic chemistry: NCERT, line by line</h2>
  <p>
    NEET inorganic questions track the NCERT textbooks very closely, often down to a single sentence, a table of
    values or an exception mentioned in passing. The approach that works is disciplined rather than clever:
  </p>
  <ul>
    <li><strong>Read NCERT actively, not once.</strong> A tutor reads each inorganic chapter with the student, underlining facts that make good questions: oxidation states, colours, exceptions to trends, structures of oxoacids and interhalogens.</li>
    <li><strong>Turn tables into quizzes.</strong> Ionisation enthalpies, electronic configurations of transition metals, colours of ions and magnetic moments are learned faster as rapid-fire questions than by re-reading.</li>
    <li><strong>Explain the trend, then learn the exception.</strong> Why the inert pair effect makes lower oxidation states more stable down group 13 and 14; why lanthanoid contraction makes zirconium and hafnium so alike. Understood exceptions are remembered.</li>
    <li><strong>Revise on a cycle.</strong> Inorganic fades fastest of the three branches. A short inorganic quiz in every session, covering a different chapter each time, keeps it all current.</li>
  </ul>
  <p>
    Coordination compounds sit between inorganic and physical chemistry: nomenclature, isomerism, valence bond and
    crystal field theory, and magnetic moments. It rewards students who are fluent with Class 11 hybridisation.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="cn-organic">Organic chemistry: mechanisms before memory</h2>
  <p>
    NEET organic questions are rarely "what is the product of this named reaction" alone. They combine steps, ask
    which reagent achieves a conversion, compare acidity or basicity, or test reaction intermediates. Students who
    memorised reactions without the reasoning struggle with this format.
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
  <h3>General organic chemistry first</h3>
  <p>
    Inductive effect, resonance, hyperconjugation, and the stability of carbocations, carbanions and radicals. These
    explain acidity of phenols and carboxylic acids, basicity of amines and the direction of most reactions. A tutor
    should revisit them until the student can rank any set of intermediates in seconds.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>Reactions as families</h3>
  <p>
    Nucleophilic substitution, elimination, electrophilic addition and substitution, and nucleophilic addition to
    carbonyls. Named reactions then slot into these families rather than standing alone, which makes them far easier
    to recall under time pressure.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>Reagent recognition</h3>
  <p>
    Many NEET questions hinge on knowing exactly what a reagent does: which reduces a carbonyl fully, which stops at
    an aldehyde, which gives anti-Markovnikov addition. A reagent sheet, built and quizzed regularly, is one of the
    most useful things a tutor can make with a student.
  </p>
    </div>
  </div>
  <p>
    Isomerism, IUPAC nomenclature and biomolecules are reliable questions that are mostly recall; they should be
    revised with the inorganic cycle rather than left to the last month.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="cn-physical">Physical chemistry: fast, accurate numericals</h2>
  <p>
    NEET physical chemistry numericals are usually short, one or two steps, but they must be solved without a
    calculator and quickly. The skills a tutor should build:
  </p>
  <ul>
    <li><strong>Mole concept fluency.</strong> Stoichiometry, limiting reagent, molarity and molality conversions without hesitation. This underpins solutions, equilibrium and electrochemistry.</li>
    <li><strong>Mental arithmetic and approximation.</strong> Handling powers of ten, logarithms of common numbers and rough division so that the right option can be picked without full working.</li>
    <li><strong>Formula selection.</strong> Knowing instantly which relation applies: first-order half-life, the Nernst equation, the relationship between Kp and Kc, ΔG and K.</li>
    <li><strong>Graph reading.</strong> Rate plots for different orders, molar conductivity against concentration, and vapour pressure curves for ideal and non-ideal solutions.</li>
    <li><strong>Theory questions in physical chemistry.</strong> Not every question here is a numerical. Bonding, atomic structure and thermodynamics sign conventions produce many conceptual questions.</li>
  </ul>
  <p>
    Timed sets of fifteen or twenty physical chemistry questions, done in a session and reviewed immediately, build
    speed faster than anything else. If physics numericals are also a worry, see our guide to a
    <a href="{{ url('/physics-home-tutor/neet') }}">NEET physics tutor</a> and the article on
    <a href="{{ url('/blog/-neet-physics-highyield') }}">high-yield NEET physics</a>.
  </p>
