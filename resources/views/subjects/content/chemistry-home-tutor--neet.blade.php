  <h2 id="cn-pattern">The NEET chemistry pattern</h2>
  <p>
    According to the NTA's NEET (UG) 2026 information bulletin, the paper has 180 compulsory multiple-choice
    questions to be answered in 180 minutes, each with four options and a single correct or best answer.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Subject</th><th scope="col">Questions</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>Physics</td><td>45</td><td>180</td></tr>
      <tr><td>Chemistry</td><td>45</td><td>180</td></tr>
      <tr><td>Biology (Botany and Zoology)</td><td>90</td><td>360</td></tr>
      <tr><td><strong>Total</strong></td><td><strong>180</strong></td><td><strong>720</strong></td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Each correct answer earns four marks, each wrong answer loses one, and an unanswered question scores zero. The
    bulletin also uses chemistry as the second tie-breaker after biology when candidates have equal scores, one more
    reason not to treat it as a filler section.
  </p>
  <p>
    Two numbers are worth keeping in mind. With 180 questions in 180 minutes, the average is one minute a question
    across the whole paper. Chemistry, done well, should take less than that, leaving time for physics numericals.
    And every careless wrong answer costs five marks relative to a correct one, which is why accuracy matters as
    much as knowledge.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="cn-syllabus">The NEET chemistry syllabus</h2>
  <p>
    The syllabus is notified by the National Medical Commission, and the NTA's 2026 bulletin confirms it was
    unchanged from the previous year. It has twenty units drawn from Class 11 and 12 chemistry, which fall naturally
    into the three branches:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Branch</th><th scope="col">Units in the NEET syllabus</th></tr>
    </thead>
    <tbody>
      <tr><td>Physical chemistry</td><td>Some Basic Concepts in Chemistry; Atomic Structure; Chemical Bonding and Molecular Structure; Chemical Thermodynamics; Solutions; Equilibrium; Redox Reactions and Electrochemistry; Chemical Kinetics</td></tr>
      <tr><td>Inorganic chemistry</td><td>Classification of Elements and Periodicity in Properties; p-Block Elements; d- and f-Block Elements; Coordination Compounds</td></tr>
      <tr><td>Organic chemistry</td><td>Purification and Characterisation of Organic Compounds; Some Basic Principles of Organic Chemistry; Hydrocarbons; Organic Compounds Containing Halogens; Organic Compounds Containing Oxygen; Organic Compounds Containing Nitrogen; Biomolecules; Principles Related to Practical Chemistry</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Some chapters that older NEET books still include, such as states of matter, hydrogen, s-block elements,
    environmental chemistry, polymers and chemistry in everyday life, are not in the current unit list. A tutor
    should use the NMC syllabus, not an old question bank, to decide what to teach.
  </p>
  <p>
    Note one mismatch with CBSE. The p-block elements are a full NEET unit, but in the CBSE 2026-27 curriculum the
    s- and p-block elements are assessed only in school, not in the board theory paper. A student preparing only for
    the board can easily under-prepare p-block. The "Principles Related to Practical Chemistry" unit is another one
    that board students often skim: it covers detection of elements, functional-group tests, salt analysis and
    titration chemistry, all of which appear as NEET questions.
  </p>
