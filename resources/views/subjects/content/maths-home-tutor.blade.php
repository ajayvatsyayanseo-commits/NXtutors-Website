  <h2 id="mt-boards">How maths differs across boards</h2>
  <p>
    The same topic can be taught and examined very differently depending on the board. A tutor's experience with one
    board does not always carry over, so we always match on the board the student is actually sitting.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>CBSE (NCERT)</h3>
  <p>
    CBSE maths is built on the NCERT textbooks, and board papers stay close to NCERT examples, exercises and exemplar
    problems. Recent papers include a significant share of competency-based questions: case studies, assertion and
    reason items and application problems set in real-life contexts. In Class 10 students choose between Standard and
    Basic mathematics. A good CBSE tutor starts from NCERT, then moves to sample papers and previous years' papers.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>ICSE and ISC</h3>
  <p>
    CISCE's ICSE (Class 10) syllabus covers more ground than CBSE, including commercial topics such as GST, banking,
    and shares and dividends, as well as matrices, loci and reflection. Papers reward complete, clearly shown working.
    ISC maths in Classes 11 and 12 is demanding, and students need a tutor who knows its sections and choices well.
    Our guide to <a href="{{ url('/blog/icse-class-10-maths-boards') }}">ICSE Class 10 maths boards</a> goes further.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>IB: Analysis and Approaches or Applications and Interpretation</h3>
  <p>
    IB Diploma students take one of two maths courses, each at Standard Level or Higher Level. Analysis and Approaches
    (AA) leans towards algebra, calculus and proof; Applications and Interpretation (AI) leans towards modelling,
    statistics and technology. Both include an internal assessment, the mathematical exploration, which counts towards
    the final grade. Choosing the right course matters as much as tutoring it; see our
    <a href="{{ url('/blog/-ib-math-aaai-slhl') }}">IB Maths AA and AI, SL and HL explainer</a>.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Cambridge IGCSE: Core or Extended</h3>
  <p>
    IGCSE Mathematics is offered at two tiers. Core covers a narrower syllabus and caps the grade a student can reach;
    Extended covers the full syllabus and opens the top grades. The tier decision is usually made by the school, but a
    tutor can help a student move up to Extended if their work supports it. Past papers and mark schemes are central
    to IGCSE preparation. Read more in our <a href="{{ url('/blog/igcse-coreextended-maths') }}">IGCSE Core and
    Extended maths guide</a>.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>State boards</h3>
  <p>
    Many state boards now use textbooks based on or closely aligned with NCERT, but chapter order, paper pattern and
    marking vary from state to state, and some are taught in regional languages. A tutor who has taught your state
    board's recent papers will know where marks are awarded, which matters more than general maths ability.
  </p>
