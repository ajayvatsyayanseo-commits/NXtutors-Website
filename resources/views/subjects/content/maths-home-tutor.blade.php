  <h2 id="mt-signs">Signs your child may need a maths tutor</h2>
  <p>
    Maths difficulty rarely announces itself. It tends to show up sideways, in behaviour and habits before marks. Look
    out for these:
  </p>
  <ul>
    <li><strong>Marks falling in every test after one weak chapter.</strong> Because maths builds on itself, a single gap spreads. If marks dropped after a particular topic and never recovered, that topic is probably the root.</li>
    <li><strong>Homework taking far longer than it should.</strong> A child who spends ninety minutes on twenty minutes of maths is often stuck on something basic and working around it.</li>
    <li><strong>Copying methods without understanding them.</strong> If your child can do the textbook example but cannot start a question worded slightly differently, they have learned a procedure, not the idea.</li>
    <li><strong>Avoidance.</strong> Leaving maths homework for last, "forgetting" the notebook, or saying the teacher never explained it. These are often signs of anxiety rather than laziness.</li>
    <li><strong>Careless mistakes that are not really careless.</strong> Repeated sign errors, dropped brackets and misread questions usually point to weak fluency or poor setting out, both of which a tutor can fix.</li>
    <li><strong>A big transition ahead.</strong> Class 9, Class 11, a change of board or a move to a new school are all points where a few months of one-to-one help can prevent a long slide.</li>
  </ul>
  </section>

