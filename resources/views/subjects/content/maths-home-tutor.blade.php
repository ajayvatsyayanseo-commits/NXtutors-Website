  <section class="nx-guide__sec">
  <h2 id="mt-best">How to judge the "best" maths home tutor</h2>
  <p>
    Parents often ask us for the best maths tutor available. There is no single best tutor; there is the best tutor
    for this student, at this stage, on this board. Qualifications and years of experience are a starting point, but
    the demo class tells you far more. During and after it, ask yourself:
  </p>
  <ol>
    <li><strong>Did the tutor ask before telling?</strong> A strong first lesson starts with a few questions to find out what the student already knows.</li>
    <li><strong>Who did the maths?</strong> If the tutor solved most of the problems on the board, the student watched rather than learned.</li>
    <li><strong>Did the tutor spot a specific mistake</strong> in the student's working and explain why it was wrong, not just what the right answer is?</li>
    <li><strong>Could they explain an idea two ways?</strong> Ask them to re-explain something the student found hard. A good maths teacher has a second route ready.</li>
    <li><strong>Do they know the paper?</strong> Ask how marks are awarded for a long answer on your child's board. The answer should be specific.</li>
    <li><strong>Did they suggest a plan</strong> for the next four to six weeks and say how progress would be checked?</li>
    <li><strong>How did your child feel?</strong> Especially with younger students and anxious ones, comfort with the tutor matters more than a polished CV.</li>
  </ol>
  <p>
    If several answers are no, that tutor is not the right fit, however good their profile looks. Tell us and we will
    arrange a demo with the next tutor on the shortlist.
