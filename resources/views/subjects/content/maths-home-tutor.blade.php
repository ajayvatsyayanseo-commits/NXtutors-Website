  <h2 id="mt-stages">Maths tuition stage by stage</h2>
  <p>
    What a maths tutor should be doing changes sharply with the student's age. A tutor who is excellent with a
    Class 12 calculus student may be the wrong choice for a Class 3 child who is afraid of numbers, and the reverse is
    just as true. We match on stage, not just on the word "maths".
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Classes 1 to 5: number sense and confidence</h3>
  <p>
    At primary level the aim is fluency and comfort with numbers: place value, the four operations, times tables,
    fractions, measurement and simple word problems. A good tutor uses objects, drawings and games before symbols, and
    keeps sessions short and lively. Speed matters less than understanding. If a child counts on fingers in Class 4,
    the fix is usually a better grasp of number facts, not more drill.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Classes 6 to 8: the bridge to algebra</h3>
  <p>
    These are the years that decide how a student will feel about maths in Class 10. Integers, fractions and decimals,
    ratio and percentage, and then letters standing for numbers all arrive here. Most later struggles trace back to
    this stage. One or two sessions a week, focused on closing gaps and building the habit of setting out working
    neatly, is usually enough.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Classes 9 and 10: the first board years</h3>
  <p>
    The jump from Class 8 to Class 9 is steep: proofs in geometry, polynomials, coordinate geometry and statistics all
    arrive together. Class 10 then brings the board exam. Here a tutor needs to know the board's syllabus and paper
    pattern closely, teach every chapter properly and then move to timed papers. Our
    <a href="{{ url('/maths-home-tutor/class-10') }}">Class 10 maths tutor guide</a> covers the CBSE and ICSE papers
    chapter by chapter.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Classes 11 and 12: specialist territory</h3>
  <p>
    Senior-secondary maths (sets and functions, trigonometric functions, limits, calculus, vectors, three-dimensional
    geometry, probability) is abstract and fast-moving. Class 11 is where many strong Class 10 students first struggle,
    and Class 12 builds directly on it. A specialist is worth it here. Our notes on
    <a href="{{ url('/blog/cbse-class-12-maths-calculusalgebra') }}">Class 12 calculus and algebra</a> show how much
    depends on getting the Class 11 foundations right.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>JEE and olympiads</h3>
  <p>
    JEE Main and JEE Advanced maths asks for speed, pattern recognition and depth well beyond board level. Most
    aspirants attend coaching, and a home tutor helps most by clearing doubts from coaching sheets and working on the
    student's weakest chapters. See our <a href="{{ url('/blog/jee-maths-topicwise-prep') }}">topic-wise JEE maths
