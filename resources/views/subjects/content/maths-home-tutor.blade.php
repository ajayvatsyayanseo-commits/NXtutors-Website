  <h2 id="mtGuideTitle">Maths home tutor: a complete guide for parents</h2>

  <p class="nx-guide__lede">
    Maths is the subject parents worry about most, and for good reason. It is cumulative: a Class 6 student who never
    quite understood fractions will struggle with algebra in Class 8, and a Class 10 student who is shaky on quadratic
    equations will find Class 11 calculus a wall rather than a step. The good news is that maths also responds to
    one-to-one teaching faster than almost any other subject. A tutor who sits beside the student, watches them work and
    catches the exact line where the reasoning slips can fix in a few weeks what a crowded classroom leaves untouched
    for years. This guide explains what a good maths home tutor does at each stage, how the boards differ, how to choose
    between home and online tuition, what it costs, and how to tell in a single demo class whether a tutor is right.
  </p>

