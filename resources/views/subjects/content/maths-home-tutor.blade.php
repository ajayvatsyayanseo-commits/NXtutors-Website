  <h2 id="mt-session">What a good maths tuition session looks like</h2>
  <p>
    A typical one-hour session with a well-organised tutor follows a simple rhythm. It varies with age, but the
    pattern holds from Class 6 upwards:
  </p>
  <ul>
    <li><strong>Warm-up (five to ten minutes).</strong> Two or three quick questions from earlier topics. This keeps old chapters alive and shows the tutor what has been forgotten.</li>
    <li><strong>Homework review.</strong> Not just ticking, but asking the student to explain one answer aloud. Explaining is the best test of understanding.</li>
    <li><strong>New idea or problem type.</strong> Short explanation, one worked example, then the student tries a similar problem straight away while the tutor watches.</li>
    <li><strong>Independent practice.</strong> Graded problems, easier to harder, with the tutor stepping in only when the student is genuinely stuck.</li>
    <li><strong>Wrap-up.</strong> What was learned, what homework is set and what comes next. A short note to the parent after the session keeps everyone aligned.</li>
  </ul>
  <p>
    Nearer exams, the rhythm changes: more timed questions, full papers under exam conditions, and sessions spent
    going through marked papers mistake by mistake.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="mt-progress">How progress is tracked</h2>
  <p>
    Maths tuition is an investment and you should be able to see what it is buying. With the tutors we work with,
    progress is usually checked in three ways:
  </p>
  <ol>
    <li><strong>A starting point.</strong> In the first two or three sessions the tutor maps which topics are secure, which are shaky and which were never learned. That map becomes the plan.</li>
    <li><strong>Short tests every few weeks.</strong> A chapter test marked the way the board marks, with step marks, shows whether understanding is improving rather than just homework getting done.</li>
    <li><strong>School results in context.</strong> Unit tests and term exams are the clearest outside measure. A quick review with the tutor after each one keeps the plan honest.</li>
  </ol>
  <p>
    If you are not seeing movement on any of these after six to eight weeks, talk to the tutor first, then to us.
    Sometimes the plan needs to change; sometimes a different tutor will suit the student better. Both are normal.
  </p>
