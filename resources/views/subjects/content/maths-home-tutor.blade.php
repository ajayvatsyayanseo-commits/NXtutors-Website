  <h2 id="mt-what">What a good maths home tutor actually does</h2>
  <p>
    Many parents picture maths tuition as a second round of school: the tutor explains the chapter again, sets the
    textbook exercise and checks the answers. That helps a little. Good maths tutoring is something different, and it
    is worth knowing what to expect before you pay for it.
  </p>
  <ul>
    <li><strong>Diagnosis before teaching.</strong> A good tutor spends the first sessions finding out where the understanding actually breaks. A Class 9 student failing at linear equations may really have a problem with negative numbers or with the idea that both sides of an equation must be treated the same way. Teaching the current chapter again will not fix a gap three years older.</li>
    <li><strong>The student does the maths.</strong> In a strong session the student holds the pencil for most of the hour. The tutor asks, prompts and corrects, but does not solve the problems for them. Watching someone else do maths feels like learning; doing it yourself is learning.</li>
    <li><strong>Reading the working, not just the answer.</strong> One-to-one teaching lets the tutor see every line. Most lost marks come from a sign error, a skipped step or a misread question, and these are invisible if only the final answer is checked.</li>
    <li><strong>Building exam technique.</strong> From Class 9 onwards, the way an answer is written matters as much as whether it is right. Board marking schemes award marks for steps, and a tutor who knows the scheme teaches students to show them.</li>
    <li><strong>Rebuilding confidence.</strong> Many students who "hate maths" are simply used to being wrong in front of others. A patient tutor, in a quiet room with no audience, changes that faster than any worksheet.</li>
  </ul>
  </section>

