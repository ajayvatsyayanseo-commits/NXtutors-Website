  <section class="nx-guide__sec">
  <h2 id="ch-best">How to choose the best chemistry home tutor</h2>
  <p>
    "Best" depends on the student. The best tutor for a Class 12 student aiming for 95 is not the best tutor for a
    Class 11 student who has lost confidence. Use the free demo class to check the things that actually predict
    results:
  </p>
  <ul>
    <li><strong>Ask which branch they would start with, and why.</strong> A good tutor will want to see some of your child's recent test papers first and will name the weak branch within a session or two.</li>
    <li><strong>Watch a numerical being solved.</strong> In the demo, ask for a physical chemistry numerical. The tutor should make the student solve it and should insist on units and significant figures, not race through it on the board.</li>
    <li><strong>Ask them to explain one organic reaction without notes.</strong> If they explain it through electron movement and effects rather than "just remember it", organic will become easier for your child.</li>
    <li><strong>Check board and syllabus knowledge.</strong> Ask which topics are in this year's CBSE theory paper and which are assessed only in school. For 2026-27, CBSE lists some chapters, such as the s- and p-block elements in Class 11 and surface chemistry in Class 12, for formative assessment only. A current tutor will know this.</li>
    <li><strong>Ask about practicals.</strong> Can they help with salt analysis logic, titration calculations and the viva? These are marks a student should not lose.</li>
    <li><strong>Ask for a plan.</strong> By the end of the first week the tutor should be able to say what will be covered before the half-yearly exams and when full-length papers will start.</li>
    <li><strong>Notice how your child reacts.</strong> A student who is afraid to ask questions will not improve, however qualified the tutor.</li>
  </ul>
