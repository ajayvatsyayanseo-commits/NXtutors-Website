  <section class="nx-guide__sec">
  <h2 id="ch-branches">The three branches, and how each should be taught</h2>
  <p>
    A good chemistry tutor does not teach the three branches the same way, because they are learned differently.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Physical chemistry: numericals</h3>
  <p>
    Mole concept, thermodynamics, equilibrium, solutions, electrochemistry and kinetics. This is applied maths:
    formulae, units, logarithms and graphs. It is taught like maths, with a worked example, then the student solving
    while the tutor watches every line. Units are written at every step, because a lost factor of 1,000 between
    grams and kilograms or millilitres and litres is the most common error in the subject.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Organic chemistry: mechanisms and reactions</h3>
  <p>
    Organic makes sense once a student understands why electrons move: inductive and resonance effects,
    carbocation stability, nucleophiles and electrophiles. A tutor who teaches these ideas first turns hundreds of
    reactions into a handful of patterns. After that comes daily practice of conversions, where the student must get
    from one compound to another in two or three steps.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Inorganic chemistry: recall and trends</h3>
  <p>
    Periodic trends, bonding exceptions, d- and f-block properties and coordination compounds. For CBSE and NEET,
    the NCERT text is the source, often line by line. A tutor makes recall stick with trend tables, short daily
    quizzes and spaced revision, and explains the reason behind each trend so that exceptions stand out.
  </p>
      </div>
    </div>
  <p>
    The balance shifts across the two years. Class 11 is heavy on physical chemistry and the foundations of organic;
    Class 12 is heavy on organic families and on coordination compounds. A tutor should say at the start which branch
    your child is weakest in and how the weekly plan reflects it.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ch-signs">Signs your child needs a chemistry tutor</h2>
  <p>
    Chemistry trouble is often invisible until a test result arrives, because students can read a chapter, nod along
    and still be unable to use it. These are the early signs worth acting on:
  </p>
  <ul>
    <li><strong>Numericals are skipped in homework and tests.</strong> The student attempts the theory questions and leaves the calculations, usually because the mole concept or unit conversions are not secure.</li>
    <li><strong>Organic answers are guessed.</strong> Asked for the product of a reaction, the student writes something plausible rather than working it out from the reagent.</li>
    <li><strong>Marks fall sharply from Class 10 science.</strong> A student who scored well in Class 10 and then drops badly in the first Class 11 test is not suddenly weak; the jump in depth has caught them out, and early help repairs it quickly.</li>
    <li><strong>Revision means re-reading.</strong> Students who revise inorganic chemistry by reading the chapter again rarely remember it a week later. They need a recall routine.</li>
    <li><strong>The practical file is a worry.</strong> Salt analysis flowcharts and titration readings that do not make sense to the student are a sign the underlying chemistry needs attention.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ch-session">What a good chemistry tutoring session looks like</h2>
  <p>
    Most effective chemistry tutors use a similar shape for an hour, whether at home or online:
  </p>
  <ol>
    <li><strong>Quick recall.</strong> Five minutes of questions from all three branches: a periodic trend, a named reaction, one short numerical. This keeps older chapters alive.</li>
    <li><strong>Homework review.</strong> The student explains one answer aloud. A wrong numerical is traced back to the exact line where it went wrong.</li>
    <li><strong>New material.</strong> One concept or one reaction family, taught through reasoning, with the student trying a question straight away.</li>
    <li><strong>Exam-style practice.</strong> Questions in the format of your child's actual board or exam, marked the way the examiner would mark them.</li>
    <li><strong>Close.</strong> Homework set, the next topic named, and a short note to the parent on progress and anything to watch.</li>
  </ol>
  <p>
    Over a month, you should see all three branches appear, even if the school is teaching only one of them. A
    chemistry tutor who spends eight weeks only on the chapter being taught in school is following, not leading.
  </p>
  </section>

