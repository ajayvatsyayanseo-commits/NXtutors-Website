  <h2 id="ch-why">Why so many students struggle with chemistry</h2>
  <p>
    In Class 9 and 10, chemistry is one part of science. Chapters are short, equations are simple and a few evenings
    of revision before a test usually works. Then Class 11 arrives and chemistry becomes a full subject with two thick
    textbooks, a practical exam and, for many students, an entrance exam sitting on top. Three problems show up again
    and again:
  </p>
  <ul>
    <li><strong>The mole concept never quite clicked.</strong> Almost every numerical in physical chemistry, from stoichiometry to solutions and electrochemistry, is a mole calculation in disguise. A student who is shaky here struggles everywhere.</li>
    <li><strong>Organic is memorised, not understood.</strong> Students try to learn every reaction as a separate fact. It works for a few chapters and then collapses under the sheer number of conversions.</li>
    <li><strong>Inorganic is left to the end.</strong> Because it feels like "just reading", it is postponed until the last month, when there is no time to learn it properly.</li>
  </ul>
  <p>
    A one-to-one chemistry tutor fixes all three far more efficiently than a class of forty can. They can find the
    exact point where a student's understanding broke, rebuild it, and set a steady rhythm of practice across all
    three branches rather than whichever one the school happens to be teaching that month.
  </p>
  </section>

