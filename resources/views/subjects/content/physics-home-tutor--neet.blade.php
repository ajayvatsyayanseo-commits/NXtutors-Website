  <section class="nx-guide__sec">
  <h2 id="pn-paper">The NEET UG physics paper</h2>
  <p>
    The NTA's NEET (UG) 2026 information bulletin sets out the paper as follows:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Subject</th><th scope="col">Questions</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>Physics</td><td>45</td><td>180</td></tr>
      <tr><td>Chemistry</td><td>45</td><td>180</td></tr>
      <tr><td>Biology (Botany and Zoology)</td><td>90</td><td>360</td></tr>
      <tr><td><strong>Total</strong></td><td><strong>180</strong></td><td><strong>720</strong></td></tr>
    </tbody>
  </table>
  </div>
  <ul>
    <li><strong>Question type.</strong> Multiple-choice questions with four options and a single correct or best answer.</li>
    <li><strong>Time.</strong> 180 minutes for all 180 questions, so an average of one minute per question across the paper.</li>
    <li><strong>Marking.</strong> Four marks for a correct answer and one mark deducted for a wrong one, so guessing has a real cost.</li>
    <li><strong>Mode.</strong> NEET 2026 was a pen-and-paper (OMR) test. The government and NTA have announced that NEET UG will move to computer-based testing from 2027. Check the 2027 information bulletin when it is published for the final pattern, and make sure mock tests match it.</li>
  </ul>
  <p>
    Physics is a quarter of the paper by marks. Because physics questions often take longer than biology questions, a
    student who spends three minutes on each hard numerical runs short of time for the rest of the paper. Managing
    that trade-off is a central part of NEET physics coaching.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pn-syllabus">The NEET physics syllabus</h2>
  <p>
    The syllabus is set by the National Medical Commission. The updated syllabus for NEET (UG) 2026 lists twenty
    physics units: ten that correspond to Class 11, nine to Class 12, and a unit on experimental skills.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Class 11 units</th><th scope="col">Class 12 units</th></tr>
    </thead>
    <tbody>
      <tr><td>Physics and measurement; kinematics; laws of motion; work, energy and power; rotational motion</td><td>Electrostatics; current electricity; magnetic effects of current and magnetism; electromagnetic induction and alternating currents</td></tr>
      <tr><td>Gravitation; properties of solids and liquids; thermodynamics; kinetic theory of gases; oscillations and waves</td><td>Electromagnetic waves; optics; dual nature of matter and radiation; atoms and nuclei; electronic devices</td></tr>
      <tr><td colspan="2">Experimental skills: eighteen listed experiments, including vernier callipers, screw gauge, Young's modulus, surface tension, viscosity, resonance tube, metre bridge, galvanometer figure of merit, focal lengths, prism deviation, and p–n junction and Zener diode characteristics.</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Two points matter for planning. First, the NEET syllabus is close to NCERT Class 11 and 12 but not identical to
    the CBSE board syllabus for the same year: the electronic devices unit, for example, includes the Zener diode,
    photodiode, solar cell and logic gates. Second, the experimental skills unit means that practicals are not just a
    board formality; questions on least count, readings and graphs from these experiments can appear. A tutor should
    check the current NMC syllabus against the student's school syllabus and teach the difference.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pn-ncert">Why NEET physics preparation starts with NCERT</h2>
  <p>
    NEET physics questions are built on NCERT concepts, and many conceptual questions track the textbook's language,
    examples and graphs closely. That is why the most reliable approach is NCERT first, then practice.
  </p>
  <ol>
    <li><strong>Read the NCERT chapter properly.</strong> Not just the formulas: the explanations, worked examples, graphs, tables and the points to ponder. Conceptual NEET questions often come straight from these.</li>
    <li><strong>Solve every NCERT exercise and example.</strong> These are the base level of NEET numericals.</li>
    <li><strong>Move to NCERT Exemplar and previous NEET papers.</strong> Previous papers show exactly how NCERT ideas are turned into MCQs.</li>
    <li><strong>Only then, coaching modules and extra question banks.</strong> These add volume and speed, but without the NCERT base they produce memorised tricks rather than understanding.</li>
  </ol>
  <p>
    A student who has worked this way can usually eliminate two options in a conceptual question even when unsure,
    which matters in a paper with negative marking. For a subject-by-subject view of NCERT-first preparation, see our
    guides to <a href="{{ url('/blog/-neet-physics-highyield') }}">high-yield NEET physics</a> and
    <a href="{{ url('/blog/-neet-biology-ncertfirst') }}">NCERT-first NEET biology</a>.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pn-areas">Where to focus in NEET physics</h2>
  <p>
    NTA does not publish chapter-wise weightage, and the spread of questions varies from year to year. Previous
    papers do show some consistent patterns, which a tutor can use to prioritise without ignoring any unit:
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Mechanics</h3>
      <p>Kinematics, laws of motion, work and energy, rotation, gravitation and oscillations together make up a large part of the Class 11 syllabus and appear every year. Rotational motion is where many NEET students are weakest.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Electricity and magnetism</h3>
      <p>Electrostatics, current electricity, magnetic effects and induction are long units with many numericals. Circuit questions reward practice.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Optics and modern physics</h3>
      <p>Ray optics, wave optics, dual nature, atoms and nuclei. Modern physics is compact and formula-driven, which makes it efficient to master.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Short scoring units</h3>
      <p>Units and measurement, thermodynamics, kinetic theory, electromagnetic waves and electronic devices. Quick to revise and often direct, so marks lost here are hard to justify.</p>
    </div>
  </div>
  <p>
    The practical rule: no chapter is skipped, but time is shared out according to how often a chapter appears, how
    weak the student is in it, and how quickly it can be improved.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pn-chapters">Where NEET physics marks usually slip</h2>
  <p>
    Across the syllabus, a handful of chapters account for most of the trouble NEET students report. A tutor who
    knows these can check for them early:
  </p>
  <ul>
    <li><strong>Rotational motion.</strong> Moment of inertia with the parallel and perpendicular axes theorems, rigid-body rotation and angular momentum conservation. Many students memorise results without understanding when they apply.</li>
    <li><strong>Laws of motion.</strong> Connected bodies, pulleys, friction on inclines. Errors begin with a wrong free-body diagram.</li>
    <li><strong>Electrostatics and capacitors.</strong> Field and potential of charge distributions, capacitor combinations and the effect of a dielectric.</li>
    <li><strong>Current electricity.</strong> Circuit reduction, Kirchhoff's rules, the metre bridge and Wheatstone bridge. Practice speed matters here more than anywhere.</li>
    <li><strong>Ray optics.</strong> Sign convention in lens and mirror combinations, prisms and instruments.</li>
    <li><strong>Thermodynamics.</strong> Work in different processes, sign conventions and reading P–V graphs.</li>
    <li><strong>Units, dimensions and errors.</strong> Short and often underestimated; error propagation and significant figures questions catch students who skipped the chapter.</li>
  </ul>
  <p>
    Conversely, modern physics, electromagnetic waves, electronic devices and kinetic theory are compact, closely
    tied to NCERT, and reward a careful read. They are where a student with limited time can gain marks fastest.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pn-board">Board physics and NEET physics: the differences</h2>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col"></th><th scope="col">CBSE board physics</th><th scope="col">NEET physics</th></tr>
    </thead>
    <tbody>
      <tr><td>Format</td><td>Written answers, derivations, diagrams; 70 theory marks plus 30 practical in each of Classes 11 and 12.</td><td>45 MCQs across the Class 11 and 12 syllabus in one paper.</td></tr>
      <tr><td>What earns marks</td><td>Correct method and presentation, with step marks.</td><td>Only the final option; one mark lost for each wrong answer.</td></tr>
      <tr><td>Syllabus</td><td>The CBSE curriculum for the year.</td><td>The NMC syllabus, which includes some topics the CBSE list for 2026-27 does not, such as the Zener diode and logic gates.</td></tr>
      <tr><td>Practicals</td><td>Performed and examined in school.</td><td>Tested indirectly through the experimental skills unit.</td></tr>
      <tr><td>Time pressure</td><td>Moderate; three hours for one subject.</td><td>High; three hours for all three subjects.</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The overlap is large, so preparing for one helps the other, but a student who only practises MCQs can be
    surprised by board derivations, and a student who only writes long answers can be too slow for NEET. A tutor
    should include both kinds of practice in most weeks until the board exams.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pn-speed">Building MCQ speed without losing accuracy</h2>
  <p>
    With an average of about a minute per question across the paper, a NEET aspirant cannot solve every physics
    question as if it were a board long answer. Speed comes from a few specific skills a tutor can drill:
  </p>
  <ul>
    <li><strong>Formula recall without hesitation.</strong> A short daily recall drill on formulas, units and standard results (moment of inertia of common bodies, fields of standard charge distributions, lens and mirror relations).</li>
    <li><strong>Reading the options first.</strong> Options often reveal the form of the answer, and dimensional analysis can eliminate some in seconds.</li>
    <li><strong>Limiting cases and estimation.</strong> What happens if the mass is zero or the angle is 90°? A rough estimate often identifies the answer without full algebra.</li>
    <li><strong>Knowing when to leave a question.</strong> A student who spends four minutes on one numerical can lose more than they gain. Practise a two-pass approach in every mock.</li>
    <li><strong>Protecting accuracy.</strong> With a mark lost for each wrong answer, blind guessing is costly. Tutors help students learn when an educated guess (two options eliminated) is reasonable and when to skip.</li>
  </ul>
  <p>
    Speed work should come after concept work, not instead of it. A student who drills shortcuts on a shaky
    foundation becomes fast and wrong.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pn-tests">Using mock tests properly</h2>
  <p>
    Most NEET students take many mock tests. Far fewer analyse them. A tutor adds most value in the hour after a
    test, sorting every physics error into one of four groups:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Type of error</th><th scope="col">What it looks like</th><th scope="col">What to do</th></tr>
    </thead>
    <tbody>
      <tr><td>Concept gap</td><td>The student did not know the idea or which principle applied.</td><td>Return to NCERT and reteach; set a short targeted problem set.</td></tr>
      <tr><td>Calculation slip</td><td>Right method, arithmetic or unit error.</td><td>Record it in an error log; practise estimation and unit checks.</td></tr>
      <tr><td>Misread question</td><td>Answered what was expected, not what was asked.</td><td>Underline the quantity asked for; slow down on the first read.</td></tr>
      <tr><td>Time pressure</td><td>Knew it, but reached it too late or rushed it.</td><td>Adjust section order and the two-pass strategy.</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Over a few months this analysis shows whether marks are being lost to knowledge or to technique, and the plan
    changes accordingly.
  </p>
  </section>

