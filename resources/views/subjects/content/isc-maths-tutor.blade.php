    Algebra and coordinate geometry carry more than half the marks, and both are heavy. Trigonometry arrives with a
    long list of identities, conics bring a new kind of geometry, and permutations and combinations reward careful
    thinking more than formula recall. Calculus is only 8 marks in Class 11, but limits and derivatives are the base
    for the 35 marks of calculus in Class 12.
  </p>
  <p>
    Because the Class 11 examination is set by the school, papers vary in length and difficulty from school to
    school. Some schools set papers close to the board standard; others are gentler. Either way, the Class 11 syllabus
    is the foundation for Class 12 and for JEE, so a student who coasts through it tends to pay for it the following
    year. Our <a href="{{ url('/maths-home-tutor/class-11') }}">Class 11 maths tutor</a> page covers this year across
    boards.
  </p>
