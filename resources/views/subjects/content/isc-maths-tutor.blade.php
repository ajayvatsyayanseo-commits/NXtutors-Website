  <section class="nx-guide__sec">
  <h2 id="isc-working">Working and presentation: where ISC marks are kept</h2>
  <p>
    ISC maths gives marks for method. A correct final answer with no working can lose most of the marks for a
    question, and a wrong answer with sound working can keep many of them. When I review an ISC student's written
    work, these are the habits I look for first:
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
  <h3>State what you are using</h3>
  <p>
    Name the method or result: "Using the product rule", "By Bayes' theorem", "Applying the property of definite
    integrals". It tells the examiner the method is sound even if an arithmetic step slips.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>Define before you calculate</h3>
  <p>
    In probability, name the events. In linear programming, define the variables and write the constraints before
    drawing anything. In 3D geometry, write the direction ratios before using them.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>Draw what can be drawn</h3>
  <p>
    Area questions need a sketch of the curves and the region. Linear programming needs a clear graph with the
    feasible region marked. A neat diagram often earns marks and prevents errors.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>Finish the question</h3>
  <p>
    Give the constant of integration, state the domain where asked, write the final answer in the form requested,
    and in word problems answer the question in a sentence with units.
  </p>
    </div>
  </div>
  <p>
    Rough work belongs next to the answer, not on a separate sheet. None of this is complicated, but it only becomes
    automatic if someone reads every line the student writes, every week, and corrects the layout as well as the
    mathematics.
  </p>
  </section>

