  <section class="nx-guide__sec">
  <h2 id="isc-jump">The jump from ICSE Class 10 to ISC Class 11</h2>
  <p>
    Students arriving from ICSE Class 10 usually have two big strengths: they are used to writing full working, and
    they are used to long papers. Those habits carry straight into ISC. What catches them out is the change in the
    mathematics itself.
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
  <h3>Abstraction arrives quickly</h3>
  <p>
    ICSE Class 10 maths is largely concrete: commercial mathematics, mensuration, geometry with diagrams. ISC
    Class 11 opens with sets, relations and functions, and soon adds complex numbers. Students need to get
    comfortable with notation and definitions, not only procedures.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>Trigonometry grows enormously</h3>
  <p>
    Class 10 trigonometry is mainly identities and heights and distances. Class 11 adds radian measure,
    trigonometric functions and their graphs, and compound-angle and multiple-angle identities. Fluency here
    affects calculus a year later.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>Algebra has to be automatic</h3>
  <p>
    Factorising, handling indices and rearranging expressions are no longer the question; they are the tools used
    inside every question. Students who still hesitate over algebra in Class 11 find every topic slower.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>The pace is higher</h3>
  <p>
    Class 11 covers a great deal in one year, and schools rarely slow down. A gap left in July is still there in
    February, and in Class 12.
  </p>
    </div>
  </div>
  <p>
    The months after Class 10 boards are the best time to prepare. A few weeks on algebraic fluency, the basics of
    functions and early trigonometry make the first term of Class 11 far easier. Families still in ICSE Class 10 in
    Gurugram can see our <a href="{{ url('/icse-maths-tutor-gurgaon') }}">ICSE maths tutor in Gurgaon</a> page; the
    same advice applies anywhere.
  </p>
  <p>
    Some students join ISC from CBSE, IGCSE or IB schools. They face the same jump, plus the ISC style of setting out
    working. A tutor who has taught those courses can map the gaps quickly; see our
    <a href="{{ url('/igcse-maths-tutor') }}">IGCSE maths tutor</a> and <a href="{{ url('/ib-maths-tutor') }}">IB maths
    tutor</a> pages for those courses.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="isc-jee">ISC maths and JEE</h2>
  <p>
    Many ISC science students also prepare for JEE, and the overlap is large. Most of what the ISC syllabus covers
    also appears in JEE Main maths: in Class 11, complex numbers, quadratic equations, permutations and combinations,
    the binomial theorem, sequences and series, straight lines, circles and conics; in Class 12, functions, matrices
    and determinants, calculus, vectors, three-dimensional geometry and probability.
  </p>
  <p>
    The change for 2027 helps JEE students. Vectors and three-dimensional geometry are now compulsory in ISC, so no
    ISC science student skips them because their school chose the other section.
  </p>
  <p>
    The difference is in the style of question. ISC rewards complete, well-presented working on questions that are
    usually direct applications of the syllabus. JEE rewards speed and the ability to combine ideas from several
    chapters, with no credit for working. A student preparing for both needs:
  </p>
  <ul>
    <li><strong>One set of concepts, two kinds of practice.</strong> Learn each chapter once, properly, then practise it both ways: written, board-style solutions, and timed objective problems.</li>
    <li><strong>Protected board time.</strong> In Class 12, the months before the ISC examination should be about ISC papers and presentation, even for committed JEE students. Board marks matter for many admissions.</li>
    <li><strong>A tutor who is honest about the difference.</strong> An ISC tutor is not automatically a JEE coach, and the reverse is also true. Say which you need, or whether you need both.</li>
  </ul>
  <p>
    JEE planning usually involves physics and chemistry too; our <a href="{{ url('/physics-home-tutor/jee') }}">JEE
    physics tutor</a> page explains how we approach entrance preparation alongside the boards. Always check the
    current JEE syllabus published by the conducting body, since it changes independently of ISC.
  </p>
  </section>

