  </div>
  <p>
    There is a second maths subject in ISC, Applied Mathematics (subject code 885), meant for students heading
    towards commerce, economics, humanities, biosciences and the social sciences. A student cannot take both. Most of
    this guide is about Mathematics (860), because that is what "ISC maths" usually means; Applied Mathematics comes
    up again in the section on Sections B and C.
  </p>
  </section>

