  <section class="nx-guide__sec">
  <h2 id="isc-sections">ISC maths Section B and Section C: what changed</h2>
  <p>
    Many families still search for help with "ISC maths Section B or C", and many guides, textbooks and older
    papers are built around it, so it is worth being clear about what has changed.
  </p>
  <p>
    <strong>Up to the 2026 examination</strong>, the Class 12 paper had a compulsory Section A worth 65 marks and then
    a choice: students answered all the questions from either Section B or Section C, each worth 15 marks. Under the
    revised 2026 syllabus, Section B covered vectors, three-dimensional geometry and applications of integrals, while
    Section C covered applications of calculus in commerce and economics, linear regression and linear programming.
    Schools usually decided which section they taught, broadly Section B for engineering-minded students and
    Section C for commerce students.
  </p>
  <p>
    <strong>From the 2027 examination</strong>, the CISCE syllabus for Mathematics (860) no longer divides the paper
    into Sections B and C. Vectors, three-dimensional geometry and linear programming are now compulsory units for
    every student, area under curves sits inside calculus, and linear regression no longer appears in the
    Mathematics syllabus. Students who want a maths course aimed at commerce and economics now have Applied
    Mathematics (885), whose Class 12 syllabus includes financial mathematics, index numbers and moving averages.
  </p>
  <p>What this means in practice:</p>
  <ul>
    <li><strong>Old papers need care.</strong> ISC maths papers up to 2026 contain Section C questions on regression and commerce applications that are no longer in the 860 syllabus. They are still excellent practice for Section A, but a tutor should flag which questions to skip.</li>
    <li><strong>Commerce students with Mathematics (860) must now do vectors and 3D geometry.</strong> For a student who expected Section C, that is roughly eleven marks of unfamiliar geometry. It is very learnable, but it needs to be planned.</li>
    <li><strong>The subject choice matters more than before.</strong> In Class 11, families choosing between Mathematics and Applied Mathematics are really choosing the course, not a section. Engineering, architecture, physics and JEE point to Mathematics (860); many commerce, economics and humanities routes are served by Applied Mathematics, but check the entry requirements of the specific degree courses your child is considering.</li>
    <li><strong>Repeaters follow the new syllabus.</strong> A student taking the examination again follows the syllabus for the year of that examination, not the one they studied.</li>
  </ul>
  <p>
    CISCE had not yet published a 2027 specimen paper for Mathematics when this guide was written. The specimen paper
    shows how many questions there are and where the internal choices sit, so look for it on cisce.org and practise
    with it as soon as it appears.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="isc-paper">How the ISC Class 12 maths paper works</h2>
  <p>
    The detailed layout for 2027 will be confirmed by the specimen paper, but several features of ISC maths papers
    have been stable and are worth building habits around. Going by the CISCE specimen paper for 2026:
  </p>
  <ul>
    <li><strong>Fifteen minutes of reading time.</strong> Students may read but not write. It is the time to choose between internal-choice questions and to spot the questions to do first.</li>
    <li><strong>A mix of question lengths.</strong> The paper opens with short items, including multiple-choice questions where only one option is written as the answer, and builds to longer questions worth several marks each.</li>
    <li><strong>Internal choices.</strong> Some questions offer an either/or. Choosing quickly and sticking with the choice saves more time than students expect.</li>
    <li><strong>Working on the same page.</strong> All working, including rough work, must be done on the same page as, and next to, the rest of the answer. Examiners look at it.</li>
    <li><strong>Tables and graph paper are provided.</strong> Students should not bring their own.</li>
  </ul>
  <p>
    On calculators, the current ISC regulations permit the Casio fx-82 MS scientific calculator, calculators of
    other makes with similar functions, or basic calculators; any calculator that can store and retrieve information
    is not allowed. That does not mean every step can be handed to the calculator. ISC maths marks come from method,
    so the student still needs to show the working. Check the regulations for your exam year and any instructions
    printed on the paper.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="isc-project">The ISC maths project: 20 marks worth taking seriously</h2>
  <p>
    Project work is Paper II, and it is worth 20 marks in each of Classes 11 and 12. That is a fifth of the subject,
    and unlike the theory paper, much of it can be secured before the examination season begins.
  </p>
  <p>
    Each student completes two projects, each marked out of 10. The syllabus sets out how the marks are divided:
  </p>
