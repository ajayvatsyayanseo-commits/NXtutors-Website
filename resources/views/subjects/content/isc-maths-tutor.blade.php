  <h2 id="isc-glance">ISC maths at a glance</h2>
  <p>
    ISC is the Indian School Certificate, the Class 12 examination run by the Council for the Indian School
    Certificate Examinations (CISCE). The maths subject most science students take is Mathematics, subject code 860.
    CISCE describes it as the course for students heading towards mathematics, physics, chemistry, engineering,
    architecture and related fields.
  </p>
  <p>
    The shape is the same in both years. Each year has a three-hour theory paper worth 80 marks and project work
    worth 20 marks. The difference is who sets the paper: the Class 11 final examination is conducted by the school,
    while the Class 12 paper is the ISC board examination set by CISCE.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
