  <p>
    Calculus is almost half the theory paper, and it is where the year is won or lost. The syllabus notes a few
    boundaries worth knowing: equations reducible to variable-separable form are included in differential equations,
    second-order differential equations are excluded, and proofs of geometrical theorems using vectors are excluded.
    A tutor who knows these edges saves the student time on material that will not be examined.
  </p>
  <p>
    Syllabuses are revised from time to time, and CISCE's rule is that candidates follow the syllabus of the year in
    which they sit the examination. Always check the current CISCE syllabus for your child's exam year before relying
    on any table, including this one.
  </p>
