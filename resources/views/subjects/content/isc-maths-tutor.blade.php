  <h2 id="isc-tutor">How to choose an ISC maths tutor</h2>
  <p>
    A strong general maths tutor is not automatically a good ISC maths tutor. These are the questions worth asking
    before and during the demo class:
  </p>
  <ul>
    <li><strong>Do they teach ISC now?</strong> The 2027 changes mean a tutor working from memory of the old Section B and C paper can plan the year wrongly. Ask how they are handling the new syllabus.</li>
    <li><strong>Do they work from the CISCE syllabus?</strong> Since there is no single ISC textbook, a good tutor knows the syllabus boundaries and works around the student's school book.</li>
    <li><strong>Do they mark working, not just answers?</strong> In the demo, watch whether the tutor reads the student's written steps and corrects the setting out.</li>
    <li><strong>Can they support the projects properly?</strong> Helping a student choose a topic and prepare for the viva is valuable; doing the project for them is not.</li>
    <li><strong>Are they clear about JEE?</strong> If your child is preparing for JEE, ask whether the tutor covers both, and how they would balance the two.</li>
    <li><strong>Does the student understand them?</strong> The best check of all. After the demo, ask your child whether the explanation made sense and whether they would be comfortable asking a question they felt silly about.</li>
