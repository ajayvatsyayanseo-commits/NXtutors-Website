      <tr><td>Findings</td><td>2</td><td>Subject teacher and Visiting Examiner</td></tr>
      <tr><td>Viva-voce based on the project</td><td>3</td><td>Visiting Examiner only</td></tr>
      <tr><td><strong>Total per project</strong></td><td><strong>10</strong></td><td></td></tr>
    </tbody>
  </table>
  </div>
  <p>
    CISCE provides a list of suggested project topics. In Class 12 these include finding areas bounded by pairs of
    curves, comparing methods for finding the area under a curve, tessellations and the derivation of
    determinants. Class 11 suggestions include illustrating trigonometric graphs, constructing conics and using
    Pascal's triangle for binomial expansions. No question paper is set for the project.
  </p>
  <p>
    The part students underestimate is the viva. Three marks per project depend on the student explaining their
    own work to the Visiting Examiner. A project that was heavily "helped" at home shows up quickly in a viva. The
    right role for a tutor is to help the student choose a topic they can handle, check the mathematics, push for
    clear findings and rehearse the viva questions, while the work itself stays the student's.
  </p>
  </section>

