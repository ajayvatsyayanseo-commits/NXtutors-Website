  <h2 id="m7-icse">ICSE Class 7 maths</h2>
  <p>
    ICSE schools follow CISCE's curriculum for the middle years through a textbook series chosen by the school, so
    chapter names and order vary. Your child's school syllabus is the reference. Broadly, ICSE Class 7 maths tends to
    include:
  </p>
  <ul>
    <li><strong>Integers, rational numbers, fractions and decimals.</strong> Rational numbers are commonly introduced in Class 7 in ICSE schools, earlier than in the NCERT order.</li>
    <li><strong>Exponents.</strong> Powers and the laws of exponents.</li>
    <li><strong>Commercial arithmetic.</strong> Ratio and proportion, unitary method, percentage, profit and loss, and simple interest.</li>
    <li><strong>Algebra.</strong> Algebraic expressions, operations on them, and linear equations in one variable, often with word problems.</li>
    <li><strong>Geometry.</strong> Lines and angles, triangles and their properties, congruency, Pythagoras in some series, and constructions.</li>
    <li><strong>Mensuration.</strong> Perimeter and area of plane figures, often including circles.</li>
    <li><strong>Data handling and probability.</strong> Mean, median, mode and bar graphs, with an early look at probability in some books.</li>
  </ul>
  <p>
    ICSE Class 7 is typically heavier on commercial arithmetic and on exercise volume. Students need both speed and
    accuracy, and a tutor can help them prioritise the exercises that matter.
  </p>
  </section>

