  <h2 id="m7-why">Why Class 7 maths is a turning point</h2>
  <p>
    Ask a Class 9 student when maths "stopped making sense" and a surprising number will say Class 7. That is because
    three things happen at once this year. Arithmetic becomes algebra, as numbers are replaced by letters. Negative
    numbers stop being a curiosity and have to be multiplied and divided. And geometry moves from drawing shapes to
    reasoning about them, with angle facts and properties of triangles.
  </p>
  <p>
    None of these is hard on its own. The trouble is that each depends on a Class 6 skill being automatic. A child who
    still hesitates over −4 + 7, or who adds fractions by adding tops and bottoms, will find Class 7 algebra
    confusing, because the algebra is built from exactly those operations.
  </p>
  <p>
    The upside is that Class 7 is still early enough to fix everything calmly, without board-exam pressure. A tutor who
    spends this year making integers, fractions and early algebra rock-solid saves a great deal of stress in Classes 8,
    9 and 10.
  </p>
  </section>

