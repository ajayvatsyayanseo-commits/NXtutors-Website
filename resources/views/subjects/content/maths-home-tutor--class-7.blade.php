  <h2 id="m7-year">A term-by-term view of the Class 7 year</h2>
  <p>
    Because the CBSE book comes in two parts, it helps to think of Class 7 as two halves with different jobs. Schools
    set their own order, so treat this as a guide rather than a timetable.
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>April to September (Part I)</h3>
      <p>Big numbers, expressions and the first decimals chapter settle quickly. The real work is Expressions using Letter-Numbers and Working with Fractions. A tutor should make sure these are secure before the half-yearly exam, because Part II assumes them.</p>
    </div>
    <div class="nx-guide__card">
      <h3>October to March (Part II)</h3>
      <p>Integers, common factors and the second decimals chapter tighten number skills; congruence, constructions and data broaden geometry and statistics. The year ends with Finding the Unknown, where letters, integers and fractions all come together in equations.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Summer break</h3>
      <p>The weeks before Class 7 are a good time to revise Class 6 fractions and negative numbers. The weeks after Class 7 are ideal for a gentle preview of squares, cubes and exponents for Class 8.</p>
    </div>
  </div>
  <p>
    ICSE students follow a different order, often meeting algebraic equations and commercial arithmetic earlier, but the
    principle is the same: secure the number and algebra chapters first, because everything else leans on them.
  </p>
