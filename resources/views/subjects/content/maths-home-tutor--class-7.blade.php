  <h2 id="m7-signs">When to get a Class 7 maths tutor</h2>
  <ul>
    <li><strong>Algebra homework is blank or copied.</strong> The student cannot start a question involving letters without help.</li>
    <li><strong>Sign errors everywhere.</strong> Correct method, wrong sign, across several chapters.</li>
    <li><strong>A slide from Class 6.</strong> Marks falling by a clear margin between the end of Class 6 and the first Class 7 tests.</li>
    <li><strong>Reliance on answers at the back.</strong> Working backwards from the answer rather than reasoning forwards.</li>
    <li><strong>Geometry answers without reasons.</strong> Losing marks because the "because" is missing.</li>
    <li><strong>Plans for later.</strong> The family is thinking about olympiads, a board change for Class 9, or a strong science stream later, and wants the base secure.</li>
  </ul>
  </section>

