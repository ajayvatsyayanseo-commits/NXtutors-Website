  <h2 id="m7-algebra">Helping a Class 7 child with early algebra</h2>
  <p>
    Algebra is where parents most often feel they cannot help. You do not need to remember the rules to make a
    difference. Try these:
  </p>
  <ul>
    <li><strong>Ask for the story behind the letter.</strong> If the homework says 4n + 3, ask "what could n be? What if n is 10?" Substituting a number is the quickest way to make an expression mean something.</li>
    <li><strong>Check by substitution.</strong> Teach your child to test a simplified answer by putting in a small number on both sides. If the two sides differ, something went wrong.</li>
    <li><strong>Use balance language.</strong> For equations, talk about keeping both sides of a scale level: whatever you do to one side, you do to the other.</li>
    <li><strong>Praise the working.</strong> Notice neat, step-by-step lines, not just ticks. That is the habit that protects marks in Classes 9 and 10.</li>
  </ul>
  <p>
    If your child is ready for more challenge, puzzle-style problems and early olympiad questions are a good stretch at
    this age; our <a href="{{ url('/blog/math-olympiad-rmoinmo-preparation-2025--syllabus-notes-tips--strategy') }}">maths olympiad guide</a>
    explains how the later stages work.
