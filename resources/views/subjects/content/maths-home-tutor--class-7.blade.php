  <h2 id="m7-hard">Where Class 7 students struggle</h2>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Letters as numbers</h3>
      <p>Why 3a + 2a is 5a but 3a + 2b cannot be combined. Students who treat letters as labels ("a for apples") rather than numbers get stuck fast.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Signs with integers</h3>
      <p>Negative times negative is positive: memorised easily, applied wrongly. Errors appear inside algebra, not just in the integers chapter.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Dividing fractions</h3>
      <p>"Invert and multiply" without knowing why leads to flipping the wrong fraction. A picture-based explanation fixes this for good.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Decimal place value</h3>
      <p>Believing 0.25 is bigger than 0.3 because 25 is bigger than 3. Two decimal chapters in one year expose this quickly.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Angle reasoning</h3>
      <p>Using alternate and corresponding angles with parallel lines, and giving a reason for each step. Many students find the right angle but cannot justify it.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Turning words into equations</h3>
      <p>"Finding the Unknown" asks students to write the equation themselves. Translating a story into symbols is the hardest single skill of the year.</p>
    </div>
  </div>
  </section>

