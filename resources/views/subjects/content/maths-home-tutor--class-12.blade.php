  <section class="nx-guide__sec">
  <h2 id="m12-present">Presenting derivations and steps for full marks</h2>
  <p>
    Class 12 maths is marked step by step. Two students with the same final answer can score very differently. The
    habits a tutor should drill:
  </p>
  <ul>
    <li><strong>State the method.</strong> "Using integration by parts" or "applying the second derivative test" tells the examiner what you are doing and often earns a method mark.</li>
    <li><strong>Write the formula before substituting.</strong> In integrals, 3D distance and probability questions, the formula line is usually worth something even if a later step slips.</li>
    <li><strong>Show the key intermediate steps.</strong> For a matrix inverse, write the determinant, the cofactors and the adjoint separately.</li>
    <li><strong>Justify maxima and minima.</strong> Show the sign of the second derivative (or the first derivative change) and conclude explicitly.</li>
    <li><strong>Draw and shade.</strong> Area questions and linear programming need a labelled graph with the region clearly marked.</li>
    <li><strong>Add the constant.</strong> Indefinite integrals need + C, and a particular solution needs the condition applied.</li>
    <li><strong>End with a statement.</strong> In applied questions, a final sentence answering the question, with units where relevant.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m12-revision">Class 12 maths revision that works</h2>
  <p>
    Revision in Class 12 is not re-reading. What helps most:
  </p>
  <ul>
    <li><strong>Mixed sets, not chapter sets.</strong> In the board paper, questions do not announce their chapter. From November, practise mixed sets.</li>
    <li><strong>An error log.</strong> Every wrong answer goes into a notebook with the reason. Reviewing the log before each paper prevents repeats.</li>
    <li><strong>Timed full papers.</strong> One a week from December, reviewed the next session. Timing Section A separately is useful.</li>
    <li><strong>Integration drills.</strong> Short daily sets of integrals keep the most practice-hungry chapter fresh.</li>
    <li><strong>Formula sheet in the student's own hand.</strong> Writing it is part of learning it.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m12-traps">Chapter traps that cost Class 12 marks</h2>
  <p>
    Beyond presentation, each high-weight chapter has its own favourite errors. A tutor who knows them can fix them
    before the pre-boards:
  </p>
  <ul>
    <li><strong>Inverse trigonometric functions.</strong> Ignoring principal value ranges, so that sin⁻¹(sin x) is simplified to x when x lies outside the principal branch.</li>
    <li><strong>Continuity.</strong> Checking only the left-hand limit, or forgetting to compare both limits with the value of the function at the point.</li>
    <li><strong>Maxima and minima.</strong> Differentiating the wrong quantity because the function was never written in one variable; always express the quantity to be optimised first.</li>
    <li><strong>Integration by parts.</strong> Choosing the wrong first function, which makes the second integral harder than the first.</li>
    <li><strong>Definite integrals.</strong> Changing the variable by substitution but not changing the limits.</li>
    <li><strong>Area under curves.</strong> Integrating across a point where the curve crosses the axis and letting positive and negative areas cancel.</li>
    <li><strong>Differential equations.</strong> Missing the integrating factor's sign, or not rewriting the equation in standard form first.</li>
    <li><strong>3D geometry.</strong> Using direction ratios where the formula needs direction cosines, or mixing up the formula for shortest distance between skew and parallel lines.</li>
    <li><strong>Bayes' theorem.</strong> Not defining the events in words before writing probabilities, which leads to swapped conditional probabilities.</li>
  </ul>
