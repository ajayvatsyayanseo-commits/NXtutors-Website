  <h2 id="m12-weight">CBSE Class 12 maths 2026-27: unit weightage</h2>
  <p>
    CBSE Class 12 Mathematics (code 041) is one three-hour board paper of 80 marks, plus 20 marks of internal
    assessment. The 2026-27 curriculum spreads the theory marks across six units:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Unit</th><th scope="col">Chapters</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>Relations and Functions</td><td>Relations and Functions; Inverse Trigonometric Functions</td><td>8</td></tr>
      <tr><td>Algebra</td><td>Matrices; Determinants</td><td>10</td></tr>
      <tr><td>Calculus</td><td>Continuity and Differentiability; Applications of Derivatives; Integrals; Applications of the Integrals; Differential Equations</td><td>35</td></tr>
      <tr><td>Vectors and Three-dimensional Geometry</td><td>Vectors; Three-dimensional Geometry</td><td>14</td></tr>
      <tr><td>Linear Programming</td><td>Linear Programming</td><td>5</td></tr>
      <tr><td>Probability</td><td>Probability</td><td>8</td></tr>
      <tr><td><strong>Theory total</strong></td><td></td><td><strong>80</strong></td></tr>
      <tr><td>Internal assessment</td><td>Periodic tests (best 2 of 3) 10; mathematics activities 10</td><td>20</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The message of this table is hard to miss. Calculus alone is 35 of the 80 marks, more than 40% of the paper.
    Vectors and 3D geometry add 14, so these two units together account for almost two-thirds of the paper. Relations
    and Functions, Algebra, Linear Programming and Probability make up the remaining 31 marks, and they are generally
    the quicker chapters to secure. CBSE also notes that there is no chapter-wise weightage within units and that all
    chapters must be covered.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m12-paper">How the 2026-27 question paper is built</h2>
  <p>
    CBSE's 2026-27 sample question paper for Class 12 maths has 38 compulsory questions in five sections:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Section</th><th scope="col">Questions</th><th scope="col">Type</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>A</td><td>1 to 20</td><td>18 multiple-choice questions and 2 assertion-reason questions, 1 mark each</td><td>20</td></tr>
      <tr><td>B</td><td>21 to 25</td><td>Very short answer, 2 marks each</td><td>10</td></tr>
      <tr><td>C</td><td>26 to 31</td><td>Short answer, 3 marks each</td><td>18</td></tr>
      <tr><td>D</td><td>32 to 35</td><td>Long answer, 5 marks each</td><td>20</td></tr>
      <tr><td>E</td><td>36 to 38</td><td>Case-study questions, 4 marks each</td><td>12</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    There is no overall choice, but internal choices are given in two questions of Section B, three of Section C, two
    of Section D and one sub-part in two of the case studies. By type of thinking, the curriculum allots 44 marks
    (55%) to remembering and understanding, 20 marks (25%) to applying, and 16 marks (20%) to analysing, evaluating
    and creating.
  </p>
  <p>
    Two practical points follow. First, Section A is a fifth of the paper and rewards speed and accuracy on short
    questions, so students should practise MCQs and assertion-reason items in timed sets, not only long answers.
    Second, the long answers in Section D are where full working matters most; a tutor should mark these the way a
    board examiner would.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m12-calc">Calculus: the core of Class 12 maths</h2>
  <p>
    Five chapters, 35 marks, and the foundation of JEE and most university maths. A Class 12 tutor should treat
    calculus as the backbone of the year and give it time accordingly.
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Continuity and Differentiability</h3>
      <p>Continuity at a point, the chain rule, derivatives of inverse trigonometric, exponential and logarithmic functions, implicit and parametric differentiation, logarithmic differentiation, and second derivatives. Speed here makes the rest of calculus easier.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Applications of Derivatives</h3>
      <p>Rates of change, increasing and decreasing functions, and maxima and minima with first and second derivative tests. Maxima-minima word problems are a regular long-answer question, and forming the function is the hard part.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Integrals</h3>
      <p>Integration by substitution, partial fractions and parts, the standard integral forms, and definite integrals with their properties. This is the chapter that most rewards daily practice; recognising which method to use comes only from volume.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Applications of the Integrals</h3>
      <p>Areas under simple curves: lines, circles, parabolas and ellipses in standard form. A neat sketch with the region shaded is half the answer.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Differential Equations</h3>
      <p>Order and degree, general and particular solutions, variables separable, homogeneous equations and linear first-order equations. Largely procedural once integration is secure.</p>
    </div>
  </div>
  <p>
    Calculus in Class 12 assumes Class 11 functions, trigonometry and limits are firm. If they are not, a tutor should
    spend the first few sessions rebuilding them rather than pushing ahead; it saves time within weeks. Our guide to
    <a href="{{ url('/blog/cbse-class-12-maths-calculusalgebra') }}">CBSE Class 12 calculus and algebra</a> goes deeper
    into each chapter, and students who need to revisit the basics can look at our
    <a href="{{ url('/maths-home-tutor/class-11') }}">Class 11 maths tutoring</a> page.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m12-rest">The other units: quick marks, if prepared</h2>
  <ul>
    <li><strong>Relations and Functions (8 marks).</strong> Reflexive, symmetric, transitive and equivalence relations; one-one and onto functions; inverse trigonometric functions with principal values and graphs. Proofs of equivalence must check all three properties explicitly.</li>
    <li><strong>Matrices and Determinants (10 marks).</strong> Matrix operations, transpose, symmetric and skew-symmetric matrices, determinants up to 3 × 3, adjoint and inverse, and solving a system of equations by the matrix method. Arithmetic slips in a 3 × 3 inverse are the usual loss.</li>
    <li><strong>Vectors and 3D Geometry (14 marks).</strong> Direction cosines and ratios, dot and cross products, vector and Cartesian equations of a line, angle between lines, skew lines and shortest distance. Students should be comfortable moving between vector and Cartesian forms.</li>
    <li><strong>Linear Programming (5 marks).</strong> Forming constraints, drawing the feasible region and testing corner points, with up to three non-trivial constraints. Accurate graphing earns these marks.</li>
    <li><strong>Probability (8 marks).</strong> Conditional probability, the multiplication theorem, independent events, total probability and Bayes' theorem. Defining events clearly before calculating avoids most errors.</li>
  </ul>
  </section>

