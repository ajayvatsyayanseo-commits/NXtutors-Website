  <h2 id="m12-balance">Balancing boards with JEE and CUET</h2>
  <p>
    Most Class 12 science students are preparing for more than one exam. The good news is that the overlap is large:
    the board syllabus is the core of JEE Main's Class 12 maths and of the CUET maths domain test. The challenge is
    that each exam rewards a different skill.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Exam</th><th scope="col">What it rewards</th><th scope="col">How to prepare</th></tr>
    </thead>
    <tbody>
      <tr><td>CBSE or ISC board</td><td>Complete, well-presented working; NCERT-level understanding; covering every chapter</td><td>NCERT and exemplar problems, sample papers, full written answers marked for steps</td></tr>
      <tr><td>JEE Main and Advanced</td><td>Speed, depth, combining ideas from several chapters</td><td>Harder problem sets built on the same chapters, timed practice, Class 11 revision</td></tr>
