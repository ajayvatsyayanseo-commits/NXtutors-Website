  <h2 id="m6-ncert">CBSE and NCERT Class 6 maths: the Ganita Prakash chapters</h2>
  <p>
    CBSE schools use <strong>Ganita Prakash</strong>, NCERT's Class 6 mathematics textbook written for the new
    National Curriculum Framework for School Education. It is a single book of ten chapters. Many chapters are
    exploratory, with puzzles and "Figure it Out" questions rather than long drill exercises.
  </p>
