  <h2 id="m6-week">A weekly tutoring plan for Class 6 maths</h2>
  <p>
    Two sessions of about an hour each week suit most Class 6 students. The aim is to stay a little ahead of school,
    not to redo school.
  </p>
  <ul>
    <li><strong>Session 1: the current chapter.</strong> Ten minutes of quick mental arithmetic, then the school's current chapter taught through one exploration or puzzle before the textbook questions. The tutor checks that the child can explain the idea in their own words, then sets homework of eight to ten well-chosen questions.</li>
    <li><strong>Session 2: foundations and reasoning.</strong> Start with the homework, with the child talking through one answer aloud. Then twenty minutes on a foundation skill (tables, long division, fractions, integers), followed by "Figure it Out" style reasoning questions and one short written explanation.</li>
    <li><strong>Every fortnight: a mixed quiz.</strong> Ten questions from all chapters done so far, to keep older topics alive.</li>
    <li><strong>Before school tests.</strong> One session of targeted revision and one short timed test, reviewed together.</li>
  </ul>
  <p>
    Between sessions, fifteen minutes of practice on four or five days a week is enough. The tutor should keep this
    manageable; long daily worksheets at this age usually backfire.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m6-session">Inside a Class 6 session: teaching negative numbers</h2>
  <p>
    To see what good Class 6 tutoring looks like, take the chapter most children find strangest: negative numbers.
    A weak session starts with the rule "two minuses make a plus" and a page of sums. A strong session looks more like
    this:
  </p>
  <ol>
    <li><strong>A real situation first.</strong> The tutor draws a building with floors above ground and basements below, and asks: if you are on floor 2 and go down 5 floors, where are you? The child answers "basement 3" before ever seeing −3.</li>
    <li><strong>Name it.</strong> Only now does the tutor write 2 − 5 = −3 and mark it on a vertical number line.</li>
    <li><strong>Let the child explore.</strong> "Is −7 bigger or smaller than −2? Which floor is higher?" The child reasons from the picture rather than guessing.</li>
    <li><strong>Move to the horizontal number line.</strong> Adding a negative means moving left; subtracting a negative means moving right. The tutor asks the child to explain why, using the building if needed.</li>
    <li><strong>Practise and check.</strong> Ten mixed questions, then two "explain your answer" questions like the ones in the book.</li>
  </ol>
  <p>
    The same pattern of concrete example, then symbols, then explanation, works for primes, fractions and area. When
    you watch a demo, look for it.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m6-marks">Mistakes that cost marks in Class 6 school tests</h2>
  <ul>
    <li><strong>Incomplete factor lists.</strong> Missing a factor because the child did not work systematically from 1 upwards in pairs.</li>
    <li><strong>Calling 1 a prime.</strong> A tiny error that shows up in every Prime Time test.</li>
    <li><strong>Protractor misreadings.</strong> Reading 130° instead of 50° by using the wrong scale. Estimating first ("is this angle more or less than a right angle?") prevents it.</li>
    <li><strong>Adding denominators.</strong> Writing 1/2 + 1/3 = 2/5. Almost always a sign that fractions were learnt as a procedure, not as numbers.</li>
    <li><strong>Missing units.</strong> Area written in cm rather than cm², perimeter with no unit at all.</li>
    <li><strong>One-word explanations.</strong> Answering "because it is" to a reasoning question. A tutor teaches a simple structure: state the fact, then say why.</li>
    <li><strong>Untidy constructions.</strong> Blunt pencils and loose compasses. Proper equipment fixes half of the problem.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m6-signs">Signs your Class 6 child needs maths help</h2>
  <ul>
    <li><strong>A first-term dip.</strong> Marks falling noticeably in the first unit tests of middle school, even if primary results were good.</li>
    <li><strong>Blank "explain why" answers.</strong> The sums are right but the reasoning questions are skipped.</li>
    <li><strong>Negative number muddles.</strong> Answers like −3 + 5 = −8, or unsure which of two negative numbers is bigger.</li>
    <li><strong>Slow arithmetic.</strong> Still unsure of tables, which makes factors, primes and fractions painful.</li>
    <li><strong>Messy geometry.</strong> Constructions that do not close, angles measured from the wrong scale on the protractor.</li>
    <li><strong>Avoidance.</strong> Leaving maths homework until last, or "forgetting" the notebook at school.</li>
  </ul>
  <p>
    If two or three of these sound familiar, starting now is far easier than repairing the gaps in Class 8.
  </p>
  </section>

