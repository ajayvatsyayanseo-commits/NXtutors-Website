  <section class="nx-guide__sec">
  <h2 id="m6-icse">ICSE Class 6 maths</h2>
  <p>
    CISCE provides a curriculum for the years up to Class 8, and each ICSE school chooses a textbook series to teach it,
    so the exact chapter list differs between schools. Always work from your school's syllabus sheet. As a general
    picture, ICSE Class 6 maths usually includes:
  </p>
  <ul>
    <li><strong>Number system.</strong> Large numbers, whole numbers, negative numbers and integers, and number properties.</li>
    <li><strong>HCF, LCM and divisibility.</strong> Usually handled with more exercise practice than in Ganita Prakash.</li>
    <li><strong>Fractions and decimals.</strong> All four operations, often including decimals as a full topic in this year.</li>
    <li><strong>Ratio, proportion and unitary method.</strong> Commonly introduced in Class 6 in ICSE series.</li>
    <li><strong>Introductory algebra.</strong> Many ICSE schools begin algebraic expressions and simple equations in Class 6, a year ahead of the NCERT order.</li>
    <li><strong>Geometry and mensuration.</strong> Basic geometrical ideas, angles, triangles, quadrilaterals, circles, constructions, perimeter and area.</li>
    <li><strong>Data handling.</strong> Pictographs, bar graphs and simple averages in some series.</li>
  </ul>
  <p>
    ICSE Class 6 is generally broader and more drill-based. A child moving from a CBSE school into ICSE, or the other
    way, often has a gap in algebra or ratio that a tutor can close within a few weeks.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m6-hard">What is new or hard in Class 6 maths</h2>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Negative numbers</h3>
      <p>"The Other Side of Zero" asks children to accept that numbers go below zero and that −5 is less than −2. Sign rules without understanding cause errors for years.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Primes and factorisation</h3>
      <p>Finding all factors systematically, spotting primes and using prime factorisation. Children who guess rather than work in order miss factors.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Fractions on a number line</h3>
      <p>Placing 5/4 between 1 and 2, or finding a common denominator to add 2/3 and 1/4. The "fractions as numbers" idea from Class 5 must be secure.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Compass constructions</h3>
      <p>Fine motor control, accurate measurement and following a sequence of steps. Many children simply need guided practice with a good compass.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Explaining and reasoning</h3>
      <p>Ganita Prakash repeatedly asks "why?" Children who can compute but cannot put reasoning into words lose marks in school tests built on the book.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Area versus perimeter</h3>
      <p>Mixing the two, or forgetting square units. A classic confusion that hands-on work with grids fixes quickly.</p>
    </div>
  </div>
  </section>

