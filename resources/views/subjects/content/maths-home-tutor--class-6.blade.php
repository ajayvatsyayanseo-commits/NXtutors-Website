    Compared with the older NCERT Class 6 book, Ganita Prakash has fewer chapters but asks for more reasoning in each.
    Algebra and decimals are not separate chapters here; letter-numbers and further work on decimals come in Class 7.
    Classes 6 to 8 have no board exam, so assessment is set by the school, and many schools now include open-ended
    and "explain why" questions modelled on the book.
