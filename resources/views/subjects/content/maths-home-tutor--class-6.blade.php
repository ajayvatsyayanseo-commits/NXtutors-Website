  <h2 id="m6-mode">Home tutor or online tutor for Class 6?</h2>
  <p>
    Both work at this age, and the right answer depends on the child.
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Home tuition suits</h3>
      <p>Children who are easily distracted, need help organising notebooks, or are learning constructions, where the tutor can guide the compass hand directly.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Online tuition suits</h3>
      <p>Focused children, families with tight schedules or long commutes, and those wanting a particular tutor who is not nearby. The child's notebook must be visible on camera.</p>
