  <h2 id="m6-shift">The jump from primary to middle-school maths</h2>
  <p>
    In primary school, most maths questions have one method and one answer. In Class 6, children are asked to find
    patterns, make a guess, test it and explain why it works. A question might ask why the sum of the first few odd
    numbers is always a square, or how many ways a number can be written as a sum of primes. For children who like
    puzzles, this is exciting. For children who are used to copying a worked example, it can be bewildering.
  </p>
  <p>
    Organisation changes too. There may be a separate notebook for classwork, homework and practice, a geometry box
    to bring every day, and unit tests that cover several chapters at once. A child who was comfortable in Class 5 can
    lose ground in the first term simply because the pace and style are unfamiliar.
  </p>
  <p>
    A tutor in Class 6 has two jobs: close any gaps left from primary school (tables, division, fractions) and
    teach the new way of thinking, so that "explain your answer" questions stop being scary.
  </p>
  </section>

