  <h2 id="c12-entrance">Boards and entrance exams in the same year</h2>
  <p>
    Many Class 12 students are preparing for NEET or JEE at the same time as the boards. The syllabi overlap heavily,
    but the skills do not. Board papers reward complete, well-written answers with reasons and equations; entrance
    papers reward speed and the ability to pick the right option under time pressure. A tutor who works with both
    should keep separate practice for each, and should be especially careful about topics that differ between the
    two lists, such as the p-block elements, which are in the NEET syllabus but assessed only in school under the
    current CBSE curriculum. From January, most students shift their weight to the board exam until it is over, then
    back to entrance practice. See our <a href="{{ url('/blog/jee-chemistry-physicalorganicinorganic') }}">JEE
    chemistry guide</a> for the engineering side.
  </p>
