  <section class="nx-guide__sec">
  <h2 id="c12-mistakes">Where Class 12 chemistry marks are lost</h2>
  <ul>
    <li><strong>Incomplete reactions.</strong> Missing reagents or conditions over the arrow, or products written without by-products where they are asked for.</li>
    <li><strong>Wrong IUPAC names.</strong> A correct structure with the wrong name loses marks, especially in coordination compounds.</li>
    <li><strong>Units and significant figures.</strong> Molar conductivity units, rate constant units by order, and answers left with too many digits.</li>
    <li><strong>Vague reasons.</strong> "Because of stability" is not an answer. The examiner wants the specific effect: resonance, inductive effect, lanthanoid contraction.</li>
    <li><strong>Skipping case-based questions.</strong> Students panic at unfamiliar contexts. The chemistry inside is always from the syllabus.</li>
    <li><strong>Leaving inorganic too late.</strong> Two chapters of recall cannot be learned in the last fortnight.</li>
  </ul>
  </section>

