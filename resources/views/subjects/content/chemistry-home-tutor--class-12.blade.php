  <section class="nx-guide__sec">
  <h2 id="c12-organic">Organic chemistry: named reactions and conversions</h2>
  <p>
    Five organic units carry 33 marks, and most students either love them or dread them. The difference is usually
    method. Students who try to memorise each reaction as a separate fact run out of memory by Amines. Students who
    learn why reactions happen, through electron-rich and electron-poor sites, leaving groups and stability of
    intermediates, find that the same few ideas repeat.
  </p>
  <p>
    Named reactions are guaranteed marks and must be known exactly: reagent, conditions and product. The main ones
    in the NCERT Class 12 organic chapters:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Unit</th><th scope="col">Reactions and tests to know</th></tr>
    </thead>
    <tbody>
      <tr><td>Haloalkanes and Haloarenes</td><td>Finkelstein, Swarts, Sandmeyer, Wurtz, Wurtz-Fittig and Fittig reactions; SN1 and SN2 mechanisms; Friedel-Crafts reactions of haloarenes</td></tr>
      <tr><td>Alcohols, Phenols and Ethers</td><td>Kolbe's reaction, Reimer-Tiemann reaction, Williamson synthesis; acidity of phenols; dehydration of alcohols</td></tr>
      <tr><td>Aldehydes, Ketones and Carboxylic Acids</td><td>Rosenmund reduction, Stephen reaction, Etard reaction, Gattermann-Koch reaction, Clemmensen and Wolff-Kishner reductions, aldol and cross-aldol condensation, Cannizzaro reaction, Hell-Volhard-Zelinsky reaction; Tollens' and Fehling's tests</td></tr>
      <tr><td>Amines</td><td>Gabriel phthalimide synthesis, Hoffmann bromamide degradation, carbylamine reaction, Hinsberg's test, diazotisation and coupling reactions</td></tr>
      <tr><td>Biomolecules</td><td>Structures of glucose and fructose, peptide bond, levels of protein structure, DNA and RNA; mostly recall</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Conversions are where named reactions become marks. A typical question asks the student to convert, say,
    benzene to a particular amine or an alcohol to a ketone with one more carbon, in two or three steps. A tutor
    should build this skill deliberately:
  </p>
  <ul>
    <li><strong>A reaction map.</strong> One large sheet linking every functional group to the others by reagent. The student builds it, not the tutor, and adds to it after every chapter.</li>
    <li><strong>Daily conversions.</strong> Three or four short conversions in every session from October onwards, mixing chapters so the student has to search the map.</li>
    <li><strong>Mechanisms where the syllabus asks for them.</strong> SN1 and SN2, dehydration of alcohols, nucleophilic addition to carbonyls. Writing curved arrows correctly is itself marked.</li>
    <li><strong>"Give reasons" practice.</strong> Why phenol is more acidic than ethanol, why aniline is a weaker base than ethylamine. These answers come from electronic effects learned in Class 11.</li>
  </ul>
