  <p>
    Add the branches up and the picture is clear: organic chemistry is 33 marks, physical 23 and inorganic 14.
    Electrochemistry, at 9 marks, is the heaviest single unit, and Aldehydes, Ketones and Carboxylic Acids, at 8, is
    the heaviest organic one. A Class 12 chemistry tutor should plan time roughly in that proportion, adjusted for the
    student's weak branch.
