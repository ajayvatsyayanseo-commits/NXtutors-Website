  <h2 id="c12-paper">How the Class 12 chemistry paper is built</h2>
  <p>
    CBSE's 2026-27 question-paper design does not fix a chapter-wise weightage within each question type, but it does
    fix the mix of thinking skills:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Type of question</th><th scope="col">Marks out of 70</th></tr>
    </thead>
    <tbody>
      <tr><td>Remembering and understanding</td><td>28 (40%)</td></tr>
      <tr><td>Applying</td><td>21 (30%)</td></tr>
      <tr><td>Analysing, evaluating and creating</td><td>21 (30%)</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    There is no overall choice, and about a third of the questions offer an internal choice. In recent CBSE papers,
    the applying and analysing marks typically come through multiple-choice and assertion-reason items, case-based
    questions built on an unseen passage or data, organic conversions and "give reasons" questions. The exact section
    layout is set in CBSE's sample question paper each year, and a tutor should use the latest one as the model for
    practice papers.
  </p>
  <p>
    The practical lesson: a student who has only read NCERT will know the facts for the 40% but may freeze on a
    case study about an unfamiliar cell or reaction. Regular practice with unseen questions is the fix.
  </p>
