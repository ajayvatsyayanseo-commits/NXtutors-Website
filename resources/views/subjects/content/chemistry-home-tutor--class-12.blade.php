  <section class="nx-guide__sec">
  <h2 id="c12-physical">Physical chemistry: solutions, electrochemistry and kinetics</h2>
  <p>
    The three physical units are worth 23 marks and are the most reliable marks on the paper for a student who has
    practised. They are also where careless arithmetic costs most.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Solutions (7 marks)</h3>
  <p>
    Concentration terms (molarity, molality, mole fraction), Henry's law, Raoult's law, ideal and non-ideal
    solutions, and the four colligative properties used to find molar mass, including the van't Hoff factor for
    abnormal molar masses. The common errors are mixing up molarity and molality and forgetting the van't Hoff factor
    for electrolytes.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Electrochemistry (9 marks)</h3>
  <p>
    Galvanic cells, standard electrode potentials, the Nernst equation, the link between cell potential and Gibbs
    energy, conductance and molar conductivity, Kohlrausch's law, electrolysis and Faraday's laws, batteries, fuel
    cells and corrosion. Nernst-equation numericals with logarithms are a board favourite; the student must be sure
    about which species goes on top of the ratio.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Chemical Kinetics (7 marks)</h3>
  <p>
    Rate and rate law, order and molecularity, integrated rate equations for zero- and first-order reactions,
    half-life, and temperature dependence through the Arrhenius equation. Students need to read graphs confidently:
    which plot is a straight line for which order, and what the slope means.
  </p>
      </div>
    </div>
  <p>
    A good tutor gives these units a numerical set every week, even while teaching organic, so the skills do not fade.
    Practice should be done without a calculator or log tables, using sensible approximations, because CBSE's
    sample paper allows neither in the exam hall; the student should always write units and state the final answer clearly.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="c12-inorganic">Inorganic chemistry: d- and f-block and coordination compounds</h2>
  <p>
    These two units carry 14 marks together. Inorganic chemistry in Class 12 is largely NCERT recall with reasoning
    behind it, which suits students who revise steadily and hurts those who leave it until February.
  </p>
  <p>
    <strong>d- and f-Block Elements.</strong> Electronic configurations of transition elements, trends in atomic size,
    ionisation enthalpy, oxidation states, colour, magnetic behaviour and catalytic properties; the preparation and
    properties of potassium dichromate and potassium permanganate; and the lanthanoids and actinoids, including
    lanthanoid contraction and its consequences. Most questions are "explain why" questions: why Zn, Cd and Hg are
    soft, why Mn shows the most oxidation states in the first series, why Cu<sup>+</sup> is unstable in water. A tutor
    should drill these as short spoken answers until they are fluent.
  </p>
  <p>
    <strong>Coordination Compounds.</strong> Werner's theory, key terms such as ligand, coordination number and
    denticity, IUPAC nomenclature, structural and stereoisomerism, bonding through valence bond theory and crystal
    field theory, metal carbonyls, and applications. Nomenclature and isomerism are reliable marks; crystal field
    splitting and predicting magnetic behaviour need hybridisation from Class 11, so a student weak in Class 11
    bonding will need a short refresher here.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="c12-formative">Topics taught in Class 12 but assessed only in school</h2>
  <p>
    The 2026-27 curriculum keeps four topics in the syllabus for formative assessment only, meaning they are not part
    of the board theory paper:
  </p>
  <ul>
    <li><strong>Surface chemistry.</strong> Adsorption, colloids, coagulation and emulsions.</li>
    <li><strong>General principles and processes of isolation of elements.</strong> Concentration, oxidation, reduction, electrolytic methods and refining.</li>
    <li><strong>Polymers.</strong> Polymerisation, homopolymers and copolymers.</li>
    <li><strong>Chemistry in everyday life.</strong> Chemicals in medicines and in food.</li>
  </ul>
  <p>
    For a board-only student these deserve only light attention. Some related practical experiments, such as
    preparing sols, remain in the practical list, so the basic ideas are still worth knowing. Students preparing for
    entrance exams should check their exam's own syllabus rather than assume the board list applies.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="c12-practical">The Class 12 chemistry practical exam</h2>
  <p>
    Thirty marks, nearly a third of the subject total, come from the practical exam. The curriculum splits them as
    volumetric analysis 8, salt analysis 8, a content-based experiment 6, project work 4, and class record and viva 4.
  </p>
  <ul>
    <li><strong>Volumetric analysis.</strong> Titrating potassium permanganate against standard oxalic acid or Mohr's salt, with the student preparing the standard solution by weighing. The calculation and the equivalence relationship must be secure.</li>
    <li><strong>Salt analysis.</strong> Identifying one cation and one anion in a given salt. Students do well when they understand the logic of the group scheme instead of memorising a flowchart.</li>
    <li><strong>Content-based experiments.</strong> Options include kinetics experiments with sodium thiosulphate, enthalpy of neutralisation, cell potential variation, paper chromatography, preparation of inorganic and organic compounds, and functional-group tests.</li>
    <li><strong>Viva and record.</strong> Questions on principle, procedure, precautions and sources of error. Easy marks if the student has prepared a few answers for each experiment.</li>
  </ul>
  <p>
    A tutor can rehearse viva questions, check titration calculations and walk through the salt-analysis logic so the
    student arrives at the lab confident.
  </p>
  </section>

