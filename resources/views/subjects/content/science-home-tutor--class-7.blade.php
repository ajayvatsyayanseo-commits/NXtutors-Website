  <p>
    Count the strands and you see why Class 7 feels busy: four physics chapters, three chemistry chapters and three
    biology chapters, plus earth and space. A tutor's first job is to show how they connect, so the year feels like
    one subject rather than eleven unrelated topics.
  </p>
