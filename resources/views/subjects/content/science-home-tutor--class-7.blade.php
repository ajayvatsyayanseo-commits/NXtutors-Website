  <section class="nx-guide__sec">
  <h2 id="s7-week">A weekly plan for Class 7 science</h2>
  <p>
    Two tutor sessions a week of about an hour suit most Class 7 students. A steady week could run like this:
  </p>
  <ul>
    <li><strong>Session one.</strong> Five-minute recall of earlier chapters, then the new idea, taught through the book's activity or a demonstration. End with the chapter's key diagram, drawn by the student.</li>
    <li><strong>Between sessions (20 to 30 minutes).</strong> Answer the in-text questions and do one home activity with a short write-up.</li>
    <li><strong>Session two.</strong> End-of-chapter questions, including the longer "explain" and "what would happen if" questions; one or two speed numericals or circuit drawings where the chapter needs them.</li>
    <li><strong>Weekend (15 minutes).</strong> Update a running glossary of new terms, one line each, across all chapters.</li>
  </ul>
  <p>
    Before half-yearly and annual exams, the tutor should switch to mixed practice across chapters and a couple of
    timed papers set in the school's format.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s7-signs">Signs your Class 7 child needs help with science</h2>
  <ul>
    <li><strong>Marks dropping from Class 6.</strong> Often a sign that the child could manage descriptive chapters but not the reasoning ones.</li>
    <li><strong>Mixed-up terms.</strong> Conduction and convection, acid and base, reflection and refraction used interchangeably.</li>
    <li><strong>Speed questions left blank.</strong> A reluctance with formulas usually starts here and grows in Class 8 and 9.</li>
    <li><strong>Diagrams avoided.</strong> Circuit and ray diagrams skipped or drawn freehand without labels.</li>
    <li><strong>Long answers that miss the point.</strong> Lots of writing but no clear reason or conclusion.</li>
    <li><strong>No questions asked.</strong> A child who has stopped asking "why" in science has often stopped following.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s7-choose">Choosing a Class 7 science tutor: what to check in the demo</h2>
  <ul>
    <li><strong>Knowledge of the new book.</strong> Ask how they teach <em>Heat Transfer in Nature</em> or which activities they use for the electricity chapter. They should know the Class 7 <em>Curiosity</em> chapters, not an older syllabus.</li>
    <li><strong>A real demonstration.</strong> Even online, a good tutor can show a circuit, an indicator test or a mirror image on camera.</li>
    <li><strong>Reasoning, not dictation.</strong> Does the tutor ask your child to predict and explain, or simply dictate notes?</li>
    <li><strong>Handling of mistakes.</strong> When your child says something wrong, does the tutor ask a follow-up question that lets them find the error?</li>
    <li><strong>Comfort with sensitive topics.</strong> For the adolescence chapter, ask how they approach it. You want a matter-of-fact answer.</li>
    <li><strong>A plan to the next exam.</strong> The tutor should be able to outline the chapters they will cover before the school's next test.</li>
  </ul>
