  <section class="nx-guide__sec">
  <h2 id="s7-skills">Diagrams and practical skills that matter in Class 7</h2>
  <ul>
    <li><strong>Circuit diagrams.</strong> Standard symbols for a cell, battery, switch (open and closed), bulb and wire, drawn with a ruler. This is a new kind of drawing and it is worth practising little and often.</li>
    <li><strong>Ray diagrams for reflection.</strong> The incident ray, reflected ray and normal, with arrows. Plane-mirror images and the periscope are the likely test figures.</li>
    <li><strong>Biology diagrams.</strong> The human digestive system, a leaf showing stomata in outline, and water moving up a plant. Labels matter more than artistic skill.</li>
    <li><strong>Arrow diagrams.</strong> Land and sea breezes, convection currents and the water cycle all need arrows showing direction, with a short label.</li>
    <li><strong>Tables of readings.</strong> Time for 20 oscillations, distance and time for a moving object, rusting over several days. Headings, units and a conclusion.</li>
    <li><strong>Simple calculations.</strong> Speed, distance and time, with units and conversions. This is the first place in science where maths skills show up directly.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s7-next">How Class 7 prepares the ground for Class 8</h2>
  <p>
    The Class 8 <em>Curiosity</em> book builds straight on this year:
  </p>
  <ul>
    <li><strong>Circuits lead to magnetic and heating effects of current.</strong> A child who can draw and reason about a simple circuit is ready for electromagnets and the heating effect of current.</li>
    <li><strong>Heat transfer and breezes lead to pressure, winds, storms and cyclones.</strong> The idea of warm air rising is used again directly.</li>
    <li><strong>Physical and chemical changes and metals lead to particles, elements, compounds and mixtures.</strong> Class 8 explains, at the level of particles, what Class 7 described.</li>
    <li><strong>Reflection in plane mirrors leads to spherical mirrors and lenses.</strong></li>
    <li><strong>Life processes lead to cells, microorganisms and health.</strong></li>
    <li><strong>Eclipses and the night sky lead to the phases of the Moon and calendars.</strong></li>
  </ul>
