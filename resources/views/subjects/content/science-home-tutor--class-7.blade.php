  <section class="nx-guide__sec">
  <h2 id="s7-hard">The Class 7 chapters that trip students up</h2>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Electricity: Circuits and their Components</h3>
  <p>
    Children often know that a bulb needs a cell but cannot say why a circuit must be closed, or draw the symbols
    correctly. Drawing each real circuit as a diagram, and each diagram as a real circuit, fixes this.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Exploring Substances</h3>
  <p>
    The colour changes of litmus and turmeric are easy to mix up. A simple two-column table (acid, base) for each
    indicator, made after doing the test, sticks far better than a list read from the book.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Physical and Chemical Changes</h3>
  <p>
    Deciding whether a change is physical or chemical needs a reason, not a guess: is a new substance formed, and can
    the change be easily reversed? Rusting and combustion are the standard test cases.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Measurement of Time and Motion</h3>
  <p>
    The first formula of the year. Students confuse speed, distance and time, forget units such as m/s and km/h, and
    struggle to tell uniform from non-uniform motion from a table of readings.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Heat Transfer in Nature</h3>
  <p>
    Conduction, convection and radiation are easy to define and hard to apply. Land and sea breezes need a diagram with
    arrows and a clear statement of which surface heats faster.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Life Processes in Plants</h3>
  <p>
    Photosynthesis needs its raw materials, conditions and products stated exactly. Transport of water and food is
    where students confuse the two vessels, so a labelled diagram helps.
  </p>
      </div>
    </div>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s7-icse">ICSE Class 7 science</h2>
  <p>
    ICSE schools do not use a single CISCE-prescribed Class 7 textbook. Most teach physics, chemistry and biology as
    separate strands, often from separate books, and the topics broadly overlap with the NCERT list above: physical and
    chemical changes, elements and compounds, heat and light, electricity and magnetism, nutrition, respiration and
    the plant and animal kingdoms. ICSE books tend to introduce more terms and definitions a little earlier, and the
    chemistry strand often starts on symbols and simple formulae in these middle years.
  </p>
  <p>
    Because the list varies by school, share the school's book list and test schedule when you ask for a tutor. For
    ICSE families, a tutor who keeps three notebooks in step, one per science, is worth a great deal.
  </p>
  </section>

