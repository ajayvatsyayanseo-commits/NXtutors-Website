  <h2 id="s7-shift">Why Class 7 science feels different from Class 6</h2>
  <p>
    In Class 6, most chapters describe things a child can see and touch: leaves, magnets, water evaporating. Class 7
    moves one step behind what is visible. Why does turmeric turn red in soapy water? Why does a wire need to make a
    complete loop for a bulb to glow? Why does a steel spoon in hot tea get hot at the handle? The answers involve
    invisible things, such as the nature of a substance, current in a circuit or the movement of heat, and children
    have to reason about them.
  </p>
  <p>
    Class 7 also brings the first real formula, speed as distance divided by time, and the first circuit symbols.
    And it includes <em>Adolescence: A Stage of Growth and Change</em>, a chapter many children find awkward to
    discuss. A calm, matter-of-fact teacher makes a real difference there.
  </p>
  </section>

