  <h2 id="en-cbse">How CBSE examines English</h2>
  <p>
    CBSE offers English Language and Literature in Classes 9 and 10 and English Core in Classes 11 and 12. In each case
    the board paper is out of 80 and the school awards 20 more through internal assessment. The split of the 80 marks
    tells a tutor where to spend time. From CBSE's 2026-27 curriculum:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>CBSE English board papers, 2026-27 curriculum</caption>
    <thead>
      <tr><th scope="col">Section</th><th scope="col">Class 10</th><th scope="col">Class 11</th><th scope="col">Class 12</th></tr>
    </thead>
    <tbody>
      <tr><td>Reading (unseen passages)</td><td>20</td><td>26</td><td>22</td></tr>
      <tr><td>Writing and grammar</td><td>20 (grammar 10, writing 10)</td><td>23 (grammar 7, creative writing 16)</td><td>18 (creative writing only)</td></tr>
      <tr><td>Literature</td><td>40</td><td>31</td><td>40</td></tr>
      <tr><td>Prescribed NCERT books</td><td>First Flight, Footprints without Feet</td><td>Hornbill, Snapshots</td><td>Flamingo, Vistas</td></tr>
      <tr><td>Internal assessment</td><td>20, including 5 for listening and speaking</td><td>20: listening 5, speaking 5, project 10</td><td>20: listening 5, speaking 5, project 10</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    In Class 10 the reading section has a discursive passage and a case-based factual passage with a chart or data, and
    the writing tasks are a formal letter and an analytical paragraph on a map, chart or graph. Literature is half the
    paper, so a student who has read the chapters but cannot write a structured 100 to 120 word answer loses marks that
    are easy to recover with practice. Our <a href="{{ url('/class-10-home-tutor-gurgaon') }}">Class 10 tutor guide</a>
    shows how English fits into a whole board-year plan.
  </p>
  <p>
    In Class 12 grammar leaves the paper, and the writing tasks are marked on format, content and accuracy. The
    literature section asks for longer answers that connect themes across chapters, which is where many students who
    were comfortable in Class 10 start to slip.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="en-cisce">ICSE and ISC English</h2>
  <p>
    CISCE treats English as two subjects, language and literature, each with its own paper. That makes it heavier than
    CBSE English and it rewards students who read widely and write at length.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>ICSE (Classes 9 and 10)</h3>
  <p>
    Paper 1, English Language, and Paper 2, Literature in English, are each two hours and 80 marks, with 20 marks of
    internal assessment for each. Paper 1 asks for a composition of about 300 to 350 words, a formal or friendly
    letter, a notice with a matching e-mail, an unseen passage of about 500 words with vocabulary, short answers and a
    summary, and a compulsory grammar question on prepositions, conjunctions, verbs and sentence structure. The
    language internal assessment is 10 marks for listening and 10 for speaking. Paper 2 covers a play, short stories
    and poems from the prescribed texts. Our notes on <a href="{{ url('/blog/icse-class-10-english-papers') }}">ICSE
    Class 10 English papers</a> go question by question.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>ISC (Classes 11 and 12)</h3>
  <p>
    English Language and Literature in English are each a three-hour theory paper of 80 marks plus 20 marks of project
    work. The language paper has a composition of 400 to 450 words chosen from six topics (narrative, descriptive,
    reflective, argumentative, discursive or a short story), directed writing, a proposal in CISCE's format, grammar
    and comprehension. The literature paper tests drama, short stories and poetry, including the style of a poem, not
    just its content. See our guide to <a href="{{ url('/blog/isc-class-12-english-literaturelanguage') }}">ISC Class 12
    English</a>.
  </p>
      </div>
    </div>
  <p>
    For an ICSE or ISC student, the tutor's most valuable job is usually timed writing. Two-hour and three-hour papers
    with long compositions punish a student who writes slowly or plans badly, and only regular practice under the
    clock fixes that.
  </p>
  </section>

