  <h2 id="enGuideTitle">English home tutor: reading, writing, grammar and speaking, class by class</h2>

  <p class="nx-guide__lede">
    English is the subject families most often leave to chance. A child reads, speaks and writes it every day, so it
    feels as if it should look after itself. Then a Class 10 paper comes back with marks lost on a letter format, or a
    Grade 8 student joins an international school and cannot keep up with the reading, or a seven-year-old still
    guesses at words instead of reading them. English tuition works when it is aimed at the skill that is actually
    weak, not at "English" as a whole. This guide explains the four skills a tutor should work on, what changes from
    early reading to the senior years, how CBSE, ICSE, ISC, Cambridge IGCSE and IB examine the subject, and how to
    judge an English tutor in a single demo class.
  </p>

