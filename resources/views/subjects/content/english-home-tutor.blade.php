  <h2 id="en-skills">What should an English tutor actually work on?</h2>
  <p>
    Every board splits English into roughly the same four skills, even if the papers weight them differently. A useful
    tutor finds out which of the four is costing your child marks or confidence, and spends most of the time there.
  </p>
  <ul>
    <li><strong>Reading.</strong> For young children this means decoding: turning letters into sounds and sounds into words, then reading smoothly enough that meaning comes through. For older students it means comprehension under time: finding the main idea, inferring what is not stated, and handling unfamiliar vocabulary from context.</li>
    <li><strong>Writing.</strong> Planning before writing, paragraphing, choosing a register that fits the task, and knowing the formats a board expects: letters, notices, e-mails, articles, analytical paragraphs, proposals and compositions. Most marks lost in writing come from structure and format, not from vocabulary.</li>
    <li><strong>Grammar and usage.</strong> Tenses, subject-verb agreement, reported speech, modals, prepositions and sentence structure. Grammar sticks far better when it is taught inside the student's own writing than when it is drilled as a separate set of worksheets.</li>
    <li><strong>Speaking and listening.</strong> Increasingly assessed in school: CBSE, ICSE, ISC and Cambridge all have a listening and speaking element, and it also matters for interviews, presentations and a child's confidence in class.</li>
  </ul>
  <p>
    Literature sits across all four. Board literature answers reward a student who can quote or refer to the text,
    explain a character's motive or a poet's choice, and do it in the word limit. That is a writing skill as much as a
    reading one, and it can be taught.
  </p>
  </section>

