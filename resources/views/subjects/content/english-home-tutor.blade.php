  <h2 id="en-intl">Cambridge IGCSE and IB English</h2>
  <p>
    International boards examine English as analysis and communication rather than as prescribed chapters. Two
    decisions matter here: which IGCSE English your child is entered for, and how an IB student handles unseen texts
    and the oral.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>Cambridge IGCSE English: First Language (0500) and Second Language (0510), syllabuses for 2027 to 2029</caption>
    <thead>
      <tr><th scope="col"></th><th scope="col">First Language English 0500</th><th scope="col">English as a Second Language 0510</th></tr>
    </thead>
    <tbody>
      <tr><td>Intended for</td><td>Students whose first language is English</td><td>Students learning English as an additional language</td></tr>
      <tr><td>Written assessment</td><td>Paper 1 Reading (2 hours, 80 marks, 50%), plus either Paper 2 Directed Writing and Composition (2 hours, 80 marks) or a Coursework Portfolio of three assignments</td><td>Reading and Writing (2 hours, 60 marks, 70%) and Listening (about 50 minutes, 40 marks, 30%)</td></tr>
      <tr><td>Speaking</td><td>Optional Speaking and Listening test, reported separately</td><td>Speaking test of 10 to 15 minutes, reported separately on 0510; counted in the grade on 0511</td></tr>
      <tr><td>Grades</td><td>A* to G</td><td>A* to G</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The school decides the entry, but parents should know which one it is: First Language rewards analysis of how a
    writer uses language and extended composition, while Second Language rewards accurate understanding and clear,
    correct writing for a purpose. A tutor preparing a child for the wrong one wastes months.
  </p>
  <p>
    <strong>IB Language A: Language and Literature</strong> is studied at SL or HL. Paper 1 is a guided analysis of
    unseen non-literary texts, such as an advertisement, speech or article; Paper 2 is a comparative essay on two
    literary works studied in class; and every student gives a 15-minute individual oral, 10 minutes prepared and 5
    minutes of questions, on how a global issue is presented in texts they have studied. HL students also write an
    essay of 1,200 to 1,500 words. At SL the weighting is Paper 1 35%, Paper 2 35% and the oral 30%; at HL it is 35%,
    25%, 20% and 20% for the essay. A tutor can coach analysis and give feedback on plans, but coursework must remain
    the student's own work. Families moving between boards may find our
    <a href="{{ url('/blog/switching-cbse-to-ib-or-igcse-gurgaon') }}">guide to switching from CBSE to IB or IGCSE</a>
    useful.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="en-signs">Signs your child may need an English tutor</h2>
  <ul>
    <li><strong>Reading avoidance.</strong> A child who never picks up a book by choice often finds reading effortful, not boring. Listen to them read a page aloud: frequent guessing, skipped words or losing the line point to a fluency problem.</li>
    <li><strong>Good ideas, weak marks.</strong> The student clearly understood the chapter but the answer lost marks for length, structure or missing the point asked. That is an exam-writing gap, and it responds quickly to practice with feedback.</li>
    <li><strong>The same grammar errors every time.</strong> Tense shifts, missing articles or agreement mistakes that survive every correction in the school notebook.</li>
    <li><strong>Running out of time.</strong> Unfinished compositions or a skipped comprehension section in two- and three-hour papers.</li>
    <li><strong>A change of board or country.</strong> Moving from a state board to CBSE, from CBSE to IGCSE, or into an English-medium school for the first time changes what is expected, often suddenly.</li>
    <li><strong>Reluctance to speak.</strong> A child who understands English well but will not answer in class or freezes in an oral assessment.</li>
  </ul>
  <p>
    Spoken confidence is a separate goal from board marks, and some families want both. Our
    <a href="{{ url('/blog/spoken-english-for-students') }}">spoken English guide for students</a> explains what helps.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="en-session">What a good English session looks like</h2>
  <p>
    English sessions look different from maths or science sessions: less explaining, more reading, writing and
    rewriting. A well-planned hour with a Class 7 to 12 student usually includes:
  </p>
  <ol>
    <li><strong>A short read.</strong> An unseen passage, a poem or a page of the set text, read aloud or silently, followed by two or three questions that go beyond the obvious.</li>
    <li><strong>Feedback on last week's writing.</strong> Not a page covered in red, but two or three priorities: "your paragraphs have no topic sentence" or "you keep switching between past and present".</li>
    <li><strong>A redraft.</strong> The student rewrites one paragraph using the feedback. This is where most improvement happens, and it is the step most often skipped.</li>
    <li><strong>A focused skill.</strong> A letter format, a summary technique, a grammar point drawn from the student's own mistakes, or planning a literature answer.</li>
    <li><strong>A timed task</strong> near exams, followed by marking against the board's scheme so the student sees where marks go.</li>
  </ol>
  <p>
    With younger children the session is shorter and livelier: reading aloud together, sounding out new words, talking
    about the story, and a few minutes of writing. A tutor who sets a comprehension worksheet and checks it at the end
    is not teaching reading.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="en-demo">How to judge an English tutor in the demo class</h2>
  <p>
    The first class is a free demo. English teaching quality is easy to see if you know what to look for. Bring a piece
    of your child's recent written work or a marked school paper, and watch for these:
  </p>
  <ol>
    <li><strong>Did the tutor read your child's writing before teaching?</strong> A good English tutor diagnoses from real work, not from a textbook chapter.</li>
    <li><strong>Were the corrections prioritised?</strong> Fixing everything at once teaches nothing. Two clear targets are better than twenty ticks and crosses.</li>
    <li><strong>Did your child write, not just listen?</strong> Improvement in English comes from producing language, so the student should have written or spoken for a good part of the hour.</li>
    <li><strong>Does the tutor know the paper?</strong> Ask what the writing tasks are on your child's board and how they are marked. For IGCSE, ask whether they have taught First Language or Second Language.</li>
    <li><strong>Can they make literature come alive?</strong> Ask them to explain a poem your child found dull. A good tutor gets the student talking about it within minutes.</li>
    <li><strong>Did they suggest reading?</strong> Tutors who teach English well almost always ask what the child reads at home and suggest something next.</li>
  </ol>
  <p>
    If the fit is wrong, tell us and we arrange a demo with the next tutor on the shortlist; switching later is free as
    well.
