  <h2 id="m11-plan">A plan for the Class 11 year</h2>
  <p>
    Schools order the chapters differently, so the tutor should follow the school timetable. This is a typical shape
    for a CBSE student who starts in April:
  </p>
  <ul>
    <li><strong>April and May.</strong> Sets, relations and functions. Spend real time on graphs of standard functions; they pay back all year. Quick check of Class 10 algebra and trigonometry.</li>
    <li><strong>June.</strong> Trigonometric functions, with identities practised every session until they are fluent. Summer break is the time to get ahead here.</li>
    <li><strong>July.</strong> Complex numbers, linear inequalities, permutations and combinations. First periodic test in many schools.</li>
    <li><strong>August.</strong> Binomial theorem, sequence and series.</li>
    <li><strong>September.</strong> Straight lines, then half-yearly exams. Review the paper chapter by chapter.</li>
    <li><strong>October and November.</strong> Conic sections and 3D geometry, then limits and derivatives. Keep calculus unhurried; it is Class 12's backbone.</li>
    <li><strong>December.</strong> Statistics and probability. Complete the lab-manual activities for internal assessment.</li>
    <li><strong>January and February.</strong> Mixed revision and full timed papers. Identify the two weakest chapters and rebuild them.</li>
    <li><strong>March.</strong> Year-end exams, then a short, targeted review before Class 12 begins, especially functions, trigonometry and derivatives.</li>
  </ul>
  <p>
    JEE students will run a parallel track of harder problems from the same chapters. A student who joins a tutor
    mid-year should begin with functions and trigonometry, even if the school has moved on, because nearly every
    later chapter depends on them.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m11-mistakes">Where Class 11 students lose marks</h2>
  <ul>
    <li><strong>Ignoring domains.</strong> Cancelling terms or taking logarithms without checking where the function is defined.</li>
    <li><strong>Degrees and radians.</strong> Mixing the two, especially in limits and graphs.</li>
    <li><strong>Memorising identities without deriving them.</strong> Students who can derive the compound-angle and double-angle formulae forget far fewer of them under exam pressure.</li>
    <li><strong>Overcounting and undercounting.</strong> Using permutations where order does not matter, or double-counting cases.</li>
    <li><strong>Limits by substitution alone.</strong> Plugging in values and writing 0/0 as the answer instead of simplifying first.</li>
    <li><strong>Conic confusion.</strong> Muddling the standard forms and properties of the ellipse and hyperbola. A comparison table the student writes themselves helps.</li>
    <li><strong>Skipped steps.</strong> School examiners mark method. A correct final answer with missing working often scores less than a small slip with full working.</li>
    <li><strong>Leaving Class 11 gaps for Class 12.</strong> They do not close by themselves; they widen.</li>
  </ul>
  </section>

