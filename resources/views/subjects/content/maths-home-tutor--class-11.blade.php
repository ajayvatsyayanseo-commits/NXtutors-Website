  <h2 id="m11GuideTitle">Maths home tutor for Class 11: CBSE, ISC and a JEE-ready foundation</h2>

  <p class="nx-guide__lede">
    Class 11 maths is the biggest single jump in a student's school career. It is common for students who did well in
    Class 10 to see their marks drop sharply in the first Class 11 tests, and many families only realise how steep the
    climb is after the half-yearly. The reason is simple: Class 11 introduces a new kind of mathematics, built on
    functions, abstraction and long chains of reasoning, and it does so at speed. This guide covers the CBSE Class 11
    maths syllabus and marks for 2026-27, what ISC students study, why the jump from Class 10 is so hard, how Class 11
    underpins JEE, and how a maths home tutor should spend the year.
  </p>

