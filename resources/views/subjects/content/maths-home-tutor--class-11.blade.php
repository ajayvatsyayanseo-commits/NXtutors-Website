  <section class="nx-guide__sec">
  <h2 id="m11-formative">Topics taught but not examined in the CBSE paper</h2>
  <p>
    CBSE's 2026-27 curriculum lists a set of Class 11 topics that are to be assessed only formatively, meaning they
    are taught and practised but do not add to the year-end summative assessment. They include composition of
    functions, general solutions of trigonometric equations, mathematical induction, polar form of complex numbers,
    graphical solution of linear inequalities in two variables, general and middle terms of a binomial expansion, sums
    of n, n² and n³, the normal and general forms of a line, the section formula in 3D, the chain rule, and sample
    spaces for random experiments.
  </p>
  <p>
    For a student who only needs the school exam, these can be treated lightly. For a student preparing for JEE,
    many of them matter a great deal: general solutions, induction-style reasoning, binomial general terms and the
    chain rule all appear in entrance problems. A good tutor will ask about the student's goals before deciding how
    much time these get.
  </p>
  </section>

