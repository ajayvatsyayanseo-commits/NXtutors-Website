  <h2 id="m11-isc">ISC Class 11 maths</h2>
  <p>
    ISC Mathematics in Class 11 follows the CISCE syllabus and is examined by the school: a theory paper of 80 marks
    and project work of 20 marks. The theory is organised into a compulsory core section and further sections from
    which the student attempts one, an arrangement that continues into Class 12. The broad areas are the same as
    CBSE, namely sets and functions (including trigonometry), algebra, coordinate geometry, calculus, and statistics
    and probability, though the depth and ordering differ and ISC papers are known for long, multi-part questions.
  </p>
  <p>
    Two practical points for ISC families. First, ISC expects fully worked solutions, so the same habits of
    presentation that matter in Class 12 should be built now. Second, the project work is a real 20 marks; a tutor can
    help plan it early rather than in the last fortnight. Check the current CISCE regulations for the exact section
    marks for your year. Gurugram families can also look at our
