    Geometry and Algebra together carry 45 of the 80 marks and take up most of the teaching periods. Those are the
    two units where a tutor's time goes furthest. The paper design mirrors Class 10: roughly 54% of marks for
    remembering and understanding, 24% for applying, and 22% for analysing, evaluating and creating. In other words,
    nearly half the paper asks students to use ideas in unfamiliar situations, exactly the skill the Class 10 board
    paper rewards.
  </p>
