  <section class="nx-guide__sec">
  <h2 id="m9-plan">A plan for the Class 9 year</h2>
  <p>
    Class 9 has no fixed board calendar, so the plan follows the school. This is a sensible shape for a student who
    starts with a tutor in April:
  </p>
  <ul>
    <li><strong>April.</strong> A diagnostic on Class 8 skills: fractions, negative numbers, expanding brackets, linear equations, angle facts. Fix what is weak before it is needed. Begin Number System.</li>
    <li><strong>May and June.</strong> The best use of the summer break is algebra: polynomials, identities and factorisation, practised little and often until they are automatic. Start sequences.</li>
    <li><strong>July and August.</strong> Linear equations in two variables, coordinate geometry, and the start of Euclid and lines and angles. Introduce proof writing gently, one reason per line.</li>
    <li><strong>September.</strong> Triangles and congruence. Half-yearly exams in many schools; go through the marked paper mistake by mistake.</li>
    <li><strong>October and November.</strong> Quadrilaterals and circles, the heaviest proof chapters, then area and perimeter.</li>
    <li><strong>December.</strong> Surface area and volume, statistics and probability. Keep the portfolio and lab activities up to date for internal assessment.</li>
    <li><strong>January and February.</strong> Mixed revision and full timed papers in the school's format. Rewrite key proofs from memory and understanding, not by copying.</li>
    <li><strong>March.</strong> Year-end exams, then a short break before a gentle start on Class 10 in April.</li>
  </ul>
  <p>
    For ICSE, move logarithms, indices and compound interest into the early months and give trigonometry its own
    block in the second term. Starting mid-year still works; the tutor simply focuses on the current chapters while
    patching the foundations those chapters depend on.
  </p>
