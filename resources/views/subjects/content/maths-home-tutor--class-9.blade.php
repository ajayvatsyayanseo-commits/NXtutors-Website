  <section class="nx-guide__sec">
  <h2 id="m9-chapters">The Class 9 chapters, and where students struggle</h2>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Number System</h3>
      <p>Rational numbers and their density, decimal expansions, irrational numbers, the square root spiral, and proofs that √2 and √3 are irrational. The proofs are short but unforgiving: each line must follow from the one before.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Polynomials and linear patterns</h3>
      <p>The new book introduces polynomials through linear growth and decay, slope and y-intercept. Students who treat y = ax + b as a formula rather than a relationship find the graph questions hard.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Sequences and Progressions</h3>
      <p>Recursive and explicit rules, the nth term of an AP and a GP, the sum of the first n natural numbers, fractals and the Tower of Hanoi. Confusing a term with its position is the classic slip.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Algebraic Identities</h3>
      <p>Identities shown with geometric models and algebra tiles, factorisation of quadratics, and simplifying rational expressions. This is the engine room of Class 10 algebra; weak factorisation here causes trouble for two years.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Linear Equations in Two Variables</h3>
      <p>Graphing a pair of lines, consistency and inconsistency, and solving by substitution and elimination, then modelling real situations. Word problems are where marks are lost, usually at the "form the equations" step.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Coordinate Geometry</h3>
      <p>Only 4 marks, but the distance and midpoint formulae reappear in quadrilaterals and in Class 10. Checking collinearity and right angles with coordinates is a neat, scoring skill.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Euclid, Lines and Angles, Triangles</h3>
      <p>Axioms and postulates, the linear pair theorem, parallel lines, and congruence by SAS, SSS, ASA, AAS and RHS. Students must write proofs with reasons, and learn why SSA usually fails.</p>
    </div>
    <div class="nx-guide__card">
      <h3>4-gons and Circles</h3>
      <p>Parallelogram characterisations, the midpoint theorem and its converse, concurrency of medians, then chord properties, angles subtended by arcs and cyclic quadrilaterals. The most proof-heavy stretch of the year.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Mensuration</h3>
      <p>Perimeter and arc length, Heron's formula, area of a circle and sector, Brahmagupta's formula, then surface area and volume of cuboids, cylinders, cones, pyramids and spheres. Units and diagrams decide the marks.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Statistics and Probability</h3>
      <p>Graphs, weighted averages and measures of central tendency; empirical and theoretical probability with tree diagrams. Easy to score if the student reads the graph carefully and states the sample space.</p>
    </div>
  </div>
  </section>

