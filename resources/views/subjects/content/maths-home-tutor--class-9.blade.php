  <section class="nx-guide__sec">
  <h2 id="m9-mistakes">Class 9 maths mistakes worth fixing now</h2>
  <p>
    These habits cost marks in Class 9, and they cost many more in Class 10 if left alone:
  </p>
  <ul>
    <li><strong>Proofs without reasons.</strong> Writing "angle A = angle D" with no justification. Every step in a geometry proof needs its reason in brackets.</li>
    <li><strong>Assuming the diagram.</strong> Treating lines as parallel or sides as equal because they look it. The new syllabus explicitly asks students to think about diagram accuracy.</li>
    <li><strong>Mixing up identities.</strong> Writing (a + b)² as a² + b². A tutor should have the student derive the identity, with an area model, until the error disappears.</li>
    <li><strong>Sign errors in elimination.</strong> Subtracting equations and forgetting to change every sign. Slow, neat working fixes this.</li>
    <li><strong>Term versus position in sequences.</strong> Confusing n with the nth term, or starting a sequence count at the wrong term.</li>
    <li><strong>Missing units in mensuration.</strong> Square units for area, cubic units for volume, and a final statement answering the question.</li>
    <li><strong>Rote learning from old guides.</strong> Memorising answers to questions that no longer match the new book. Understanding transfers; memorised answers do not.</li>
    <li><strong>Treating Class 9 as a rest year.</strong> The student who coasts in Class 9 usually starts Class 10 already behind.</li>
  </ul>
  </section>

