  <h2 id="m9GuideTitle">Maths home tutor for Class 9: the new CBSE syllabus, ICSE and the road to Class 10</h2>

  <p class="nx-guide__lede">
    Class 9 is the year parents most often underestimate. There is no board exam, the school report looks much like
    Class 8, and it is tempting to wait until Class 10 before getting help. But Class 9 is where secondary maths
    actually begins: proofs arrive, algebra becomes abstract, and the ideas that the Class 10 board paper tests are
    first laid down. For CBSE students in 2026-27 there is a further reason to pay attention: the Class 9 syllabus and
    NCERT textbook have both been rewritten. This guide explains what has changed, how the marks are spread, what ICSE
    Class 9 covers, which chapters Class 10 leans on, and how a Class 9 maths home tutor should use the year.
  </p>

