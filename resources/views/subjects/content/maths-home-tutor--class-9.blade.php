  <h2 id="m9-adv">The optional "Mathematics at Advanced Level" material</h2>
  <p>
    Alongside the main syllabus, CBSE has published an optional document titled Mathematics at Advanced Level for
    Grade 9. Its chapters are Sets, Logarithms, Relations and Functions, Coordinate Geometry, Combinatorics, and
    Exploring Some More Progressions. These are topics most students otherwise meet in Class 11.
  </p>
  <p>
    It is marked optional, and schools will differ in how they use it. For a strong student who enjoys maths, and
    particularly one already thinking about JEE or olympiads, working through it with a tutor is an excellent
    stretch. For a student who is finding the main syllabus hard, it should wait. Ask the school how it is being
