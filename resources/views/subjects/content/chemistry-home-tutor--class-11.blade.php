    The Class 11 practical syllabus includes titrations of sodium hydroxide against standard oxalic acid and of
    hydrochloric acid against standard sodium carbonate, identification of one cation and one anion in a salt,
    detection of nitrogen, sulphur and chlorine in organic compounds, pH experiments and equilibrium-shift
    experiments. A tutor cannot run the lab at home, but can make sure the student understands the logic of the salt
    analysis scheme and can do titration calculations confidently, which is where most practical marks are lost.
