  <h2 id="c11-tutor">Choosing a Class 11 chemistry tutor</h2>
  <p>
    In the demo class, look for a tutor who does the following:
  </p>
  <ul>
    <li><strong>Diagnoses before teaching.</strong> A quick check of mole concept and Class 10 chemistry in the first session tells the tutor where to start.</li>
    <li><strong>Makes the student write.</strong> In physical chemistry, the student should be doing the calculation while the tutor watches, not copying a solution.</li>
    <li><strong>Explains organic through reasoning.</strong> Ask how they would teach carbocation stability. If the answer involves "just memorise the order", keep looking.</li>
    <li><strong>Knows the current syllabus.</strong> A tutor who knows which topics CBSE has moved to formative-only assessment this year is keeping up to date.</li>
    <li><strong>Thinks ahead to Class 12.</strong> Ideally, the same tutor can continue into Class 12 so that nothing is lost in a handover.</li>
