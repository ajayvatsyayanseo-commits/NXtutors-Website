  <h2 id="c11-entrance">Using Class 11 as a NEET or JEE foundation</h2>
  <p>
    For students with an entrance exam in view, Class 11 is not a practice year. NEET chemistry, for example, is 45
    compulsory multiple-choice questions for 180 marks, with a mark deducted for each wrong answer, drawn from both
    Class 11 and Class 12. Many of those questions come from Class 11 physical chemistry and bonding.
  </p>
  <ul>
    <li><strong>Go deeper than the school test.</strong> Solve multi-concept numericals in mole concept, thermodynamics and ionic equilibrium, not just textbook examples.</li>
    <li><strong>Do not skip the formative-only topics.</strong> p-block elements in particular should be learned properly.</li>
    <li><strong>Start timed practice early.</strong> A few objective questions at the end of every session builds the speed that entrance exams demand.</li>
    <li><strong>Work with coaching, not against it.</strong> If your child attends a coaching class, the tutor should follow its sequence and spend sessions on doubts and weak topics rather than teaching everything twice.</li>
  </ul>
