  <section class="nx-guide__sec">
  <h2 id="c11-plan">A Class 11 chemistry plan from April to the annual exam</h2>
  <p>
    School timetables differ, but this is a realistic sequence for a student who starts with a tutor at the beginning
    of the year:
  </p>
  <ul>
    <li><strong>April and May.</strong> Some Basic Concepts of Chemistry, with heavy numerical practice. A short review of Class 10 equations and formulae writing if needed.</li>
    <li><strong>June.</strong> Use the summer break to get ahead: Structure of Atom and the start of Classification of Elements.</li>
    <li><strong>July.</strong> Periodicity trends and exceptions; begin Chemical Bonding, with shapes and hybridisation practised every session.</li>
    <li><strong>August.</strong> Finish Chemical Bonding, including molecular orbital theory. Start Thermodynamics, taking sign conventions slowly.</li>
    <li><strong>September.</strong> Complete Thermodynamics. Half-yearly exams in many schools: review the paper question by question.</li>
    <li><strong>October and November.</strong> Equilibrium, chemical and then ionic, followed by Redox Reactions. Weekly mixed numerical sets from all physical units so far.</li>
    <li><strong>December.</strong> Organic Chemistry: Some Basic Principles and Techniques. Nomenclature and electronic effects daily.</li>
    <li><strong>January.</strong> Hydrocarbons, with the reaction notebook built as the chapter goes. Light coverage of s- and p-block trends and the gaseous state.</li>
    <li><strong>February and March.</strong> Full-length practice papers, practical revision and the annual exam. For entrance students, the weeks after the exam are ideal for closing Class 11 gaps before Class 12 begins.</li>
  </ul>
  <p>
    Starting late is common, often after a poor first unit test or half-yearly. In that case the tutor should begin
    with the mole concept and bonding whatever the school is teaching, because they unlock the rest.
  </p>
