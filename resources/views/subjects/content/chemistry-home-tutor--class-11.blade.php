  <section class="nx-guide__sec">
  <h2 id="c11-why">Why Class 11 chemistry decides the next two years</h2>
  <p>
    Look at the Class 12 syllabus and almost every unit leans on something from Class 11. Solutions and
    electrochemistry are mole calculations. Chemical kinetics uses the logarithms and graph work first practised in
    equilibrium. Coordination compounds need hybridisation and electronic configuration. Every Class 12 organic
    chapter assumes the student already understands inductive effect, resonance, carbocations and nomenclature from
    the Class 11 unit on basic principles.
  </p>
  <p>
    Entrance exams make the point even more strongly: NEET and JEE both examine Class 11 and Class 12 chemistry, and
    Class 11 topics such as the mole concept, atomic structure, chemical bonding, thermodynamics and equilibrium are
    among the most tested ideas in physical chemistry.
  </p>
  <p>
    The difficulty is that Class 11 is a school-examined year. Schools set their own tests, the pace can be uneven,
    and a student who scrapes through the annual exam can carry serious gaps straight into Class 12. A Class 11
    chemistry tutor's main job is to make sure that does not happen.
  </p>
  </section>

