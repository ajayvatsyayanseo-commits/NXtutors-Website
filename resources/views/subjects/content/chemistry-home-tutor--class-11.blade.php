  <section class="nx-guide__sec">
  <h2 id="c11-formative">Topics taught but assessed only in school</h2>
  <p>
    The 2026-27 curriculum lists two topics that remain part of the syllabus but are assessed only formatively, that
    is, through classroom work rather than the year-end theory paper:
  </p>
  <ul>
    <li><strong>s- and p-block elements.</strong> Electronic configuration, atomic and ionic radii, ionisation and hydration enthalpy, general trends down groups and across periods, and the unusual behaviour of the first element in each group.</li>
    <li><strong>The gaseous state.</strong> A qualitative treatment of the gas laws, the ideal gas equation and deviations from it.</li>
  </ul>
  <p>
    A student aiming only at the school exam might be tempted to skip these. That is a mistake for anyone heading
    towards NEET or JEE, where p-block chemistry is part of the syllabus, and the gas equation turns up constantly in
    physical chemistry numericals. A good tutor covers them lightly but properly, alongside the related units on
    periodicity and the mole concept.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="c11-physical">The physical chemistry units, and where students slip</h2>
  <p>
    These five units carry most of the Class 11 marks and nearly all of the calculation. Each has its own trap.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Some Basic Concepts (7 marks)</h3>
  <p>
    Significant figures, the laws of chemical combination, atomic and molecular mass, the mole, percentage
    composition, empirical formulae and stoichiometry, including limiting reagents and molarity. It looks easy, and
    that is the problem. A tutor should give this unit far more practice than its seven marks suggest, because every
    later numerical depends on it.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Structure of Atom (9 marks)</h3>
  <p>
    From Thomson and Rutherford through Bohr's model of hydrogen to the quantum mechanical model: quantum numbers,
    orbital shapes, the Aufbau principle, Pauli and Hund's rules, and electronic configurations. Students lose marks
    on Bohr-model calculations with exponents and on the exceptional configurations of chromium and copper.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Chemical Thermodynamics (9 marks)</h3>
  <p>
    System and surroundings, internal energy and enthalpy, calorimetry, Hess's law, enthalpies of different
    reactions, and spontaneity through Gibbs energy. The hardest part is sign conventions: whether work done is
    positive or negative, and what a negative ΔG actually tells you. A tutor should drill these until they are
    automatic.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Equilibrium (7 marks)</h3>
  <p>
    The equilibrium constant and reaction quotient, Le Chatelier's principle, then ionic equilibrium: acids and
    bases, pH, buffers and solubility product. This is the longest chapter in the book, and the ionic half is where
    logarithms appear in earnest. Students who are weak with logs need a short maths detour first.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Redox Reactions (4 marks)</h3>
  <p>
    Oxidation numbers, identifying oxidising and reducing agents, and balancing redox equations. Few marks in Class
    11, but the oxidation-number method is used again in Class 12 electrochemistry and in the practical titrations,
    so it is worth mastering.
  </p>
      </div>
    </div>
  <p>
    The common thread is careful setting out: write the formula, substitute with units, calculate, then state the
    answer with the right significant figures. Students who build that habit in Class 11 are the ones who find Class
    12 electrochemistry straightforward.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="c11-inorganic">Periodicity and chemical bonding</h2>
  <p>
    Unit 3, Classification of Elements and Periodicity in Properties, is the gateway to all inorganic chemistry. It
    covers the modern periodic law, naming elements with atomic number above 100, the s-, p-, d- and f-blocks, and
    trends in atomic radius, ionisation enthalpy, electron gain enthalpy and electronegativity. The trends are simple;
    the exceptions, such as why nitrogen's ionisation enthalpy is higher than oxygen's, are where questions come from.
    A tutor who explains each exception from electronic configuration saves the student from memorising a list.
  </p>
  <p>
    Unit 4, Chemical Bonding and Molecular Structure, is the unit that most often separates confident Class 11
    students from struggling ones. It covers Lewis structures and formal charge, bond parameters, VSEPR theory and
    molecular shapes, valence bond theory and hybridisation, molecular orbital theory for homonuclear diatomic
    molecules, and hydrogen bonding. The skills a tutor should practise until they are quick:
  </p>
  <ul>
    <li><strong>Predicting shape from VSEPR.</strong> Counting bond pairs and lone pairs and naming the geometry, including distorted shapes such as those of water and ammonia.</li>
    <li><strong>Assigning hybridisation.</strong> Linking sp, sp<sup>2</sup>, sp<sup>3</sup> and the expanded-octet cases to geometry, which is needed again for coordination compounds in Class 12.</li>
    <li><strong>MO diagrams and bond order.</strong> Filling molecular orbitals for species such as O<sub>2</sub>, N<sub>2</sub> and their ions, and using bond order to compare stability and magnetic behaviour.</li>
    <li><strong>Dipole moment reasoning.</strong> Explaining why some molecules with polar bonds are non-polar overall.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="c11-organic">Organic basics and hydrocarbons: 21 marks that shape Class 12</h2>
  <p>
    Unit 8, Organic Chemistry: Some Basic Principles and Techniques, is worth 11 marks, more than any other Class 11
    unit. It covers the tetravalence and shapes of carbon compounds, structural representations, classification,
    IUPAC nomenclature, isomerism, the fundamental concepts of reaction mechanisms, purification methods, and
    qualitative and quantitative analysis of organic compounds.
  </p>
  <p>
    The mechanism section is the one to spend time on. Inductive effect, resonance, hyperconjugation and the
    stability of carbocations, carbanions and free radicals explain almost every organic reaction in Class 12. A
    tutor should keep returning to these ideas, asking the student to predict which of two intermediates is more
    stable and why.
  </p>
  <p>
    Unit 9, Hydrocarbons, worth 10 marks, applies those ideas to alkanes, alkenes, alkynes and aromatic
    hydrocarbons, including conformations of ethane, Markovnikov and anti-Markovnikov addition, and electrophilic
    substitution in benzene, with a note on carcinogenicity and toxicity. This is the first chapter where students
    must remember many reactions, and it is the right moment to start a reaction notebook: one page per reaction
    type, with reagent, conditions, product and mechanism.
  </p>
  <p>
    Nomenclature deserves a special mention. Students who cannot name compounds quickly and correctly lose marks in
    every organic question for the next two years. Ten minutes of naming practice in every session during these units
    pays back many times over.
  </p>
  </section>

