  <h2 id="s8-week">A weekly plan for Class 8 science</h2>
  <ul>
    <li><strong>Session one (60 minutes).</strong> Quick recall from earlier chapters, then the new concept through a demonstration or the book's activity, and the chapter diagram drawn by the student.</li>
    <li><strong>Independent work (30 minutes).</strong> In-text questions, one home activity with a write-up, and flashcards for new terms.</li>
    <li><strong>Session two (60 minutes).</strong> End-of-chapter and application questions, two or three short numericals where the chapter has them, and one question that links this chapter to an earlier one.</li>
    <li><strong>Once a fortnight.</strong> A 20-minute mixed quiz across chapters, marked with the student, so revision happens all year, not only before exams.</li>
  </ul>
  <p>
    Two sessions a week is right for most Class 8 students. A third is worth adding only for a specific reason, such
    as catching up after illness or preparing for the annual exam.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s8-signs">Signs your Class 8 child needs help with science</h2>
  <ul>
    <li><strong>Terms blur together.</strong> Element and compound, mass and weight, solute and solvent.</li>
    <li><strong>Numericals are avoided.</strong> Pressure or density questions left blank, or answers without units.</li>
    <li><strong>Diagrams copied without understanding.</strong> The child cannot explain what the rays or arrows mean.</li>
    <li><strong>Heavy reliance on guidebooks.</strong> Answers memorised from a guide rather than understood from the textbook.</li>
    <li><strong>Worry about Class 9.</strong> Hearing that Class 9 is hard can make children anxious; a tutor who secures Class 8 ideas is the best reassurance.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s8-choose">Choosing a Class 8 science tutor: a demo checklist</h2>
  <ul>
    <li><strong>Knows the Curiosity book.</strong> Ask what the Class 8 book says about forces or particles. A tutor teaching the new book should answer easily.</li>
    <li><strong>Sees the Class 9 picture.</strong> Ask how they will prepare your child for Class 9. A good tutor mentions atoms, cells and motion without prompting.</li>
    <li><strong>Teaches through a model or demonstration.</strong> Particles, forces and pressure are best shown, not told.</li>
    <li><strong>Checks working.</strong> In any numerical, the tutor should watch every line, not just the final answer.</li>
    <li><strong>Leaves your child talking.</strong> After the demo, can your child explain one idea back to you? That is the best single test.</li>
  </ul>
