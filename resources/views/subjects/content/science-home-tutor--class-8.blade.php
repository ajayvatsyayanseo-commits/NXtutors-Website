  <section class="nx-guide__sec">
  <h2 id="s8-online">Online science tuition for Class 8, or at home?</h2>
  <p>
    Online science tuition works well for Class 8 because the student is old enough to manage a device and many
    ideas can be shown with simulations and on-screen diagrams. What makes it work is set-up: a writing tablet or a
    phone camera on the notebook so the tutor can see diagrams and numericals, and simple materials ready for the
    chapters that need a demonstration.
  </p>
  <p>
    Home tuition is still the better choice for children who drift off on screens, or who need someone beside them to
    build the habit of neat, labelled work. Many families use a hybrid of one home session and one online session a
    week. Our comparison of <a href="{{ url('/blog/online-vs-offline-tutoring') }}">online and offline tutoring</a>
