  <h2 id="s8-why">Why Class 8 science matters more than it looks</h2>
  <p>
    There is no board exam in Class 8, so it is easy to treat the year lightly. That would be a mistake for science.
    Three things happen this year that did not happen before.
  </p>
  <ul>
    <li><strong>The subject goes microscopic.</strong> Cells, microorganisms and the particles that make up matter are things children cannot see. They have to build mental models, and those models are used for the rest of school science.</li>
    <li><strong>Quantities start to be calculated.</strong> Pressure as force per unit area, weight in newtons, density, and solubility at different temperatures all bring numbers into science.</li>
    <li><strong>Language becomes precise.</strong> Element, compound and mixture; solute, solvent and solution; contact and non-contact force. Loose use of these words costs marks from now on.</li>
  </ul>
  </section>

