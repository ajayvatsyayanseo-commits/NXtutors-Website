  <section class="nx-guide__sec">
  <h2 id="s8-hard">Where Class 8 students struggle most</h2>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Particles and states of matter</h3>
  <p>
    Children often say particles "melt" or "expand". A tutor fixes this with drawings of particle spacing in solids,
    liquids and gases, and by insisting that the particles themselves do not change, only their spacing and movement.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Elements, compounds and mixtures</h3>
  <p>
    Classifying correctly needs a test, not a feeling: can it be separated by physical means, and does it have a fixed
    composition? Air being a mixture and water a compound is the classic confusion.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Pressure</h3>
  <p>
    Pressure as force divided by area is simple on paper, but applying it (why a knife cuts, why camels have broad
    feet) and doing the numerical with the right units takes practice.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Mirrors and lenses</h3>
  <p>
    Concave versus convex, real versus virtual, and which one does what. Without a few careful diagrams, students
    learn a table by heart and then mix it up.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Forces and weight</h3>
  <p>
    Mass and weight are used interchangeably at home. Class 8 separates them: weight is a force, measured in newtons
    with a spring balance.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Solutions and density</h3>
  <p>
    Saturated solutions, the effect of temperature on solubility, and density as mass per volume combine reading a
    table with simple calculation.
  </p>
      </div>
    </div>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s8-icse">ICSE Class 8 science</h2>
  <p>
    CISCE does not prescribe one Class 8 science textbook, and ICSE schools almost always teach physics, chemistry
    and biology as separate subjects by this stage, each with its own book and tests. Topics usually include matter
    and its particles, atomic structure at an introductory level, elements, compounds and simple chemical equations,
    force and pressure, energy, light, heat and electricity, cells and tissues, reproduction, and the human body.
    Exact lists depend on the school and publisher.
  </p>
  <p>
    ICSE Class 8 is a direct warm-up for Class 9, where CISCE's syllabus treats Physics, Chemistry and Biology as three
    separate papers. The most useful thing an ICSE Class 8 tutor can do is make definitions, chemical symbols and
    diagrams precise, because the ICSE style of marking rewards exactness.
  </p>
  </section>

