  <h2 id="s8-skills">Diagrams, numericals and practical skills for Class 8</h2>
  <ul>
    <li><strong>Particle diagrams.</strong> Circles for particles, drawn closely packed for solids, loosely for liquids and far apart for gases. Simple, but examiners in later years expect them.</li>
    <li><strong>Cells and microorganisms.</strong> Outline diagrams of cells and common microorganisms, correctly labelled. This is the direct start of Class 9 biology.</li>
    <li><strong>Mirror diagrams.</strong> Spherical mirrors with the principal axis, rays and arrows, using a ruler.</li>
    <li><strong>Force diagrams.</strong> Arrows showing direction and the object each force acts on. Forces as interactions between two objects is a key idea of the chapter.</li>
    <li><strong>Short numericals.</strong> Pressure, weight from mass, density. Always formula, substitution with units, answer with unit.</li>
    <li><strong>Reading data.</strong> Solubility at different temperatures and a Moon-phase record are both about spotting a pattern in data and describing it in a sentence.</li>
  </ul>
  </section>

