  <section class="nx-guide__sec">
  <h2 id="m8-session">Inside a Class 8 session: making identities stick</h2>
  <p>
    Algebraic identities are the Class 8 topic most worth teaching well, because they are used in almost every
    chapter of Classes 9 and 10. Here is how a strong tutor might handle (a + b)² in one session:
  </p>
  <ol>
    <li><strong>Start with a picture.</strong> A square of side a + b, split into an a × a square, a b × b square and two a × b rectangles. The child sees that the area is a² + 2ab + b², and why a² + b² alone is too small.</li>
    <li><strong>Check with numbers.</strong> Put a = 3 and b = 2: (3 + 2)² = 25, and 9 + 12 + 4 = 25. The identity is now something the child has verified, not been told.</li>
    <li><strong>Use it for mental maths.</strong> 102² = (100 + 2)² = 10,000 + 400 + 4. Students enjoy the shortcut, and it shows what an identity is for.</li>
    <li><strong>Change the letters.</strong> Expand (2x + 3y)² and (p − 5)². This is where memorised identities break, so it is where practice matters.</li>
    <li><strong>Reverse it.</strong> Recognise x² + 6x + 9 as a perfect square. This is the first step towards factorisation in Class 9.</li>
  </ol>
  <p>
    The same approach, seeing why and then practising with varied forms, works for exponents, percentages and the
    Pythagoras theorem.
  </p>
  </section>

