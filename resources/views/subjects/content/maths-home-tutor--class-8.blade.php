  <section class="nx-guide__sec">
  <h2 id="m8-signs">Warning signs in Class 8 maths</h2>
  <ul>
    <li><strong>Formula without understanding.</strong> Can recite an identity but cannot use it when the letters change.</li>
    <li><strong>Algebra avoidance.</strong> Leaves out or guesses questions with brackets, powers or equations.</li>
    <li><strong>Percentage confusion.</strong> Unsure whether to multiply or divide, or what the percentage is "of".</li>
    <li><strong>Declining test marks</strong> across two or more units, especially after a strong Class 7.</li>
    <li><strong>Losing interest.</strong> A teenager who says maths is "pointless" often means it has stopped making sense.</li>
    <li><strong>A board change ahead.</strong> Moving from CBSE to ICSE for Class 9, or the reverse, calls for a topic audit now.</li>
  </ul>
