  <h2 id="m8-stakes">Why Class 8 maths matters more than it looks</h2>
  <p>
    Class 8 has no board exam, so it is easy to treat it as a quiet year. That is a mistake. Class 9 maths assumes
    students can already expand (a + b)², work with exponents, handle percentages and use Pythagoras without thinking.
    Class 9 teachers rarely have time to reteach these, because the Class 9 and 10 syllabus is long and the boards are
    only two years away.
  </p>
  <p>
    Class 8 is also where abstraction ramps up. Students are asked to prove simple results, generalise patterns with
    algebra and reason about proportion rather than just calculate. Many students who coasted through earlier classes
    on good arithmetic find this the first year they need to think hard in maths.
  </p>
  <p>
    That makes Class 8 the most cost-effective year for tutoring. Fixing a gap now takes a few weeks; fixing the same
    gap in the middle of Class 10 revision takes months and costs marks.
  </p>
  </section>

