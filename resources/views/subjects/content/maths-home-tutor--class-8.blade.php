    Two features stand out. First, the Pythagoras theorem is taught under the name Baudhayana-Pythagoras, recognising
    the Indian Sulba-sutra tradition, and students are expected to understand why it holds, not just use it. Second,
    proportional reasoning gets two full chapters, which reflects how often ratio and rate problems appear later in
    science, commerce and everyday life. Assessment in Class 8 is still set by the school.
  </p>
