  <h2 id="m8-next">How Class 8 prepares your child for Class 9</h2>
  <p>
    Class 9 is the start of secondary school and of the board-exam years. Here is how Class 8 topics carry forward:
  </p>
  <ul>
    <li><strong>Squares, cubes and exponents</strong> lead into number systems, irrational numbers and laws of exponents for real numbers.</li>
    <li><strong>Algebraic identities</strong> become polynomials and factorisation, which run through the whole of Classes 9 and 10.</li>
    <li><strong>Algebra Play and simple equations</strong> prepare for linear equations in two variables.</li>
    <li><strong>Quadrilaterals and the Pythagoras theorem</strong> are the base for Class 9 geometry, including triangles, quadrilaterals and circles, and later for trigonometry.</li>
    <li><strong>Area</strong> leads into surface areas, volumes and further mensuration.</li>
    <li><strong>Data chapters</strong> lead into statistics with grouped data.</li>
  </ul>
