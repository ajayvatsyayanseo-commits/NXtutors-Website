  <h2 id="m8-icse">ICSE Class 8 maths</h2>
  <p>
    ICSE schools teach Class 8 through CISCE's middle-years curriculum, using the textbook series each school
    chooses. Chapter titles vary, so work from your school's syllabus. In general, ICSE Class 8 maths covers six broad
    areas:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Area</th><th scope="col">Typical topics</th></tr>
    </thead>
    <tbody>
      <tr><td>Number system</td><td>Rational numbers, exponents and powers, squares and square roots, cubes and cube roots, playing with numbers</td></tr>
      <tr><td>Sets</td><td>Sets, subsets and Venn diagrams (a topic many CBSE students do not meet at this stage)</td></tr>
      <tr><td>Ratio and commercial maths</td><td>Percentage, profit and loss, discount, simple and compound interest, direct and inverse variation, time and work</td></tr>
      <tr><td>Algebra</td><td>Algebraic expressions, identities, factorisation, linear equations and inequations in one variable</td></tr>
      <tr><td>Geometry and mensuration</td><td>Quadrilaterals and parallelograms, constructions, circles, area, surface area and volume of solids</td></tr>
      <tr><td>Data handling</td><td>Frequency distributions, graphs and an introduction to probability</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    ICSE Class 8 is broader than the NCERT book, especially in commercial arithmetic, sets, factorisation and
    mensuration, and the exercises are long. It is also the direct lead-in to the two-year CISCE Class 9 and 10 maths
    course, which carries the same topics forward into compound interest, factorisation, indices, mensuration of
    solids and more demanding geometry. Students who finish Class 8 strong on algebra and commercial maths start ICSE
    Class 9 at a real advantage.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="m8-hard">The hardest Class 8 maths topics, and why</h2>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
      <h3>Identities and expansion</h3>
      <p>(a + b)², (a − b)² and (a + b)(a − b) are easy to memorise and easy to misuse. The classic error, writing (a + b)² as a² + b², must be fixed now.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Laws of exponents</h3>
      <p>Negative and zero exponents, and multiplying versus adding powers. Mistakes here reappear in Class 9 and in science notation for years.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Proportional reasoning</h3>
      <p>Deciding whether two quantities vary directly or inversely. Students who set up every problem as a direct proportion get half of them wrong.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Percentages in context</h3>
      <p>Successive percentages, percentage change and working backwards from a final amount. In ICSE schools this extends to compound interest.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Why Pythagoras works</h3>
      <p>Applying a² + b² = c² is manageable; explaining it and spotting right triangles hidden in a diagram is harder.</p>
    </div>
    <div class="nx-guide__card">
      <h3>Factorisation (ICSE)</h3>
      <p>Taking out common factors, grouping and using identities in reverse. Weak factorisation is the biggest single cause of trouble in ICSE Class 9 algebra.</p>
    </div>
  </div>
  </section>

