  <p>
    Mechanics (the first two blocks, chapters 1 to 7) carries 40 of the 70 theory marks. It is also the part of the
    course that everything else leans on: oscillations use Newton's laws and energy, fluids use pressure and force,
    and kinetic theory uses momentum. A tutor who makes mechanics secure has done most of the year's work.
  </p>
  <p>
    The curriculum also notes that content marked in NCERT textbooks as excluded for 2026-27 is not to be tested, so
    the tutor should work from the current NCERT edition rather than an old guidebook.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="p11-chapters">Chapter-by-chapter: what is new and where marks go</h2>
  <ul>
    <li><strong>Units and Measurements.</strong> SI units, significant figures, uncertainty in results and dimensional analysis. Short, but significant figures and error handling come back in every practical.</li>
    <li><strong>Motion in a Straight Line.</strong> The syllabus explicitly introduces elementary differentiation and integration to describe motion, and asks for the equations of uniformly accelerated motion by both graphical and calculus methods. Position–time and velocity–time graphs are central.</li>
    <li><strong>Motion in a Plane.</strong> Vectors in full: addition, resolution, unit vectors, scalar and vector products, then projectile motion and uniform circular motion. This is the chapter most often behind a weak Class 11 result.</li>
    <li><strong>Laws of Motion.</strong> Newton's laws, impulse, conservation of momentum, friction and circular motion including a vehicle on a banked road. Free-body diagrams decide everything.</li>
    <li><strong>Work, Energy and Power.</strong> Work by variable forces, the work–energy theorem, spring potential energy, vertical circular motion and collisions in one and two dimensions.</li>
    <li><strong>System of Particles and Rotational Motion.</strong> Centre of mass, torque, angular momentum and its conservation, and moment of inertia (values for simple objects, without derivation). Students find the analogy between linear and rotational motion the key that unlocks it.</li>
    <li><strong>Gravitation.</strong> Kepler's laws, variation of g with height and depth, potential energy, escape speed and satellite energy. Formula-heavy and very testable.</li>
    <li><strong>Solids and Fluids.</strong> Stress, strain and Young's modulus; Pascal's law, viscosity, Stokes' law, Bernoulli's theorem, surface tension and capillary rise.</li>
    <li><strong>Thermal Properties, Thermodynamics and Kinetic Theory.</strong> Expansion, calorimetry and heat transfer; the laws of thermodynamics and isothermal and adiabatic processes; rms speed, degrees of freedom and equipartition. Sign conventions for work and heat are the common trap.</li>
    <li><strong>Oscillations and Waves.</strong> Simple harmonic motion, energy in SHM, the simple pendulum, progressive and standing waves, harmonics in strings and pipes, and beats.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="p11-maths">Vectors and calculus in Class 11 physics</h2>
  <p>
    If there is one thing a Class 11 physics tutor should check in the first week, it is the student's comfort with
    the mathematical tools. The table shows what physics needs and when.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Tool</th><th scope="col">Where physics first needs it</th><th scope="col">What the student must be able to do</th></tr>
    </thead>
    <tbody>
      <tr><td>Differentiation</td><td>Motion in a Straight Line</td><td>Find velocity from position and acceleration from velocity; read a derivative as a slope.</td></tr>
      <tr><td>Integration</td><td>Motion in a Straight Line; work by a variable force</td><td>Read an integral as the area under a graph; integrate simple powers.</td></tr>
      <tr><td>Vectors</td><td>Motion in a Plane onward</td><td>Resolve into components, add and subtract, use unit vectors, take dot and cross products.</td></tr>
      <tr><td>Trigonometry</td><td>Projectiles, inclined planes, banking</td><td>Use sine and cosine of standard angles quickly; small-angle approximations for the pendulum.</td></tr>
      <tr><td>Graphs</td><td>Every unit</td><td>Interpret slope, intercept and area; sketch a curve from an equation.</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    A good tutor teaches just enough calculus for the physics, framed physically ("the slope of the position–time
    graph is the velocity"), and does not wait for the maths syllabus to catch up. Where the gaps are wider, working
    alongside a <a href="{{ url('/maths-home-tutor/class-11') }}">Class 11 maths tutor</a> is often the fastest fix,
    because the two subjects reinforce each other all year.
  </p>
