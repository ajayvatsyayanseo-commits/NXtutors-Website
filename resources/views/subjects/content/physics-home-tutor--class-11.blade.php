  <section class="nx-guide__sec">
  <h2 id="p11-mistakes">Habits that cost Class 11 physics marks</h2>
  <p>
    Class 11 marks are rarely lost because a topic is beyond the student. They are lost to habits a tutor can spot
    in the first few sessions and correct over a term:
  </p>
  <ul>
    <li><strong>Writing a formula before drawing anything.</strong> In laws of motion, rotation and projectiles, the diagram decides which formula applies. Students who skip it pick the wrong one.</li>
    <li><strong>Treating vectors as numbers.</strong> Adding two velocities or forces without considering direction, or dropping the sign of a component.</li>
    <li><strong>Using equations of motion when acceleration is not constant.</strong> The calculus in chapter 2 exists precisely for those cases.</li>
    <li><strong>Mixing up heat and work signs</strong> in the first law of thermodynamics, especially across different textbooks and coaching notes.</li>
    <li><strong>Losing significant figures and units</strong> in practical calculations and numericals.</li>
    <li><strong>Only reading solved examples.</strong> Watching a solution feels like learning; attempting the problem first is what actually builds skill.</li>
    <li><strong>Letting a chapter go.</strong> Skipping rotational motion because it is hard is common, and costly: it returns in Class 12 magnetism and in both entrance exams.</li>
  </ul>
  </section>

