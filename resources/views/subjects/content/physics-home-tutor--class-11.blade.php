  <p>
    In other words, more than 60% of the marks ask the student to use physics in a situation they have not seen word
    for word. Reading NCERT and memorising derivations is necessary but not enough. The tutor's job is to add a steady
    diet of unfamiliar problems: NCERT exercises and additional exercises first, then NCERT Exemplar, then mixed
    questions that cross chapters.
  </p>
