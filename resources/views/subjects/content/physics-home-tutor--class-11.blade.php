  <h2 id="p11-jump">Why Class 11 physics feels like a different subject</h2>
  <p>
    In Class 10, physics was two or three chapters inside a science paper: light, electricity and magnetic effects of
    current. Most questions could be answered with one formula and a careful diagram. In Class 11 the student faces
    fourteen physics chapters in one year, and almost every one of them assumes the student can handle vectors, graphs
    and a little calculus.
  </p>
  <p>Three changes cause most of the trouble:</p>
  <ul>
    <li><strong>Mathematics arrives before it is taught in maths class.</strong> Physics uses vectors and differentiation in the first term, often weeks before the maths syllabus reaches them.</li>
    <li><strong>Problems stop being one-step.</strong> A single mechanics question can require a free-body diagram, resolving forces, Newton's second law and a kinematic equation, in that order.</li>
    <li><strong>The volume.</strong> Mechanics alone, from kinematics to gravitation, occupies more than half the year. Students who fall behind in July rarely catch up without help.</li>
  </ul>
  <p>
    The Class 11 exam is set by the school rather than by CBSE, which leads some families to treat the year lightly.
    That is a mistake. Class 12 builds directly on it, and JEE and NEET test it in full.
  </p>
  </section>

