  <section class="nx-guide__sec">
  <h2 id="p11-practicals">Class 11 physics practicals: 30 marks worth collecting</h2>
  <p>
    Students are expected to record at least eight experiments (four from each section) and six activities (three
    from each section), and to carry out an investigatory project. The practical exam is marked like this:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Component</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>Two experiments, one from each section</td><td>7 + 7</td></tr>
      <tr><td>Practical record (experiments and activities)</td><td>5</td></tr>
      <tr><td>One activity from either section</td><td>3</td></tr>
      <tr><td>Investigatory project</td><td>3</td></tr>
      <tr><td>Viva on experiments, activities and project</td><td>5</td></tr>
      <tr><td><strong>Total</strong></td><td><strong>30</strong></td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Section A experiments centre on measurement and mechanics: vernier callipers, screw gauge, spherometer, the simple
    pendulum and friction. Section B covers properties of matter, heat and sound: Young's modulus, the force constant
    of a spring, surface tension by capillary rise, viscosity by terminal velocity, cooling curves, the sonometer and
    the resonance tube. A home tutor cannot replace the school lab, but can make sure the student understands the
    theory behind each experiment, can take readings with the correct least count, handles significant figures, and
    is ready for viva questions. Many of these same experiments appear in the Experimental Skills unit of the JEE
    Main and NEET syllabi.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="p11-entrance">Class 11 as the foundation for JEE and NEET</h2>
  <p>
    Both the JEE Main physics syllabus and the NEET UG physics syllabus list twenty units. The first ten, from units
    and measurement to oscillations and waves, map onto Class 11. Units 11 to 19 cover Class 12, and unit 20 is
    experimental skills. So roughly half of the entrance syllabus is this year's work.
  </p>
  <p>
    For a student in coaching, Class 11 is where most fall behind: lectures move on, modules pile up, and school
    exams pull in a different direction. A home tutor's role here is usually to:
  </p>
  <ul>
    <li><strong>Clear the backlog of doubts</strong> from coaching modules each week, before they compound.</li>
    <li><strong>Keep NCERT and school exams in view</strong>, so board-style answers and practicals are not neglected.</li>
    <li><strong>Strengthen mechanics</strong>, which both exams test heavily and which Class 12 electricity and magnetism problems reuse.</li>
    <li><strong>Pitch the difficulty right.</strong> NEET aspirants need NCERT depth and speed; JEE aspirants need multi-concept problems.</li>
  </ul>
