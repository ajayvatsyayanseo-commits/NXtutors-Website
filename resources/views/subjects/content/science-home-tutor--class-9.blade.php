  <p>
    Compared with the older book, the main changes a parent will notice are a standalone chapter on mixtures, simple
    machines added to work and energy, reproduction moved into Class 9, and earth science appearing for the first time
    as a Class 9 chapter. Tutors who have taught Class 9 for years from old notes need to have caught up with these.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s9-marks">CBSE Class 9 science 2026-27: unit weightage</h2>
  <p>
    CBSE's Class 9 Science (code 086) curriculum for 2026-27 groups the chapters into four units for the 80-mark,
    three-hour annual examination:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Unit</th><th scope="col">Chapters</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>I. World of Living</td><td>2 Cell, 3 Tissues, 11 Reproduction, 12 Diversity and Classification</td><td>27</td></tr>
      <tr><td>II. Matter: Its Nature and Behaviour</td><td>5 Mixtures, 8 Inside the Atom, 9 Atomic Foundations of Matter</td><td>25</td></tr>
      <tr><td>III. Motion, Force, Work and Sound</td><td>4 Motion, 6 Forces, 7 Work and Energy, 10 Sound</td><td>23</td></tr>
      <tr><td>IV. Earth as a System</td><td>13 Earth as a System</td><td>5</td></tr>
      <tr><td><strong>Theory total</strong></td><td></td><td><strong>80</strong></td></tr>
      <tr><td>Internal assessment</td><td>Set by the school</td><td>20</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Two points for planning. Biology now carries the largest single share, 27 marks, largely because reproduction has
    joined cells, tissues and classification; students who treat biology as "just reading" often lose marks on
    diagrams and precise terms. And although physics carries 23 marks, it is the unit that most often pulls the total
    down, because every chapter has numericals and graphs. A tutor should balance time by difficulty as well as marks.
    The introductory Chapter 1 does not appear in the unit table.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s9-paper">How the paper is built, and the 20 internal marks</h2>
  <p>
    CBSE's question paper design for Class 9 Science in 2026-27 divides the 80 theory marks by the kind of thinking
    each question tests:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Competency</th><th scope="col">Share of theory marks</th></tr>
    </thead>
    <tbody>
      <tr><td>Demonstrate knowledge and understanding</td><td>50%</td></tr>
      <tr><td>Application of knowledge and concepts</td><td>30%</td></tr>
      <tr><td>Formulate, analyse, evaluate and create</td><td>20%</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Question types include very short answers and objective items, assertion-reasoning, short and long answers, and
    source-based, case-based or passage-based questions, with internal choice in about a third of the paper. Half the
    paper, in other words, goes beyond recall. Students who only reread the chapter are usually comfortable with the
    first 50% and uneasy with the rest.
  </p>
  <p>
    The 20 internal marks are split into four parts of five marks each: periodic assessment, multiple assessment,
    portfolio, and subject enrichment (practical work). These are the easiest marks of the year to secure, provided
    practical records and the portfolio are kept up as the year goes, not in a rush in February.
  </p>
  <p>
    CBSE has also published optional "Science at Advanced Level" material for Grade 9, covering topics such as
    measurement, Newton's laws, advanced simple machines, chemical bonding, microscopy and biotechnology. It is
    optional enrichment; ask your child's school whether and how it uses it.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s9-prac">The CBSE Class 9 practical list</h2>
  <p>
    The 2026-27 curriculum lists thirteen practicals to be done alongside the theory. Grouped by strand:
  </p>
  <ul>
    <li><strong>Chemistry (Chapters 5 and 9).</strong> Preparing a true solution, a suspension and a colloid and telling them apart by transparency, filtration, stability and the Tyndall effect; separating mixtures by separating funnel, paper chromatography, sublimation and coagulation; verifying the law of conservation of mass.</li>
    <li><strong>Biology (Chapters 2, 3, 11 and 12).</strong> Stained temporary mounts of onion peel or Rhoeo leaf and human cheek cells; identifying plant and animal tissues from slides; budding in yeast and Hydra and spore formation in bread mould; the parts of a bisexual flower; identifying specimens from Spirogyra and moss to starfish and snail.</li>
    <li><strong>Physics (Chapters 4, 6, 7 and 10).</strong> Conservation of energy with a simple pendulum; mechanical advantage of a lever; Newton's second law with a trolley, pulley and hanging masses; distance-time and velocity-time graphs on an inclined plane; speed of a pulse along a stretched string or slinky.</li>
  </ul>
  <p>
    Almost every practical ends with a labelled diagram or a graph. A tutor who asks for the diagram from memory a week
    after the lab session is doing exactly what the exam will do.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s9-icse">ICSE Class 9 science: Physics, Chemistry and Biology</h2>
  <p>
    In ICSE schools, science in Class 9 is three subjects. CISCE's syllabus for students who will sit the ICSE
    examination in 2028 (that is, in Class 9 in 2026-27) sets, for each of Physics, Chemistry and Biology, one written
    paper of two hours for 80 marks plus 20 marks of internal assessment of practical work. The Class 9 topics are:
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Physics (Science Paper 1)</h3>
  <p>
    Measurements and Experimentation (including Vernier callipers, screw gauge and the simple pendulum); Motion in One
    Dimension; Laws of Motion; Fluids; Heat and Energy; Light; Sound; Electricity and Magnetism.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Chemistry (Science Paper 2)</h3>
  <p>
    The Language of Chemistry; Chemical Changes and Reactions; Water; Atomic Structure and Chemical Bonding; The
    Periodic Table; Study of the First Element, Hydrogen; Study of Gas Laws; Atmospheric and Environmental Chemistry.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Biology (Science Paper 3)</h3>
  <p>
    Basic Biology (cell and tissues); Flowering Plants; Plant Physiology (seeds, germination, respiration); Diversity in
    the Animal Kingdom; Economic Importance of Bacteria and Fungi; Human Anatomy and Physiology; Health and Hygiene.
  </p>
      </div>
    </div>
  <p>
    ICSE Class 9 is broader and more numerical than CBSE in places: Vernier and screw-gauge readings, gas-law
    calculations and fluid pressure all appear this year. The most effective ICSE tutors keep three separate
    notebooks and revision cycles, so no one science is left behind. If one subject needs a specialist, a separate
    physics or chemistry tutor for that subject alone can work alongside a general science tutor.
  </p>
  </section>

