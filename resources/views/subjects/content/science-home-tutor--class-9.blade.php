      <tr><td>2</td><td>Cell: The Building Block of Life</td><td>Plant and animal cells, prokaryotic and eukaryotic cells, organelles, cell membrane permeability, osmosis, mitosis and meiosis</td></tr>
      <tr><td>3</td><td>Tissues in Action</td><td>Plant tissues (meristematic, permanent, simple and complex, xylem and phloem), animal tissues, muscle types, joints</td></tr>
