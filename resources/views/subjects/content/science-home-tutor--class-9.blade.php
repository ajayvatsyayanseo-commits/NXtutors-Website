  <h2 id="s9GuideTitle">Science home tutor for Class 9: the new CBSE book, ICSE papers and a plan for 2026-27</h2>

  <p class="nx-guide__lede">
    Class 9 science has always been a jump, and in 2026-27 it has changed as well. CBSE schools now teach from NCERT's
    new Class 9 textbook, <em>Exploration</em>, first published in April 2026, which reorganises the year into thirteen
    chapters, brings reproduction forward from Class 10 and adds a chapter on the Earth as a system. ICSE students, as
    before, study Physics, Chemistry and Biology as three separate subjects with three separate papers. This guide
    sets out both syllabuses with CBSE's unit weightage, the practicals, the diagrams and numericals that decide marks,
    a weekly plan, and how to choose a Class 9 science home tutor.
  </p>

