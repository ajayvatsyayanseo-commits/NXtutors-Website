  <section class="nx-guide__sec">
  <h2 id="s9-week">A weekly plan for Class 9 science</h2>
  <p>
    Most Class 9 students do well with two sessions a week, rising to three in the weeks before half-yearly and
    annual exams. A typical week:
  </p>
  <ul>
    <li><strong>Session one: the new concept.</strong> Quick recall from all three strands, then the new idea, a worked example or demonstration, and the related diagram drawn by the student.</li>
    <li><strong>Independent work (45 minutes across the week).</strong> NCERT in-text and end-of-chapter questions, five numericals if the chapter has them, and one practical write-up kept current.</li>
    <li><strong>Session two: practice and exam style.</strong> Homework reviewed line by line, then a mix of assertion-reasoning, case-based and long-answer questions, marked the way the school marks.</li>
    <li><strong>Every third week.</strong> A 40-minute test across chapters from all three strands, so revision is built in rather than left to the end.</li>
  </ul>
  <p>
    ICSE students need the same rhythm for each of the three sciences, which is why many ICSE families choose three
    sessions a week from the start.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s9-signs">Signs your Class 9 child needs a science tutor</h2>
  <ul>
    <li><strong>A sharp drop from Class 8.</strong> The most common pattern: a student who scored well in middle school falls back in the first unit test.</li>
    <li><strong>Physics numericals left out.</strong> Motion and force questions skipped or attempted without units.</li>
    <li><strong>Chemistry formulae guessed.</strong> Valencies not known, formulae written by pattern rather than by rule.</li>
    <li><strong>Biology answers vague.</strong> "The cell has many parts" instead of named organelles with functions.</li>
    <li><strong>Case-based questions going wrong.</strong> The student knows the chapter but cannot apply it to an unfamiliar situation.</li>
    <li><strong>Practical records behind.</strong> Internal marks are at risk and the diagrams have not been learnt.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s9-choose">Choosing a Class 9 science home tutor: a demo checklist</h2>
  <ul>
    <li><strong>Up to date with the new book.</strong> Ask which chapters make up the World of Living unit, or where reproduction sits now. A tutor who has prepared for 2026-27 will know.</li>
    <li><strong>All three strands, or honest about it.</strong> Ask which of physics, chemistry and biology they are strongest in. For ICSE, check they teach all three papers or suggest a specialist for one.</li>
    <li><strong>Numericals watched line by line.</strong> In the demo, the tutor should look at every step your child writes.</li>
    <li><strong>Diagrams taught, not just shown.</strong> The tutor should ask your child to draw and label, then correct it.</li>
    <li><strong>A plan to the half-yearly.</strong> By the end of the first week the tutor should be able to say what will be covered and when.</li>
    <li><strong>Rapport.</strong> Class 9 students are teenagers; one who feels respected will ask the questions that matter.</li>
  </ul>
