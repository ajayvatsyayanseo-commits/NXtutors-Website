  <section class="nx-guide__sec">
  <h2 id="s9-skills">The diagrams and numericals that decide Class 9 marks</h2>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Biology diagrams</h3>
  <p>
    Plant and animal cells, tissues seen under the microscope, a bisexual flower, budding and spore formation. Labels
    ruled, spelt correctly and placed on one side.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Motion graphs</h3>
  <p>
    Distance-time and velocity-time graphs: reading slope as speed or acceleration and area as distance. This is the
    single biggest numerical skill of the year.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Newton's laws and energy numericals</h3>
  <p>
    F = ma, work, kinetic and potential energy, power and mechanical advantage. Formula, substitution with units,
    answer with unit, every time.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Chemistry writing</h3>
  <p>
    Electron distribution, valency, formulae from ions and molecular mass. Small errors with charges or subscripts
    are the usual mark losses.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Concentration</h3>
  <p>
    Mass by mass, mass by volume and volume by volume percentages. Straightforward, but only if the student is clear
    which quantity is the solution and which the solute.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Case-based answers</h3>
  <p>
    Reading a short passage or data set and answering in the terms it uses. Practising two of these a week is enough
    to make them routine.
  </p>
      </div>
    </div>
