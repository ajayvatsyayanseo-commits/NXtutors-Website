  <p>
    The Class 10 board paper assumes Class 9 is secure. Atomic structure and valency underpin chemical equations,
    acids and bases and carbon compounds; cells and tissues underpin life processes; motion, force and energy underpin
    the numerical side of Class 10 physics. Graph work and unit handling from Class 9 are used in every numerical that
    follows.
