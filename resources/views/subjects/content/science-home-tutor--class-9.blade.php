  <h2 id="s9-jump">Why Class 9 science is a jump</h2>
  <p>
    Middle-school science asks children to observe and explain. Class 9 asks them to do that and also to calculate,
    define exactly and draw to a standard. In the same fortnight a student may meet equations of motion, Bohr's model
    of the atom and the organelles of a cell. Three changes stand out:
  </p>
  <ul>
    <li><strong>Maths enters physics properly.</strong> Velocity-time graphs, acceleration, force from Newton's second law, work, energy and power are all numerical.</li>
    <li><strong>Chemistry becomes symbolic.</strong> Valency, formulae, molecular mass and the structure of the atom need a new kind of precision.</li>
    <li><strong>Biology gets detailed.</strong> Cell organelles, plant and animal tissues and classification bring many new terms, each with a diagram.</li>
  </ul>
  <p>
    Class 9 is also the first half of the secondary stage. Habits formed now, good or bad, carry straight into the
    Class 10 board year.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s9-book">The new NCERT Class 9 science book: Exploration</h2>
  <p>
    For 2026-27, CBSE prescribes NCERT's Class 9 science textbook, now <em>Exploration: Textbook of Science for
    Grade 9</em>. It replaces the book Class 9 students used for many years, and it follows on from the
    <em>Curiosity</em> books of Classes 6 to 8. Its thirteen chapters:
  </p>
