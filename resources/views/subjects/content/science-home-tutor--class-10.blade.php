  <h2 id="s10-tutor">What a Class 10 science home tutor adds</h2>
  <p>
    Most Class 10 students already have a school teacher, and many attend coaching. A home tutor is worth it when
    they do something neither of those can:
  </p>
  <ul>
    <li><strong>Individual diagnosis.</strong> Finding the specific chapter, skill or misconception that is costing marks, rather than re-teaching everything.</li>
    <li><strong>Balance across the three sciences.</strong> Students often over-revise the part of science they like and avoid the part they fear. A tutor makes sure time goes where marks are.</li>
    <li><strong>Marking like the board.</strong> Going through test answers line by line against the marking scheme shows a student where marks are gained and lost, which classroom teaching rarely has time for.</li>
    <li><strong>Pace.</strong> Slower on hard chapters, faster on familiar ones, which a class of forty cannot do.</li>
    <li><strong>Calm.</strong> In the final months, a steady weekly routine with a trusted adult helps many students more than extra hours.</li>
  </ul>
