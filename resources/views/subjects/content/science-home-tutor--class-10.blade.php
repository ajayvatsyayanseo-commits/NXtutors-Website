  <h2 id="s10-cbse">CBSE Class 10 Science: syllabus and unit weightage</h2>
  <p>
    CBSE Class 10 Science (subject code 086) is a single paper of 80 marks, three hours long, plus 20 marks of
    internal assessment. The CBSE curriculum for 2026-27 divides the theory marks across five units:
  </p>
  <div class="nx-table-wrap">
    <table class="nx-table">
      <thead>
        <tr><th scope="col">Unit</th><th scope="col">Chapters (NCERT)</th><th scope="col">Marks</th></tr>
      </thead>
      <tbody>
        <tr><td>I. Chemical Substances: Nature and Behaviour</td><td>Chemical Reactions and Equations; Acids, Bases and Salts; Metals and Non-metals; Carbon and its Compounds</td><td>25</td></tr>
        <tr><td>II. World of Living</td><td>Life Processes; Control and Coordination; How do Organisms Reproduce?; Heredity</td><td>25</td></tr>
        <tr><td>III. Natural Phenomena</td><td>Light – Reflection and Refraction; The Human Eye and the Colourful World</td><td>12</td></tr>
        <tr><td>IV. Effects of Current</td><td>Electricity; Magnetic Effects of Electric Current</td><td>13</td></tr>
        <tr><td>V. Natural Resources</td><td>Our Environment</td><td>5</td></tr>
        <tr><td><strong>Theory total</strong></td><td></td><td><strong>80</strong></td></tr>
        <tr><td>Internal assessment</td><td>Periodic assessment, multiple assessment, portfolio, practical work (5 marks each)</td><td>20</td></tr>
      </tbody>
    </table>
  </div>
  <p>
    Three things about this table matter for planning:
  </p>
  <ul>
    <li><strong>Chemistry and biology carry half the paper.</strong> Units I and II together are 50 of the 80 theory marks. A student who is secure in these eight chapters is already most of the way to a good score.</li>
    <li><strong>Physics is smaller but decisive.</strong> Light and electricity together are 25 marks, and they contain the numericals and ray diagrams that separate a good score from a very good one.</li>
    <li><strong>Some topics are learned but not examined.</strong> The 2026-27 curriculum lists Periodic Classification of Elements, the evolution topics, and the electric motor, electromagnetic induction and the electric generator as topics to be assessed only formatively (in school), not in the year-end board paper. Confirm the current position with the school's science teacher, and do not skip them entirely: they come back in Class 11.</li>
  </ul>
  <p>
    The question paper is designed around competencies: roughly half the marks test knowledge and understanding,
    about 30 percent test application, and about 20 percent ask the student to analyse, evaluate or create. Question
    types include objective questions, assertion and reason, short and long answers, and source-based or case-based
    questions, with internal choice in about a third of the paper. That mix is why rote learning alone no longer
    delivers top marks. For chapter-wise revision, see our <a href="{{ url('/blog/cbse-class-10-science-notes') }}">CBSE
    Class 10 science notes</a>.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s10-exams">The two CBSE board exams in Class 10</h2>
  <p>
    From 2026, CBSE holds two board examinations for Class 10. The first, in February, is compulsory for every
    student. The second, held later in the spring, is optional and allows a student to try to improve their
    performance in up to three subjects from science, mathematics, social science and the languages. Both cover the
    full syllabus.
  </p>
  <p>
    For science this changes planning in a useful way, but it should not change the goal. We advise families to
    prepare for the February exam as if it were the only one. The second exam is a safety net for a bad day or one
    weak subject, not a reason to leave chapters for later: the gap between the two exams is short, and students
    will be revising science alongside other subjects. If your child does plan to take the second exam in science, a
    tutor can use the February paper to pinpoint exactly which chapters and question types cost marks, and focus the
    following weeks on those. Always check the latest CBSE circulars for dates and eligibility, as the rules are new
    and may be refined.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s10-icse">ICSE Class 10 science: three papers</h2>
  <p>
    In ICSE, science is examined as three separate papers under CISCE: <strong>Physics (Science Paper 1)</strong>,
    <strong>Chemistry (Science Paper 2)</strong> and <strong>Biology (Science Paper 3)</strong>. Each has a written
    theory paper of 80 marks and 20 marks of internal assessment based on practical work set and marked by the school.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>ICSE Physics</h3>
  <p>
    ICSE Physics goes further than CBSE in several areas, including machines, work, energy and power, refraction
    through lenses, sound, calorimetry and electricity, with a heavier numerical load. Students need to be fluent
    with formulas and units, and with drawing and reading graphs.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>ICSE Chemistry</h3>
  <p>
    ICSE Chemistry is the paper where many students feel the difference from CBSE most. It includes the mole concept
    and stoichiometry, analytical chemistry, electrolysis, and the study of specific compounds, with a lot of
    equations and observations to learn precisely. Consistent, spaced revision matters more here than anywhere else.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>ICSE Biology</h3>
  <p>
    ICSE Biology is detailed and diagram-heavy, covering topics such as cell division, genetics, plant physiology and
    human anatomy and physiology. Answers are expected to use exact terminology, and labelled diagrams are central
    to scoring.
  </p>
      </div>
    </div>
  <p>
    Because the three papers are separate, ICSE families more often use either one strong tutor for all three or a
    specialist for the weakest paper, usually Chemistry or Physics. The syllabus is set by CISCE each year, so a tutor
    should work from the current regulations and specimen papers rather than an old guidebook.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s10-plan">A month-by-month plan for Class 10 science</h2>
  <p>
    Most schools start the Class 10 session in April, and the CBSE first board exam and ICSE exams fall in February
    and March. A realistic plan with a home tutor looks like this:
  </p>
  <ul>
    <li><strong>April to May: diagnose and begin.</strong> The tutor checks Class 9 foundations that Class 10 builds on (atoms and molecules, motion and force, the cell) and starts the first chapters: chemical reactions and equations, and acids, bases and salts. Summer break is the best time to get ahead by a few chapters.</li>
    <li><strong>June to July: build the core.</strong> Metals and non-metals, life processes, and light. Life processes and light are long chapters; the aim is full understanding, with diagrams and ray diagrams practised weekly.</li>
    <li><strong>August to September: middle of the book.</strong> Carbon and its compounds, control and coordination, the human eye, and electricity. Chapter tests every two to three weeks. Mid-term exams usually fall in September.</li>
    <li><strong>October to November: finish the syllabus.</strong> Reproduction, heredity, magnetic effects of current and our environment. By the end of November the whole syllabus should be taught once.</li>
    <li><strong>December to January: pre-boards and papers.</strong> Full-length sample papers under timed conditions, marked against the official marking scheme. Revise weak chapters in short, focused sessions. Pre-board exams in many schools fall in this window.</li>
    <li><strong>February to March: the board exams.</strong> Light-touch revision: formulas, equations, diagrams, and the student's own list of past mistakes. No new material in the final fortnight.</li>
    <li><strong>After February (CBSE): the optional second exam.</strong> Only if needed, a targeted plan based on the chapters and question types that cost marks the first time.</li>
  </ul>
  <p>
    Starting later is still worthwhile. A tutor starting in October will compress teaching and move to sample papers
    sooner; a tutor starting in January will focus almost entirely on high-weight chapters and exam technique.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s10-skills">The skills that decide Class 10 science marks</h2>
  <p>
    Knowing the chapter is necessary but not sufficient. These are the specific skills a Class 10 science tutor
    should drill until they are automatic.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Balancing chemical equations</h3>
  <p>
    Every chemistry chapter depends on writing correct formulas and balancing equations, including state symbols
    and conditions where relevant. Students should also be able to identify the type of reaction (combination,
    decomposition, displacement, double displacement, redox) from the equation alone.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Labelled diagrams</h3>
  <p>
    The human digestive system, heart, nephron and brain; the structure of a neuron; a flower in longitudinal
    section; the human eye; the magnetic field around a conductor; a domestic circuit. Each should be drawn neatly in
    pencil, labelled with straight lines, and practised to a time limit.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Ray diagrams</h3>
  <p>
    Image formation by concave and convex mirrors and lenses for each object position is one of the most reliable
    sources of marks, and one of the easiest to lose through a missing arrow or a ray drawn freehand.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Numericals</h3>
  <p>
    Mirror and lens formula, magnification, power of a lens, Ohm's law, resistors in series and parallel, electric
    power and energy. The routine is always the same: write the formula, list the given values with units, apply
    the sign convention, substitute, calculate, and state the answer with its unit.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Case-based questions</h3>
  <p>
    These give a short passage, table or experiment and ask three or four linked questions. Students need to read
    carefully, pick out the relevant data and apply a concept they know to an unfamiliar setting. Regular practice
    with the board's sample papers is the only reliable way to build this.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Assertion and reason</h3>
  <p>
    A small format with its own trap: both statements may be true while the reason does not explain the assertion.
    A tutor should teach the four-option logic explicitly and practise it until it is quick.
  </p>
      </div>
    </div>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s10-chapters">Chapter by chapter: where CBSE students most need help</h2>
  <p>
    Every student is different, but some chapters come up again and again when parents ask us for a Class 10 science
    tutor.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Carbon and its Compounds</h3>
  <p>
    Often the hardest chemistry chapter: covalent bonding, electron-dot structures, homologous series, naming
    compounds with functional groups, and reactions of ethanol and ethanoic acid. It rewards slow, careful teaching
    and a lot of practice at drawing structures and naming them.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Life Processes</h3>
  <p>
    Long and diagram-heavy: nutrition, respiration, transport and excretion in plants and animals. Students need to
    connect the processes rather than learn four separate lists, and to draw the digestive system, heart and nephron
    confidently.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Light – Reflection and Refraction</h3>
  <p>
    Ray diagrams, sign convention, the mirror and lens formulas and refractive index. This chapter carries a large
    share of the physics marks and is where careful routine pays off most.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Electricity</h3>
  <p>
    Ohm's law, resistivity, series and parallel combinations, heating effect and electric power. Students who are
    uncertain with algebra struggle here, so a tutor may need to shore up the maths alongside the physics.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Acids, Bases and Salts</h3>
  <p>
    Many reactions and compounds to keep straight, including the preparation and uses of common salts such as
    baking soda, washing soda, bleaching powder and plaster of Paris. Summary tables built by the student help.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Heredity and Reproduction</h3>
  <p>
    Mendel's experiments, dominant and recessive traits, sex determination, and reproduction in plants and animals.
    Precise terminology matters, and cross diagrams must be set out clearly to earn full marks.
  </p>
      </div>
    </div>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s10-mistakes">Common Class 10 science mistakes (and how a tutor fixes them)</h2>
  <ul>
    <li><strong>Unbalanced or unlabelled equations.</strong> Writing a word equation where a balanced chemical equation is expected, or leaving out the physical states. Fix: every equation written in tuition is balanced and checked, without exception.</li>
    <li><strong>Sign convention errors in light.</strong> Using the wrong sign for focal length or object distance in mirror and lens numericals. Fix: a fixed routine of drawing the principal axis and marking directions before substituting.</li>
    <li><strong>Units missing or wrong.</strong> Resistance written without ohms, power confused with energy, kilowatt-hour mixed up with watt. Fix: units written at every step, not just the answer.</li>
    <li><strong>Copying diagrams from memory incorrectly.</strong> Arrows reversed in the heart or in a circuit, parts of the nephron mislabelled. Fix: draw from the NCERT figure several times, then from memory, then check.</li>
    <li><strong>Mixing up similar terms.</strong> Respiration and breathing, pollination and fertilisation, genes and chromosomes, series and parallel. Fix: short comparison tables the student writes in their own words.</li>
    <li><strong>Long answers without structure.</strong> A five-mark answer written as one paragraph. Fix: points, keywords underlined, a diagram where it helps.</li>
    <li><strong>Skipping NCERT in favour of guidebooks.</strong> Reference books have their place, but board questions follow NCERT's wording and in-text activities closely. Fix: NCERT text, in-text questions and exercises first, NCERT Exemplar next.</li>
    <li><strong>Not practising under time.</strong> Students who know the material still run out of time in the board paper. Fix: full-length timed papers from December, reviewed question by question.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s10-practicals">Practicals and internal assessment</h2>
  <p>
    Internal assessment is 20 marks in both boards, and it is easy to take for granted. In CBSE, the 2026-27
    curriculum splits it into periodic assessment, multiple assessment, a portfolio and practical work, and the
    theory paper itself can include questions based on the prescribed experiments. Those experiments include finding
    the pH of common solutions, observing types of chemical reactions, comparing the reactivity of metals, studying
    Ohm's law and resistors in series and parallel, preparing a temporary mount of a leaf peel to show stomata,
    finding the focal length of a concave mirror and a convex lens, and tracing rays through a glass slab and a prism.
  </p>
  <p>
    Experiments themselves belong in the school lab. What a tutor can do at home is go through each experiment's aim,
    materials, procedure, observations, precautions and sources of error, so the student can answer practical-based
    questions confidently and write up practical files properly. Anything involving heating, acids or mains
    electricity should not be attempted at home.
  </p>
  <p>
    In ICSE, the 20 internal marks for each of Physics, Chemistry and Biology come from practical work set by the
    school. The student should keep the practical record complete and up to date through the year rather than
    rushing it before submission.
  </p>
  </section>

