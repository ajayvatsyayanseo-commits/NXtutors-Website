  <h2 id="sci-boards">Science in CBSE, ICSE and other boards</h2>
  <p>
    The science a child studies depends heavily on the board, and a tutor's experience with one does not
    automatically transfer to another. We match on board as well as class.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>CBSE</h3>
  <p>
    CBSE teaches science as a single integrated subject from Class 6 to Class 10, using NCERT textbooks. In Classes 9
    and 10 the book mixes physics, chemistry and biology chapters, and the Class 10 board paper is one science paper
    of 80 marks plus 20 marks of internal assessment. Papers include objective questions, assertion and reason,
    short and long answers, and case-based questions, so a CBSE tutor needs to train both understanding and
    application.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>ICSE</h3>
  <p>
    Many ICSE schools (under CISCE) teach Physics, Chemistry and Biology as separate subjects well before Class 10,
    often with separate textbooks and sometimes separate teachers. At Class 10 each is examined as its
    own paper. ICSE science covers more content per subject than CBSE and expects precise, well-structured written
    answers; chemistry in particular goes further into topics like the mole concept and analytical chemistry. ICSE
    families often need help with the sheer volume and with planning revision across three papers.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>IGCSE and IB MYP</h3>
  <p>
    Some families are in Cambridge IGCSE or IB Middle Years Programme schools. IGCSE science (Biology, Chemistry,
    Physics, or combined options) is examined through structured papers where command words and practical skills
    matter a great deal. IB MYP sciences are assessed against criteria that include inquiry, designing
    investigations and reflecting on the impact of science, so tutoring leans towards scientific writing and
    investigation skills rather than drilling. We shortlist tutors who have taught these programmes specifically.
  </p>
