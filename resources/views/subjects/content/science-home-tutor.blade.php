  <section class="nx-guide__sec">
  <h2 id="sci-olympiad">Olympiads, foundation courses and stretching a strong student</h2>
  <p>
    Some Class 6 to 10 students enjoy science enough to want more: science olympiads, national-level talent
    searches, or an early foundation for NEET or JEE. A home tutor can help here in ways a large batch cannot.
  </p>
  <ul>
    <li><strong>Depth over speed.</strong> Olympiad questions reward reasoning, not recall. The best preparation is working slowly through fewer, harder problems and discussing why an approach works.</li>
    <li><strong>No neglect of school work.</strong> A foundation course that leaves board chapters shaky is a poor trade. A tutor can make sure NCERT is secure first and stretch from there.</li>
    <li><strong>Watch the load.</strong> Adding olympiad preparation, coaching and school tests together can burn out a twelve-year-old. A tutor should help you choose rather than add.</li>
  </ul>
  <p>
    Check the official website of each olympiad for its current syllabus, levels and dates, as these change from
    year to year.
