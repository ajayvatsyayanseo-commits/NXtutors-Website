  <h2 id="sci-signs">Signs your child needs a science tutor</h2>
  <p>
    Not every child needs tuition, and not every low mark means the child is weak at science. These are the signs
    that usually point to a real gap that one-to-one teaching can fix:
  </p>
  <ul>
    <li><strong>Good at reading, poor at explaining.</strong> The child can read the chapter aloud but cannot tell you in their own words why something happens. This is the classic sign of memorising without understanding.</li>
    <li><strong>Numericals avoided.</strong> The physics questions are left for last, or skipped. Often the real problem is maths (rearranging a formula, handling units or decimals), and a tutor needs to spot that.</li>
    <li><strong>Diagrams skipped or copied.</strong> Diagrams are drawn only by tracing, or left out of answers altogether.</li>
    <li><strong>Marks falling in Class 9.</strong> A drop of this kind is common and fixable, but it rarely fixes itself before Class 10.</li>
    <li><strong>Confusion between the three sciences.</strong> Terms from chemistry turn up in biology answers and vice versa, or the child cannot tell which chapter a question belongs to.</li>
    <li><strong>Homework battles every evening.</strong> If science homework has become a source of stress at home, an outside person often lowers the temperature as much as the tutoring helps.</li>
    <li><strong>A strong student who is bored.</strong> Tuition is not only for catching up. A curious child who finishes the NCERT questions in minutes may benefit from a tutor who stretches them with harder problems or olympiad-style questions.</li>
  </ul>
