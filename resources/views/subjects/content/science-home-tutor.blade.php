  <h2 id="sci-stages">What science looks like from Class 6 to Class 10</h2>
  <p>
    School science is cumulative in a way parents do not always see. The idea of particles in Class 6 becomes the
    atom in Class 9 and chemical bonding in Class 10. Measuring length and time in Class 6 becomes speed and
    acceleration in Class 9 and electric current in Class 10. A gap left open at one stage tends to reappear, larger,
    two years later. That is why the right kind of help changes from stage to stage.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Classes 6 to 8: curiosity and foundations</h3>
  <p>
    Middle-school science is broad and practical: food and nutrition, materials and their properties, light and
    shadows, electricity and circuits, living things and their habitats, force and pressure, and simple chemical
    changes. The aim of a tutor here is not to pile on extra content but to make sure the child understands why
    things happen and can explain it in their own words. The habits built now, reading a diagram carefully, writing
    a definition precisely, asking "how do we know?", are the habits that decide Class 9 and 10. One or two sessions
    a week is usually plenty.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Class 9: the jump</h3>
  <p>
    Class 9 is where most families first look for a science tutor, and for good reason. The subject suddenly
    becomes three subjects in one course. Physics brings topics such as motion, force and laws of motion, gravitation, work and
    energy, and sound, with numericals and graphs. Chemistry brings matter, atoms and molecules, and the structure of
    the atom, with its own vocabulary and formulas. Biology brings the cell, tissues and a lot of precise
    terminology and diagrams. Students who coasted through Classes 6 to 8 on memory often find that memory alone no
    longer works.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Class 10: the board year</h3>
  <p>
    Class 10 science is examined as one paper in CBSE and as three separate papers in ICSE. The content deepens
    (chemical reactions and equations, carbon compounds, life processes, heredity, light, electricity and magnetic
    effects) and the questions are increasingly competency-based: case studies, assertion and reason, data and
    diagrams to interpret. The work shifts from learning chapters to practising under exam conditions. We have a
    separate, detailed guide to <a href="{{ url('/science-home-tutor/class-10') }}">Class 10 science tuition</a>.
  </p>
      </div>
    </div>
  <p>
    The single most useful thing a parent can do is start before the jump. A tutor who begins in the summer before
    Class 9, or in April of Class 9, has time to fix the Class 7 and 8 gaps quietly while teaching the new syllabus.
    A tutor who begins in the December before the Class 10 boards is working against the clock.
  </p>
