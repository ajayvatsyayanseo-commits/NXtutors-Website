  <h2 id="sci-choose">How to choose the best science tutor: a demo checklist</h2>
  <p>
    A tutor's profile tells you about qualifications and experience. A demo class tells you whether they can teach
    your child. During and after the demo, ask yourself:
  </p>
  <ol>
    <li><strong>Did the tutor start by finding out what the child knows?</strong> A few quick questions on the current chapter, and perhaps on the chapter before it, should come before any teaching.</li>
    <li><strong>Did they explain the concept, not just the answer?</strong> Ask them to explain one idea the child found hard in a second, different way.</li>
    <li><strong>Did the child draw or solve something?</strong> A diagram or a numerical attempted by the child during the demo tells you more than any explanation from the tutor.</li>
    <li><strong>Do they know the board?</strong> Ask how the Class 10 paper is structured for your board, and how they use NCERT (for CBSE) or the prescribed textbooks (for ICSE).</li>
    <li><strong>Can they link science to real life?</strong> Good science teaching constantly connects to the kitchen, the road, the body and the weather.</li>
    <li><strong>Did they suggest a plan?</strong> What will the first month cover, how often will there be tests, and how will you hear about progress?</li>
    <li><strong>How did your child feel afterwards?</strong> Comfort matters, especially for younger children. A child who wants to ask questions is a child who will learn.</li>
  </ol>
