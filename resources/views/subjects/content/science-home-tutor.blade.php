  <h2 id="sci-mode">Science tuition at home or online?</h2>
  <p>
    Both work well for science, and the right answer depends on the child more than the subject.
  </p>
  <ul>
    <li><strong>Home tuition suits</strong> younger students, children who drift on a screen, and students who need to practise diagrams and numericals by hand while someone watches their working. A tutor sitting beside the child can see where the pencil hesitates.</li>
    <li><strong>Online tuition suits</strong> older, self-motivated students, families in areas where good science tutors are few, and students who need a specialist (ICSE Chemistry, IGCSE Physics) who may not live nearby. A good online tutor uses a digital whiteboard or a document camera so diagrams and working are still visible.</li>
    <li><strong>Hybrid</strong> is common: one home session a week for hand-written practice and the relationship, plus one online session for doubt clearing or a test.</li>
  </ul>
