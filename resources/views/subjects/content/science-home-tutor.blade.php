  <h2 id="sci-how">How a good science home tutor teaches</h2>
  <p>
    Science tuition is often reduced to "finishing the chapter" and "doing the back exercises". That gets homework
    done but rarely changes marks or confidence. The tutors we look for work in a recognisably different way.
  </p>
  <ul>
    <li><strong>Concepts before answers.</strong> Before any question is attempted, the student should be able to explain the idea in plain words: why a balloon rubbed on hair sticks to the wall, why the sky looks blue, why a plant kept in the dark turns yellow. A tutor who can get a child to explain, rather than recite, is teaching science.</li>
    <li><strong>NCERT first.</strong> For CBSE students, the NCERT textbook is the syllabus, and board papers draw closely on its wording, examples, in-text questions and activities. A good tutor works line by line through NCERT before touching any reference book or question bank, and uses NCERT Exemplar for harder practice.</li>
    <li><strong>Diagrams as a skill.</strong> Biology and physics answers lose marks for diagrams that are unlabelled, labelled wrongly or drawn without a pencil and a clear outline. The human heart, the nephron, the eye, ray diagrams for mirrors and lenses, the structure of a flower, circuit diagrams: each needs to be practised until the student can draw it neatly from memory in a couple of minutes.</li>
    <li><strong>Numericals, step by step.</strong> Physics numericals (speed, acceleration, force, work, power, resistance, lens and mirror formula) and chemistry calculations (mole concept in ICSE and in higher classes) are where marks are most often lost to careless steps and missing units. A tutor should insist on writing the formula, substituting with units and boxing the final answer, every single time.</li>
    <li><strong>Experiments at home, safely.</strong> Many NCERT activities can be done at the dining table with household materials: separating mixtures, testing indicators with turmeric or red cabbage, making a simple circuit with a cell and a bulb, watching germination, observing refraction through a glass of water. Anything involving heat, flames, strong acids or mains electricity belongs in the school lab, not at home, and a responsible tutor will say so.</li>
    <li><strong>Language of the answer.</strong> Science answers are marked against keywords. "The ball falls because of gravity" and "The Earth exerts a gravitational force on the ball which accelerates it towards the Earth's centre" earn very different marks. Tutors should model and correct the exact phrasing boards reward.</li>
    <li><strong>Regular short tests.</strong> A chapter test every two to four weeks, marked the way the board marks, shows whether understanding is improving rather than just homework getting done.</li>
  </ul>
