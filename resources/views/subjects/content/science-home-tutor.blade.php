  <p>
    This is one of the most common questions parents ask us, and the answer depends on the class and board.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>One tutor for all science</h3>
  <p>
    For Classes 6 to 8 in any board, and for CBSE Classes 9 and 10, one good science tutor is usually the right
    choice. CBSE science is a single subject with one textbook and one exam, and a tutor who sees the whole subject
    can plan revision across physics, chemistry and biology, and link ideas between them. It is also simpler and
    usually less expensive to schedule one tutor than three.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Separate specialists</h3>
  <p>
    For ICSE Classes 9 and 10, where Physics, Chemistry and Biology are separate papers, or for a CBSE student with
    one clearly weak area (often physics numericals or chemical equations), a specialist for that part can make
    more difference than general science tuition. Many families use one tutor for all three and bring in a
    specialist only for the weakest.
  </p>
