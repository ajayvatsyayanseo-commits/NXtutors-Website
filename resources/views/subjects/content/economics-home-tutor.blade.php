  <h2 id="ecGuideTitle">Economics home tutor: a guide for parents and students</h2>

  <p class="nx-guide__lede">
    Economics looks like the gentle subject in a commerce or humanities timetable, and then the first test comes
    back. Students discover that it asks for four different skills at once: precise definitions, accurate diagrams,
    calculations (index numbers, national income, elasticity), and written arguments that weigh one effect against
    another. A student can be good at two of these and still score poorly. This guide sets out what CBSE, ISC,
    Cambridge and the IB actually assess in economics, where marks are usually lost, what a strong tutoring session
    looks like, and how to judge an economics tutor in one demo class.
  </p>

