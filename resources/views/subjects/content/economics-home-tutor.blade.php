  <h2 id="ec-cbse">CBSE Economics in Classes 11 and 12</h2>
  <p>
    CBSE Economics (subject code 030) is a three-hour, 80-mark theory paper plus 20 marks of project work in each of
    Classes 11 and 12. The 2026-27 curriculum divides it like this:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>CBSE Economics parts and marks, 2026-27 (from the CBSE curriculum document)</caption>
    <thead>
      <tr><th scope="col">Class</th><th scope="col">Part and units</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>11</td><td>Part A, Statistics for Economics: introduction; collection, organisation and presentation of data; statistical tools and interpretation</td><td>40</td></tr>
      <tr><td>11</td><td>Part B, Introductory Microeconomics: introduction (4); consumer's equilibrium and demand (14); producer behaviour and supply (14); perfect competition and price determination (8)</td><td>40</td></tr>
      <tr><td>12</td><td>Part A, Introductory Macroeconomics: national income (10); money and banking (6); determination of income and employment (12); government budget (6); balance of payments (6)</td><td>40</td></tr>
      <tr><td>12</td><td>Part B, Indian Economic Development: development experience 1947-90 and reforms since 1991 (12); current challenges (20); comparison with neighbours (8)</td><td>40</td></tr>
      <tr><td>11 and 12</td><td>Part C, Project Work</td><td>20</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The suggested question paper design gives about 40% of the theory marks to remembering and understanding, 30% to
    applying, and 30% to analysing, evaluating and creating. Class 11 statistics is a common surprise for students who
    dropped maths: it is arithmetic rather than advanced maths, but it needs careful, tabulated working, and the CBSE
    document asks students to interpret numerical results, not just calculate them. A tutor can make it one of the
    most reliable parts of the paper.
  </p>
  <p>
    The project deserves attention early. CBSE expects one project in each session, of 3,500 to 4,000 words
    (excluding diagrams and graphs), preferably handwritten, and presented to an internal and an external examiner.
    It is marked for relevance of the topic (3), knowledge content and research (6), presentation (3) and a viva (8).
    CBSE asks teachers to help students choose a topic from recent news, government policy, RBI bulletins or similar
    sources, and to check that the work is the student's own. A tutor can help a student understand the economics
    behind a chosen topic and rehearse for the viva; the research and writing must stay the student's.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ec-isc">ISC Economics</h2>
  <p>
    ISC Economics (856) follows CISCE's standard pattern: a three-hour, 80-mark theory paper with a compulsory Part I
    of 20 marks (short answers across the whole syllabus) and a Part II in which students answer five questions out of
    eight, each worth 12 marks, plus two projects of 10 marks each, marked on format, content, findings and a viva.
  </p>
  <p>
    The Class 11 syllabus covers understanding economics (basic concepts and the micro-macro distinction), Indian
    economic development and statistics. Class 12 covers microeconomic theory, the theory of income and employment,
    money and banking, balance of payments and exchange rate, public finance and national income. Compared with CBSE,
    60 of the 80 theory marks in ISC come from the 12-mark Part II questions, so practising complete answers to time
    matters a great deal.
  </p>
  </section>

