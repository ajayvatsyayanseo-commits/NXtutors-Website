  <h2 id="ec-skills">The four skills economics really tests</h2>
  <ul>
    <li><strong>Definitions that are exact.</strong> "Demand" is not the same as "want", and "GDP at market price" is not the same as "national income". Examiners give marks for the precise wording, and loose everyday language loses them.</li>
    <li><strong>Diagrams that carry the argument.</strong> Supply and demand, cost curves, aggregate demand and supply, the production possibility curve. A correct diagram is labelled fully (axes, curves, equilibrium points, the direction of any shift) and referred to in the written answer. Many students draw one and never mention it.</li>
    <li><strong>Numericals.</strong> Statistics in CBSE Class 11 (averages, correlation, index numbers), national income and the multiplier in Class 12, elasticity everywhere. These are steady marks for a student who sets out the working.</li>
    <li><strong>Evaluation.</strong> From Class 12 upwards, and throughout IB and A Level, the higher marks go to answers that weigh a policy's benefits against its costs, consider who is affected, and reach a judgement. This is the skill that separates good scores from excellent ones, and it is the one that responds most to one-to-one practice.</li>
  </ul>
  <p>
    A tutor's first job is to find which of the four is weak. A student who "does not understand economics" often
    understands the ideas well and is losing marks on diagrams alone, or writes fluent essays that never use a
    number. The fix is different in each case.
  </p>
