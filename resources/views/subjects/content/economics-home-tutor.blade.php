  <section class="nx-guide__sec">
  <h2 id="ec-ib">IB Economics SL and HL</h2>
  <p>
    IB Diploma Economics sits in group 3, individuals and societies. The IBO describes the course as examining
    economic choices at three levels (individual markets, the national economy, and the global economy) through nine
    key concepts: scarcity, choice, efficiency, equity, economic well-being, sustainability, change, interdependence
    and intervention. The syllabus has four units: introduction to economics, microeconomics, macroeconomics, and the
    global economy. The current course was first assessed in 2022. The IB recommends 150 teaching hours at SL and 240
    at HL.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>IB Economics assessment (from the IBO subject briefs)</caption>
    <thead>
      <tr><th scope="col">Component</th><th scope="col">What it is</th><th scope="col">SL</th><th scope="col">HL</th></tr>
    </thead>
    <tbody>
      <tr><td>Paper 1</td><td>Extended response paper on all units</td><td>1 h 15 min, 30%</td><td>1 h 15 min, 20%</td></tr>
      <tr><td>Paper 2</td><td>Data response paper on all units</td><td>1 h 45 min, 40%</td><td>1 h 45 min, 30%</td></tr>
      <tr><td>Paper 3</td><td>Policy paper on all units</td><td>Not taken</td><td>1 h 45 min, 30%</td></tr>
      <tr><td>Internal assessment</td><td>Portfolio of three commentaries</td><td>30%</td><td>20%</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    <strong>The internal assessment.</strong> Both SL and HL students produce a portfolio of three commentaries, each
    based on a published extract from the news media. The subject briefs say the three must be based on different
    units of the syllabus (not the introductory unit) and analysed using different key concepts, with 20 teaching
    hours allocated to the task. The skill being assessed is linking a real news story to economic theory and a key
    concept, with a diagram where it helps. A tutor can teach that skill on practice articles, help a student judge
    whether an article gives enough to work with, and explain the assessment criteria. Under IB academic-integrity
    rules, the tutor must never write or rewrite any part of the commentaries.
  </p>
  <p>
    HL Paper 3 is the component with no equivalent in the other boards. It is a policy paper: the IBO's sample
    question gives students data about a country and asks them to recommend a policy in response. It rewards clear
    use of the data followed by a reasoned recommendation, which improves quickly with guided practice.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ec-cuet">Economics in CUET (UG)</h2>
  <p>
    The NTA's CUET (UG) 2026 information bulletin lists <strong>Economics / Business Economics</strong> (code 309)
    among the domain subjects. Each domain test has 50 compulsory questions in 60 minutes, and the domain syllabus
    follows NCERT's Class 12 syllabus. Because the format is objective, CUET preparation is about recognising concepts
    quickly and doing short calculations accurately, built on board preparation rather than in place of it.
    Check the bulletin for the year your child applies.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ec-session">What a strong economics session looks like</h2>
  <p>
    Economics tutoring works when the student talks, draws and writes, and the tutor questions. A one-hour session for
    a Class 12, A Level or IB student might go like this:
  </p>
  <ol>
    <li><strong>A news item, five minutes.</strong> The tutor brings one current story (a fuel price change, an interest rate decision) and asks which part of the syllabus it belongs to.</li>
    <li><strong>The concept, fifteen minutes.</strong> The tutor teaches or revisits one idea, with the student drawing the diagram, not copying it.</li>
    <li><strong>A numerical, fifteen minutes.</strong> One calculation set out as the examiner wants to see it.</li>
    <li><strong>A written answer, twenty minutes.</strong> One exam-style question answered in full, then marked together against the board's criteria.</li>
    <li><strong>Next steps, five minutes.</strong> What to practise, and what the tutor will check next time.</li>
  </ol>
  <p>
    A small worked example of the numerical habit: the price of a good rises from ₹10 to ₹12 and the quantity demanded
    falls from 100 units to 90. The percentage change in quantity is −10%, the percentage change in price is +20%, so
    price elasticity of demand is −10 ÷ 20 = −0.5. Demand is inelastic, and total spending on the good rises (from
    ₹1,000 to ₹1,080). A student who can do the arithmetic but cannot say what the answer means for sellers or for a
    tax on the good has done half the question. The tutor's job is to make that second half automatic.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ec-demo">How to judge an economics tutor in the demo class</h2>
  <p>The first class is a free demo. While it runs, look for these signs:</p>
  <ol>
    <li>Does the tutor ask for the board and exact course (CBSE, ISC, IGCSE, AS or A Level, IB SL or HL) before teaching?</li>
    <li>Does your child draw the diagrams, with every axis and curve labelled?</li>
    <li>Does the tutor push for a judgement ("so which effect is bigger, and why?") rather than a list of points?</li>
    <li>Are real-world examples current and relevant, not ten years old?</li>
    <li>For IB students, can the tutor explain the IA criteria and the Paper 3 approach clearly, and do they say plainly that they will not write the commentaries?</li>
    <li>For CBSE students, do they know the statistics and national income numericals well enough to teach the working step by step?</li>
    <li>Does the session end with specific practice and a way to check it?</li>
  </ol>
