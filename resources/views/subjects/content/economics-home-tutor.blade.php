  <h2 id="ec-mode">Home or online economics tuition</h2>
  <p>
    Economics suits online tuition better than many subjects. Diagrams work well on a shared whiteboard or a writing
    tablet, news articles can be opened together, and essay drafts can be marked on screen. Online tuition also widens
    the choice for IB and A Level economics, where the number of experienced tutors near any one home is small. Home
    tuition still suits younger students, students who lose focus on a screen, and CBSE Class 11 statistics, where a
    tutor watching the pencil catches arithmetic slips as they happen.
