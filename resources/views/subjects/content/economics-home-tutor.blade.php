  <h2 id="ec-cambridge">Cambridge IGCSE Economics and AS &amp; A Level Economics</h2>
  <p>
    IGCSE Economics (0455) is taught in six sections: the basic economic problem, the allocation of resources,
    microeconomic decision-makers, government and the macroeconomy, economic development, and international trade and
    globalisation. At AS and A Level (9708), the content deepens and the essays lengthen.
