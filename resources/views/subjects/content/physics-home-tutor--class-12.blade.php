  </div>
  <p>What this means for planning:</p>
  <ul>
    <li><strong>Electricity and magnetism are the core.</strong> Units I to IV, chapters 1 to 7, carry 33 of the 70 marks and take up well over half the teaching time.</li>
    <li><strong>EM waves and optics form the largest single block.</strong> 18 marks, with ray diagrams, lens and mirror numericals and wave optics.</li>
    <li><strong>Modern physics and semiconductors are compact.</strong> Chapters 11 to 14 are shorter and more direct, together worth 19 marks. They reward precise NCERT study and are ideal revision chapters.</li>
    <li><strong>Several topics are qualitative or formula-only this year.</strong> For example, the energy stored in a capacitor is listed without derivation, the Young's double-slit fringe width as a final expression only, and the bar magnet treatment qualitatively. Knowing this saves time better spent on practice.</li>
  </ul>
  <p>
    Content marked as excluded in the current NCERT textbooks is not assessed in the 2026-27 board exam, so the tutor
    should teach from the current edition.
  </p>
