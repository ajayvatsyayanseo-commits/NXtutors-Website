  <p>
    CBSE points students to the Class 12 sample question paper for the exact section structure, which it publishes
    each year. The pattern above is the important part: 43 of the 70 marks go to applying and analysing. Case-based
    questions, assertion–reason items and problems that combine two chapters live here. A student who has memorised
    derivations but not practised unfamiliar questions can lose a large share of the paper.
  </p>
  <p>
    A tutor should work through the current sample paper and its marking scheme early, around August, so the student
    knows the target, and then return to it in full-length form during revision.
