  <section class="nx-guide__sec">
  <h2 id="p12-mistakes">Mistakes that cost Class 12 physics marks</h2>
  <ul>
    <li><strong>Unlabelled or missing diagrams</strong> in derivations, ray optics and circuits.</li>
    <li><strong>Sign convention slips</strong> in mirror and lens problems, and in potential and potential energy.</li>
    <li><strong>Missing or wrong units</strong>, and answers without the vector direction when direction was asked.</li>
    <li><strong>Reciting a derivation</strong> that does not match the figure given in the question.</li>
    <li><strong>Case-based questions answered from memory</strong> instead of from the passage.</li>
    <li><strong>Practical file finished in a rush</strong>, losing easy record and viva marks.</li>
    <li><strong>No timed papers</strong> before the pre-board, so the student runs short of time on the long answers.</li>
  </ul>
