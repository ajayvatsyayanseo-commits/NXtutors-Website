  <section class="nx-guide__sec">
  <h2 id="p12-derivations">Derivations: build a list, understand each one, write it under time</h2>
  <p>
    Derivations are a reliable source of board marks and a frequent source of anxiety. The approach that works is to
    build the student's own derivation list from the 2026-27 syllabus text, chapter by chapter, and treat each item
    as reasoning to understand rather than text to memorise.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Chapter group</th><th scope="col">Results the syllabus asks students to derive or apply</th></tr>
    </thead>
    <tbody>
      <tr><td>Electrostatics</td><td>Field of a dipole; torque on a dipole; Gauss's theorem for a long wire, infinite sheet and thin spherical shell; potential due to a dipole; capacitance of a parallel-plate capacitor with and without a dielectric.</td></tr>
      <tr><td>Current electricity</td><td>Drift velocity and its relation to current; combination of cells; Kirchhoff's rules and the Wheatstone bridge.</td></tr>
      <tr><td>Magnetism and induction</td><td>Biot–Savart law for a circular loop; Ampere's law for a long straight wire; force between parallel conductors; torque on a current loop; galvanometer conversion to ammeter and voltmeter; LCR series circuit using phasors.</td></tr>
      <tr><td>Optics</td><td>Mirror and thin lens formulae; refraction at spherical surfaces; lens maker's formula; prism; magnifying power of microscopes and telescopes; laws of reflection and refraction using Huygens' principle.</td></tr>
      <tr><td>Modern physics</td><td>Einstein's photoelectric equation; de Broglie relation; Bohr model expressions for radius, velocity and energy in the nth orbit.</td></tr>
    </tbody>
  </table>
  </div>
  <p>For each derivation, a good tutor makes sure the student can:</p>
  <ul>
    <li><strong>Draw the diagram first</strong>, labelled, because the diagram carries marks and organises the argument.</li>
    <li><strong>State the assumptions</strong>: an infinite sheet, a thin lens, paraxial rays, a point charge. Examiners and entrance papers both test these.</li>
    <li><strong>Explain each step aloud</strong> before writing it. If the student cannot say why a step follows, they will not reproduce it under pressure.</li>
    <li><strong>Write it under time</strong>, once a fortnight, marked as an examiner would.</li>
  </ul>
