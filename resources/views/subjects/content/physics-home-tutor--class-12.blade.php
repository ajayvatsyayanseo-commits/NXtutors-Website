  <section class="nx-guide__sec">
  <h2 id="p12-chapters">Chapter by chapter: where Class 12 students get stuck</h2>
  <ul>
    <li><strong>Electric Charges and Fields.</strong> Superposition of forces from several charges needs Class 11 vectors. Gauss's theorem is easy to state and hard to apply: choosing the right Gaussian surface is the skill.</li>
    <li><strong>Potential and Capacitance.</strong> Students confuse potential with potential energy and field with potential. Capacitor networks and the effect of inserting a dielectric are regular numericals.</li>
    <li><strong>Current Electricity.</strong> Drift velocity, internal resistance, cells in series and parallel, and Kirchhoff's rules. Circuit reduction is a practice skill; it does not come from reading.</li>
    <li><strong>Moving Charges and Magnetism.</strong> Right-hand rules and three-dimensional directions. Many errors are about direction, not magnitude. The galvanometer conversions link directly to practicals.</li>
    <li><strong>Magnetism and Matter.</strong> Largely qualitative in 2026-27: para-, dia- and ferromagnetism and the effect of temperature. Short, precise answers score well.</li>
    <li><strong>Electromagnetic Induction and Alternating Current.</strong> Lenz's law direction questions, self and mutual inductance, then RMS values, reactance, impedance, resonance and power factor in the LCR circuit. Phasor diagrams make the AC chapter far easier.</li>
    <li><strong>Electromagnetic Waves.</strong> Displacement current and the spectrum with uses of each band. Pure recall, and easy marks if revised.</li>
    <li><strong>Ray Optics.</strong> The longest chapter. Sign convention, lens and mirror formulae, total internal reflection, prisms and optical instruments with neat ray diagrams.</li>
    <li><strong>Wave Optics.</strong> Huygens' principle, interference and single-slit diffraction. Conceptual questions dominate.</li>
    <li><strong>Dual Nature, Atoms and Nuclei.</strong> Photoelectric graphs, de Broglie wavelength, Bohr model energies and binding energy per nucleon. Formula-driven and quick to revise.</li>
    <li><strong>Semiconductor Electronics.</strong> Energy bands, p- and n-type materials, the p–n junction and the diode as a rectifier. Diagrams of the rectifier circuit and the I–V curve are common questions.</li>
  </ul>
  </section>

