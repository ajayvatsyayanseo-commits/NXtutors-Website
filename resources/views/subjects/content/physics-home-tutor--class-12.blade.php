  <section class="nx-guide__sec">
  <h2 id="p12-numericals">Numericals: where Class 12 marks are won and lost</h2>
  <p>
    Class 12 numericals are rarely hard in their arithmetic. They are hard because the student must choose the right
    principle from several that look plausible. A tutor builds this judgement through graded sets:
  </p>
  <ol>
    <li><strong>Direct application</strong> from NCERT in-text examples and exercises.</li>
    <li><strong>NCERT Exemplar</strong> and recent board papers, which add a twist or combine ideas.</li>
    <li><strong>Mixed-chapter sets</strong>, for example a capacitor in a circuit with a cell of internal resistance, or a lens combination with a mirror.</li>
  </ol>
  <p>
    The chapters where students most often need numerical practice are current electricity (circuit reduction and
    Kirchhoff's rules), capacitance (series and parallel with dielectrics), alternating current (impedance and
    resonance), ray optics (sign convention in lens and mirror problems) and dual nature (photoelectric equation).
    Every numerical should be set out as given, required, formula, substitution with units, answer with units.
  </p>
  <p>
    Two habits help more than anything else. First, estimate before calculating: if a capacitor's charge comes out
    in kilocoulombs or a lens's focal length in kilometres, something has gone wrong. Second, keep an error log: a
    single page where the student writes down every numerical they got wrong and why. By December that page is the
    most useful revision document they own, because it lists their own mistakes rather than someone else's.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="p12-practicals">Class 12 physics practicals: the 30 marks</h2>
  <p>
    Students record at least eight experiments (four from each section), six activities (three from each section) and
    an investigatory project. The practical exam is marked as follows:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Component</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>Two experiments, one from each section</td><td>7 + 7</td></tr>
      <tr><td>Practical record (experiments and activities)</td><td>5</td></tr>
      <tr><td>One activity from either section</td><td>3</td></tr>
      <tr><td>Investigatory project</td><td>3</td></tr>
      <tr><td>Viva on experiments, activities and project</td><td>5</td></tr>
      <tr><td><strong>Total</strong></td><td><strong>30</strong></td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Section A is electrical: resistivity from a V–I graph, the metre bridge, combination of resistances, galvanometer
    resistance by half-deflection and its conversion to an ammeter or voltmeter, and the frequency of AC mains with a
    sonometer. Section B is optics and electronics: focal lengths of mirrors and lenses, the angle of minimum deviation
    for a prism, refractive index with a travelling microscope or a liquid lens, and the p–n junction diode's I–V
    curve. A tutor can prepare the student for the theory behind each experiment, graph plotting, sources of error and
    the viva, and make sure the file and project are not left until January.
  </p>
  </section>

