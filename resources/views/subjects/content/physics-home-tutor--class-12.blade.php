  <h2 id="p12-year">What makes Class 12 physics different</h2>
  <p>
    Class 11 was mostly mechanics: objects you can picture moving. Class 12 is mostly electricity, magnetism and
    light, where the student has to reason about fields and waves that are only visible through their effects. The
    mathematics is lighter than the Class 11 calculus, but the reasoning is harder, and the chapters are tightly
    linked. Electrostatics feeds current electricity, which feeds magnetic effects, which feeds induction and
    alternating current.
  </p>
  <p>
    It is also a year of competing demands. School pre-boards arrive in December or January; practical files and the
    investigatory project are due before the theory exam; and entrance aspirants are sitting mock tests every week.
    Much of a Class 12 physics tutor's value lies in planning: deciding what to do this week so that none of these
    collapses in February.
  </p>
  </section>

