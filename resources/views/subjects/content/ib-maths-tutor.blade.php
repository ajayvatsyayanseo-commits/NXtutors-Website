  <h2 id="ibn-basics">How IB maths works for families across India</h2>
  <p>
    Every IB Diploma Programme (DP) student takes one maths course from Group 5. There are two courses, Mathematics:
    Analysis and Approaches (AA) and Mathematics: Applications and Interpretation (AI), and each runs at Standard Level
    (SL) or Higher Level (HL). That gives four options, and the choice matters more than many families expect. It
    affects the student's workload for two years, the kind of questions they face in the final exams, and in some
    cases which university courses they can apply for.
  </p>
  <p>
    The DP is a two-year programme, usually Grades 11 and 12. Final grades run from 1 to 7 for each subject. For maths,
    most of the grade comes from written papers taken at the end of DP2, and the rest comes from the mathematical
    exploration, a piece of individual written work that the school marks and the IB moderates. The school chooses
    which examination session its students sit, so check the date of your child's final exams with the school early
    in DP1 and plan backwards from it.
  </p>
  <p>
    What differs from city to city is not the course but the practicalities: how many specialist IB maths tutors live
    within reasonable travel time, how long the school day is, and how much time goes on CAS, the extended essay and
    other subjects. In the large metros there is usually a choice of home tutors for AA and AI at SL. For HL, and for
    AI HL in particular, the pool is smaller everywhere, which is why many families end up with an online or hybrid
    arrangement. If you are in Gurugram, our <a href="{{ url('/ib-maths-tutor-gurgaon') }}">IB maths tutor in
    Gurgaon</a> page covers the local picture.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ibn-courses">AA and AI in depth: what each course actually asks of a student</h2>
  <p>
    Both courses cover the same five topic areas: number and algebra; functions; geometry and trigonometry; statistics
    and probability; and calculus. There is a shared core that SL students on both courses study. The difference lies
    in emphasis, in how questions are posed, and in what the HL extension adds.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Analysis and Approaches (AA)</h3>
  <p>
    AA is built around algebraic fluency, reasoning and proof. Students are expected to manipulate expressions by hand,
    work with exact values, and justify their steps. Calculus runs through the whole course. At HL the course adds
    topics such as proof by induction and by contradiction, complex numbers, vectors in three dimensions including
    lines and planes, further calculus and differential equations, and series. The questions reward students who like
    to know why a method works, not only how to use it.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Applications and Interpretation (AI)</h3>
  <p>
    AI is built around modelling, data and technology. Questions typically start from a context, such as a data set,
    a loan, a network or a population, and ask the student to choose a model, use technology to work with it, and
    interpret the answer. Statistics is heavier than on AA. At HL the course adds topics such as matrices, graph
    theory, more advanced statistical testing and modelling with differential equations. AI HL is a demanding course;
    it is different from AA, not easier.
  </p>
      </div>
    </div>
  <p>
    A useful way to think about it: AA asks "can you do the mathematics precisely, by hand if needed, and explain it?"
    AI asks "can you pick the right mathematics for a real situation, use technology well, and say what the result
    means?" Both are genuine mathematics. Students who struggle on one course sometimes do well on the other, which is
    why the choice deserves thought rather than a default.
  </p>
