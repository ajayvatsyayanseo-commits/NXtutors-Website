  <h2 id="ibn-myp">Coming into DP maths: from MYP, IGCSE, CBSE or ICSE</h2>
  <p>
    Students across India arrive in DP1 from different routes, and each leaves different gaps.
  </p>
  <ul>
    <li><strong>From the IB Middle Years Programme (MYP).</strong> MYP maths is assessed against four criteria: knowing and understanding, investigating patterns, communicating, and applying mathematics in real-life contexts. MYP students are usually good at investigation and writing about maths, which helps with the exploration. The common gap is speed and accuracy in algebra under timed conditions. Many schools teach MYP maths at two levels, often called standard and extended, and the extended route is better preparation for AA, especially AA HL.</li>
    <li><strong>From Cambridge IGCSE.</strong> IGCSE Extended maths gives a solid base for most DP courses, though the style of DP questions is less predictable. Our <a href="{{ url('/igcse-maths-tutor') }}">IGCSE maths tutor</a> page covers that stage. Students who took Core rather than Extended may need extra work before AA.</li>
    <li><strong>From CBSE or ICSE Class 10.</strong> Some students join an IB school only for the Diploma. They often have strong procedural skill but are less used to GDC work, open-ended questions and the IB's command terms. A short bridging period at the start of DP1 helps.</li>
  </ul>
  <p>
    Whatever the route, the summer before DP1 is a good time for a few focused sessions on algebra, functions and
    trigonometry. The first weeks of DP1 move quickly, and students who start with gaps tend to spend the rest of the
    year catching up. Families still weighing the Diploma against other Class 11 options can compare with our
    <a href="{{ url('/isc-maths-tutor') }}">ISC maths tutor</a> page and the general
    <a href="{{ url('/maths-home-tutor/class-11') }}">Class 11 maths tutor</a> page.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ibn-revised">The revised IB maths courses: first teaching August 2027</h2>
  <p>
    The IB has published updates to both maths courses. According to ibo.org, the revised AA and AI courses are first
    taught from August 2027, with first assessment in May 2029. Both courses and both levels continue, and the IB
    describes the redevelopment as refinement rather than reinvention. The changes the IB has announced include:
  </p>
  <ul>
    <li><strong>Shorter papers.</strong> Papers 1 and 2 are reduced to 100 marks (from 110), and Paper 3 is reduced to 50 marks (from 55), with its time cut to one hour (from one hour and 15 minutes).</li>
    <li><strong>The exploration stays.</strong> The internal assessment remains largely the same task, and SL and HL now share the same assessment criteria, which have been revised to reflect the IB's description of the mathematical inquiry process.</li>
    <li><strong>More explicit emphasis on inquiry.</strong> The IB says the revised courses give greater emphasis to mathematical inquiry, problem formulation, interpretation and the appropriate use of technology.</li>
  </ul>
  <p>
    What this means in practice: a student who starts DP1 in August 2026 is on the current courses and sits final exams
    in 2028. A student who starts DP1 in August 2027 or later is on the revised courses. Detailed syllabus content for
    the revised courses is published to schools by the IB, so check with the school for anything not covered here.
    When you ask us for a tutor, tell us the exam year so we match someone teaching the right version.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ibn-uni">What your course choice means for university</h2>
  <p>
    This is the question that should drive the AA or AI decision more than any other, and it is the one families most
    often leave too late.
  </p>
  <p>
    Some university courses, particularly in mathematics, physics, engineering, computer science and some economics
    programmes, state which IB maths course and level they expect. Some ask specifically for AA HL; others accept AA SL
    or AI HL; many courses outside the sciences accept any IB maths course. Requirements differ between countries,
    between universities, and even between courses at the same university, and they change from year to year.
  </p>
  <p>
    The practical advice is simple. Before the course choice is final, list the universities and courses the student is
    seriously considering, in India and abroad, and read each one's current entry requirements for IB students on the
    university's own website. If a course names a particular maths course and level, treat that as fixed. Where the
    requirements are silent or unclear, ask the university's admissions office directly and keep the reply. The school's
    university counsellor is also a good first stop.
  </p>
  <p>
    Two further points. First, if the student is genuinely undecided between a maths-heavy degree and something else,
    AA (at SL or HL) usually keeps more doors open. Second, a student who takes AA HL for university reasons but finds
    the course overwhelming should talk to the school early; changing course or level is far easier in the first
    weeks of DP1 than in DP2.
  </p>
  </section>

