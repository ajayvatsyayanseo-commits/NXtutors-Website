  <section class="nx-guide__sec">
  <h2 id="ibn-choose">How to choose an IB maths tutor</h2>
  <p>
    A strong maths tutor is not automatically a strong IB maths tutor. The IB rewards particular habits, and the tutor
    should know the course well enough to build them. These are the questions worth asking before and during a demo.
  </p>
  <ol>
    <li><strong>Which course and level do you teach?</strong> Look for someone who teaches the student's exact course and level. AA HL and AI SL are very different jobs.</li>
    <li><strong>Which syllabus version?</strong> Students sitting exams in 2028 are on the current courses; those starting DP1 from August 2027 are on the revised ones. The tutor should know which applies.</li>
    <li><strong>How do you use IB command terms and markschemes?</strong> Terms such as "show that", "hence", "write down" and "sketch" tell the student how much working is needed. IB markschemes separate method, accuracy and answer marks and allow follow-through. A good tutor marks this way.</li>
    <li><strong>How do you handle the calculator?</strong> For AA, expect regular non-calculator work. For AI, expect confident GDC teaching.</li>
    <li><strong>What will you do, and not do, for the exploration?</strong> The answer should match the limits set out above. Any offer to write or edit the IA is a warning sign.</li>
    <li><strong>How will we know it is working?</strong> Expect a plan tied to the school calendar, an error log, and regular timed practice, with short updates to parents.</li>
  </ol>
  <p>
    In the demo itself, watch whether the tutor asks the student to explain their thinking rather than simply
    explaining at them, and whether they spot the specific kind of mistake the student keeps making. For IB students
    who also need help in science, see how we match for <a href="{{ url('/ib-physics-tutor-gurgaon') }}">IB physics</a>.
