  <section class="nx-guide__sec">
  <h2 id="ibn-levels">SL and HL: hours, papers and weightings</h2>
  <p>
    The IB recommends 150 teaching hours for an SL course and 240 for HL. HL is not simply SL plus a few chapters.
    HL questions are longer and less structured, they combine topics, and they leave more of the problem-solving to the
    student. A student who is comfortable at SL can find the jump to HL steep in the second half of DP1, when the extra
    material starts to pile up.
  </p>
  <p>
    On the current courses, external assessment is worth 80 percent and the exploration 20 percent at both levels. SL
    students sit two papers; HL students sit three.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <caption>IB DP maths assessment on the current courses</caption>
    <thead>
      <tr><th scope="col">Component</th><th scope="col">SL</th><th scope="col">HL</th><th scope="col">Notes</th></tr>
    </thead>
    <tbody>
      <tr><td>Paper 1</td><td>40%, 1 hour 30 minutes</td><td>30%, 2 hours</td><td>AA: no calculator. AI: GDC required</td></tr>
      <tr><td>Paper 2</td><td>40%, 1 hour 30 minutes</td><td>30%, 2 hours</td><td>GDC required on both courses</td></tr>
      <tr><td>Paper 3</td><td>Not taken</td><td>20%, 1 hour 15 minutes</td><td>Extended problem-solving questions, GDC required</td></tr>
      <tr><td>Exploration (IA)</td><td>20%</td><td>20%</td><td>Written investigation; marked by the teacher, moderated by the IB</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Papers 1 and 2 each have a short-response section and a long-response section. The short questions test whether a
    student can apply a method cleanly; the long questions build over several parts and often use a result from an
    earlier part. HL Paper 3 is a different kind of test: a small number of long problems that start somewhere familiar
    and lead the student step by step towards something new. It rewards patience and the confidence to keep going when
    a part looks unfamiliar. Students who practise Paper 3 style questions only in the last month usually find it the
    hardest paper; students who meet them regularly from DP1 find it far less daunting.
  </p>
  <p>
    A practical point about SL: with only two papers, each carries 40 percent. One bad paper is hard to recover from,
    so steady exam technique matters as much as knowledge.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ibn-marks">Where IB maths students most often lose marks</h2>
  <p>
    The same patterns come up again and again, whatever the course or city. Knowing them early lets a tutor work on
    them before they cost marks in a real paper.
  </p>
  <ul>
    <li><strong>Missing the command term.</strong> "Show that" needs every step written; "write down" needs little or no working. Students who treat every question the same way either waste time or drop method marks.</li>
    <li><strong>Unsupported answers from the calculator.</strong> A correct number with no indication of how it was found can lose marks when the question expects working. Students need to know how much to write down even when the GDC does the computation.</li>
    <li><strong>Rounding too early.</strong> Rounding in the middle of a long question carries errors into later parts. Keeping full accuracy until the end, and giving the final answer to the accuracy asked for, is a habit worth building from the first week.</li>
    <li><strong>Giving up on a long question after one hard part.</strong> Later parts of a long question can often be answered using a given result, even if the student could not prove it. Follow-through marks reward students who keep going.</li>
    <li><strong>Weak interpretation on AI.</strong> A correct calculation followed by a vague or wrong sentence about what it means in context loses marks that AI students can least afford.</li>
  </ul>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ibn-calc">The calculator rules, and why they shape how you revise</h2>
  <p>
    Technology is part of both courses, but not in the same way.
  </p>
  <ul>
    <li><strong>AA Paper 1 is taken without a calculator</strong> at both SL and HL. Students must simplify, solve, differentiate, integrate and work with exact trigonometric values by hand.</li>
    <li><strong>AA Paper 2 and HL Paper 3 require a graphic display calculator (GDC).</strong> Questions assume the student can use it to graph, find intersections, solve equations numerically and handle statistics.</li>
    <li><strong>All AI papers require a GDC.</strong> AI questions are written on the assumption that students use technology for the heavy computation, so the skill being tested is choosing and interpreting.</li>
  </ul>
  <p>
    In the exam room, the calculator must be a model the IB permits, set up in the way the IB requires for
    examinations. The rules are detailed and are updated from time to time, so follow your school's IB coordinator on
    which models are allowed and how they must be prepared before each exam. Do not buy a calculator on the strength of
    a friend's recommendation without checking with the school.
  </p>
  <p>
    For revision, this has two consequences. AA students need regular non-calculator practice all through the course,
    not just before Paper 1, because algebraic fluency fades quickly when the calculator is always on the desk. And
    every student needs to know their own GDC well. Minutes lost hunting through menus in Paper 2 are minutes not spent
    on the long questions. A tutor should build both habits into ordinary weekly sessions.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ibn-ia">The exploration (IA): what it is, and the limits on tutor help</h2>
  <p>
    The mathematical exploration is the internal assessment for both AA and AI, at both levels. The student chooses an
    area of mathematics that interests them, poses a focused question and investigates it in a written report. The
    IB's guidance suggests a length of roughly 12 to 20 pages. On the current courses it is marked out of 20 against
    five criteria: presentation, mathematical communication, personal engagement, reflection, and use of mathematics.
    It is worth 20 percent of the final grade, which is large enough to move a student up or down a whole grade.
  </p>
  <p>
    Parents often search for "IB maths IA help", and this is where families need to be careful. The exploration must
    be the student's own work. The IB's academic integrity policy applies to it, schools check submissions closely, and
    the consequences of a breach can reach the student's whole diploma, not just the maths grade. A good tutor
    protects the student here rather than putting them at risk.
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Help that is appropriate</h3>
  <ul>
    <li>Teaching the underlying mathematics, including ideas beyond the syllabus that the student wants to use.</li>
    <li>Explaining what each criterion looks for, using the IB's own published material.</li>
    <li>Asking questions that help the student test their own topic ideas for scope and depth.</li>
    <li>Talking through, in general terms, what good reflection or clear communication looks like.</li>
    <li>Encouraging the student to keep a record of their process and to meet the school's internal deadlines.</li>
  </ul>
      </div>
      <div class="nx-guide__card">
  <h3>Help that crosses the line</h3>
  <ul>
    <li>Choosing the topic or the research question for the student.</li>
    <li>Writing, rewriting, paraphrasing or "polishing" any part of the report.</li>
    <li>Doing the calculations, producing the graphs or writing code for the models.</li>
    <li>Editing a draft line by line or marking it against the criteria as if it were the teacher.</li>
    <li>Helping to hide outside support from the school.</li>
  </ul>
      </div>
    </div>
  <p>
    Formal feedback on a draft comes from the student's school teacher, not from a tutor. Students should tell their
    teacher that they have a tutor. If a tutor offers to "write the IA" or "guarantee a 7 on the IA", treat that as a
    reason to walk away.
  </p>
  <p>
    On topic choice, the most reliable explorations grow out of something the student genuinely cares about and can
    work through with mathematics they understand. An ambitious-sounding topic that the student cannot actually handle
    usually scores lower than a modest one explored thoroughly, with honest reflection on its limits.
  </p>
  </section>

