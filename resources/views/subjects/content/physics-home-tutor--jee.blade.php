  <section class="nx-guide__sec">
  <h2 id="pj-main">The JEE Main physics paper</h2>
  <p>
    Paper 1 of JEE Main (for B.E. and B.Tech.) is a computer-based test. The NTA's 2026 information bulletin sets out
    this structure:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Subject</th><th scope="col">Section A (MCQ)</th><th scope="col">Section B (numerical value)</th><th scope="col">Marks</th></tr>
    </thead>
    <tbody>
      <tr><td>Physics</td><td>20</td><td>5</td><td>100</td></tr>
      <tr><td>Chemistry</td><td>20</td><td>5</td><td>100</td></tr>
      <tr><td>Mathematics</td><td>20</td><td>5</td><td>100</td></tr>
      <tr><td><strong>Total</strong></td><td colspan="2"><strong>75 questions</strong></td><td><strong>300</strong></td></tr>
    </tbody>
  </table>
  </div>
  <ul>
    <li><strong>Time.</strong> Three hours for the whole paper, shared across three subjects as the student chooses.</li>
    <li><strong>Marking.</strong> Four marks for a correct answer and minus one for an incorrect answer, in both sections. Unanswered questions score zero.</li>
    <li><strong>Numerical-value questions.</strong> The answer is entered as a number using an on-screen keypad and rounded to the nearest integer. There are no options to eliminate, so the student must actually solve the problem.</li>
    <li><strong>Sessions.</strong> JEE Main is held in two sessions each year. Check the information bulletin for your exam year, which NTA publishes before registration opens, for dates and any change in pattern.</li>
  </ul>
  <p>
    Negative marking in Section B changes strategy: a numerical answer entered on a guess now carries a real cost.
    Physics tutors should practise Section B questions under the same rule.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pj-syllabus">The JEE Main physics syllabus</h2>
  <p>
    The NTA's JEE Main 2026 syllabus lists twenty physics units. Units 1 to 10 cover the Class 11 physics (units and
    measurements through oscillations and waves), units 11 to 19 cover Class 12 (electrostatics through electronic
    devices), and unit 20 is experimental skills.
  </p>
  <p>
    It is close to the NCERT syllabus but not identical to the CBSE board syllabus for the same year. The electronic
    devices unit, for example, includes the Zener diode as a voltage regulator, the photodiode, solar cell, LED
    characteristics and logic gates, and the experimental skills unit expects familiarity with standard laboratory
    experiments such as the metre bridge, screw gauge, resonance tube and prism deviation. A good JEE tutor teaches
    these explicitly rather than assuming the school covers them. For a unit-by-unit approach, see our
    <a href="{{ url('/blog/jee-physics-topicwise-prep') }}">topic-wise JEE physics preparation guide</a>.
  </p>
  </section>

