  <section class="nx-guide__sec">
  <h2 id="pj-session">What a JEE physics session with a tutor looks like</h2>
  <p>
    JEE sessions look different from board tuition, because much of the content has already been lectured in
    coaching. A productive 90-minute session often runs like this:
  </p>
  <ol>
    <li><strong>Warm-up, ten minutes.</strong> Two short problems from a chapter studied weeks ago, attempted without notes, to keep older topics alive.</li>
    <li><strong>The student's doubts, thirty minutes.</strong> Problems from the coaching module that the student attempted and could not finish. The tutor asks what was tried first, then guides rather than solves.</li>
    <li><strong>Targeted concept work, twenty minutes.</strong> One idea the doubts or last test exposed, taught properly with a derivation or a clean example.</li>
    <li><strong>Timed set, twenty minutes.</strong> Five or six JEE Main-level questions under exam timing, including at least one numerical-value question, marked with negative marking.</li>
    <li><strong>Close, ten minutes.</strong> Review of the timed set, an entry in the error log, and the plan until the next session.</li>
  </ol>
  <p>
    For Advanced aspirants, the timed set is replaced some weeks by one or two long multi-concept problems discussed
    in depth. For students who are behind, the concept block expands and the timed set shrinks until the
    foundation is secure.
  </p>
