  <h2 id="pj-areas">What each area of JEE physics demands</h2>
  <p>
    NTA does not publish chapter-wise weightage for JEE Main, and the spread shifts between shifts and years. It is
    more useful to know what kind of thinking each area asks for, because that decides how a tutor teaches it.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Area</th><th scope="col">What JEE tends to test</th><th scope="col">How a tutor builds it</th></tr>
    </thead>
    <tbody>
      <tr><td>Mechanics (kinematics to gravitation)</td><td>Choosing the system and frame; constraints; combining force, energy and momentum methods; rolling and rotation.</td><td>Free-body diagrams in every problem; solving the same problem by two methods; constraint relations drilled early.</td></tr>
      <tr><td>Properties of matter, heat and thermodynamics</td><td>Graph interpretation, P–V processes, calorimetry, and fluid problems that reuse mechanics.</td><td>Process diagrams; sign conventions fixed once and used consistently.</td></tr>
      <tr><td>Oscillations and waves</td><td>Identifying SHM in unfamiliar systems; superposition, standing waves in strings and pipes, and beats.</td><td>Deriving the restoring force from first principles rather than memorising periods.</td></tr>
      <tr><td>Electrostatics and current electricity</td><td>Symmetry arguments, Gauss's law, capacitor networks with dielectrics, circuit reduction and Kirchhoff's rules.</td><td>Redrawing circuits; potential-based reasoning; time-bound circuit sets.</td></tr>
      <tr><td>Magnetism, EMI and AC</td><td>Force and torque with correct directions; induced EMF and Lenz's law; LCR circuits, resonance and power.</td><td>Vector cross products made automatic; phasor diagrams for AC.</td></tr>
      <tr><td>Optics</td><td>Sign convention in combinations of lenses and mirrors; interference and diffraction patterns.</td><td>A single consistent sign convention; ray tracing for every combination problem.</td></tr>
      <tr><td>Modern physics and electronic devices</td><td>Photoelectric graphs, de Broglie wavelength, Bohr model, nuclear binding energy, semiconductors and logic gates.</td><td>Compact, formula-based chapters; fast to master and reliable for marks.</td></tr>
    </tbody>
  </table>
