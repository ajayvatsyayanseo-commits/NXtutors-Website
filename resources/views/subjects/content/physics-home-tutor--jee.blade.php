  <section class="nx-guide__sec">
  <h2 id="pj-tests">Test analysis: turning mocks into marks</h2>
  <p>
    JEE aspirants take a great many tests. The improvement comes from what happens after each one. A tutor should
    review every physics question the student got wrong, left, or got right slowly, and classify it:
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Category</th><th scope="col">Typical sign</th><th scope="col">Response</th></tr>
    </thead>
    <tbody>
      <tr><td>Concept missing</td><td>Could not start, even with time.</td><td>Reteach the idea; a focused problem set on that concept.</td></tr>
      <tr><td>Concept known, not recognised</td><td>Understood the solution immediately when shown.</td><td>More mixed-chapter practice; discuss "what told you to use this?"</td></tr>
      <tr><td>Execution error</td><td>Right approach, wrong algebra, sign or unit.</td><td>Error log; symbolic solving; end-of-problem checks.</td></tr>
      <tr><td>Time or selection</td><td>Spent too long; attempted a hard one first.</td><td>Practise a scan-and-select first pass; set time limits per question.</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    Tracked across tests, this shows clearly whether the next month should go on concepts, practice volume or exam
    temperament. It also tells the student which kinds of question to skip on the day. Sensible skipping, with
    negative marking in both sections, is a genuine skill.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pj-stall">Why JEE physics scores stall, and what fixes them</h2>
  <p>
    Parents often call when a student's physics marks have stopped rising despite hours of work. The causes are
    usually one of these:
  </p>
  <ul>
    <li><strong>Formula-first habits.</strong> The student searches memory for a formula that matches the given quantities, instead of thinking about the physics. It works for easy questions and fails on anything new. The fix is slower, principle-first practice for a few weeks.</li>
    <li><strong>Too many problems, too little review.</strong> Solving hundreds of questions without checking why the wrong ones went wrong. Fewer problems with proper discussion usually lift scores faster.</li>
    <li><strong>A hidden Class 11 gap.</strong> Weak vectors, rotation or calculus quietly drag down Class 12 electromagnetism. A diagnostic test on Class 11 fundamentals often reveals it.</li>
    <li><strong>Avoiding weak chapters.</strong> Students revise what they are good at because it feels productive. A tutor makes the uncomfortable chapters part of every week.</li>
    <li><strong>Poor exam temperament.</strong> Panic after one hard question, or refusing to skip. This improves with test practice under real conditions and a clear plan for the first pass through the paper.</li>
    <li><strong>Ignoring the numerical section.</strong> With negative marking, careless Section B answers cost marks. Practise these questions to completion, and check units and rounding before entering an answer.</li>
  </ul>
  </section>

