  <section class="nx-guide__sec">
  <h2 id="pj-adv">What changes for JEE Advanced</h2>
  <p>
    JEE Advanced is conducted by the IITs for students who qualify through JEE Main. It has two compulsory papers,
    and its format is set afresh each year by the organising IIT, so the details vary. In general terms:
  </p>
  <ul>
    <li><strong>Question types are more varied.</strong> Papers have used single-correct and multiple-correct questions, numerical answers, and matching or paragraph-based items, with marking rules that differ by type, sometimes including partial marks.</li>
    <li><strong>Questions go deeper.</strong> A problem may need three concepts chained together, or a careful physical argument before any equation is written.</li>
    <li><strong>Reading the instructions matters.</strong> Because marking changes from section to section, students must know each section's rules before they begin.</li>
  </ul>
  <p>
    Always read the official JEE Advanced information brochure for your year. A tutor preparing a student for Advanced
    should use recent Advanced papers from the second half of Class 12 onwards, not only JEE Main-level practice.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pj-depth">Building problem-solving depth</h2>
  <p>
    The difference between a student who scores well in JEE physics and one who plateaus is rarely knowledge. It is
    how they approach an unfamiliar problem. A tutor builds that habit deliberately:
  </p>
  <ol>
    <li><strong>Understand the physics before choosing an equation.</strong> What is conserved? What is the system? Is the frame inertial? A student should say this aloud before writing anything.</li>
    <li><strong>Draw everything.</strong> Free-body diagrams, field lines, ray diagrams, circuit redrawings, energy bar charts.</li>
    <li><strong>Solve in symbols, substitute at the end.</strong> This exposes errors through dimensional checks and limiting cases, and it is faster in multi-step problems.</li>
    <li><strong>Check the answer.</strong> Units, sign, order of magnitude, and what happens when a variable goes to zero or infinity.</li>
    <li><strong>Solve one problem two ways.</strong> Force and energy methods, or a ground frame and a moving frame. Seeing both is what makes the next unfamiliar problem manageable.</li>
  </ol>
  <p>
    Practice should be graded: NCERT and standard exercises for the idea, JEE Main previous papers for speed and
    typical traps, then harder multi-concept problems for Advanced aspirants. Quantity matters less than reflection:
    ten problems each discussed properly teach more than forty checked against an answer key.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="pj-maths">The mathematics behind JEE physics</h2>
  <p>
    JEE physics leans heavily on mathematics that students are learning at the same time in their maths class:
    vectors, trigonometry, differentiation, integration and simple differential equations. Common points of
    difficulty include:
  </p>
  <ul>
    <li><strong>Calculus in mechanics</strong>: variable acceleration, work done by variable forces, centre of mass and moment of inertia of continuous bodies.</li>
    <li><strong>Vectors in electromagnetism</strong>: the direction of magnetic force, torque on loops, and field superposition.</li>
    <li><strong>Differential equations</strong>: the equation of SHM, and for Advanced aspirants, problems where a quantity changes at a rate proportional to itself.</li>
    <li><strong>Approximations</strong>: small-angle and binomial approximations used throughout.</li>
  </ul>
  <p>
    If maths is holding back physics, it is often worth pairing the physics tutor with a
