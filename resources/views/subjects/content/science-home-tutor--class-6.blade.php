  <h2 id="s6GuideTitle">Science home tutor for Class 6: a parent's guide to the Curiosity year</h2>

  <p class="nx-guide__lede">
    Class 6 is the year science stops being part of environmental studies and becomes a subject of its own. For
    CBSE and most NCERT-following schools, that subject now comes through <em>Curiosity</em>, NCERT's science
    textbook for Grade 6, which asks children to observe, measure, test and explain rather than learn answers by
    heart. Most children enjoy it. Some find that "why" questions, measurement and written explanations are harder
    than they expected. This guide goes through the Class 6 chapters for 2026-27, safe experiments you can do at
    home, the diagrams and practical habits worth building, and how to judge whether a science tutor would help.
  </p>

