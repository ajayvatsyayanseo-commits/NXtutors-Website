  <h2 id="s6-next">How Class 6 science prepares the ground for Class 7</h2>
  <p>
    Almost every Class 6 chapter has a sequel. The Class 7 <em>Curiosity</em> book picks up the threads directly:
  </p>
  <ul>
    <li><strong>Mindful Eating leads to Life Processes in Animals and Plants.</strong> Knowing what food contains makes digestion and photosynthesis far easier to follow.</li>
    <li><strong>Materials Around Us and Methods of Separation lead to Metals and Non-metals, Acids and Bases, and Physical and Chemical Changes.</strong> Property words learnt in Class 6 are used every week in Class 7.</li>
    <li><strong>Measurement of Length and Motion leads to Measurement of Time and Motion.</strong> Speed, distance and time build on the Class 6 idea of describing motion.</li>
    <li><strong>Temperature leads to Heat Transfer in Nature.</strong> A child who is clear about temperature finds conduction, convection and radiation much easier.</li>
    <li><strong>Beyond Earth leads to Earth, Moon, and the Sun.</strong> Night-sky observation turns into eclipses and the Earth's revolution.</li>
  </ul>
