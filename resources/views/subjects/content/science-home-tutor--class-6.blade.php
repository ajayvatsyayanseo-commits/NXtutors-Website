  <h2 id="s6-mode">Home or online science tuition for Class 6</h2>
  <p>
    At this age, home tuition has a real advantage: the tutor can run the experiments with your child, handle
    materials, and see the notebook directly. Many Class 6 children also concentrate better with someone in the room.
  </p>
  <p>
    Online tuition works well when the child is settled and the family can set up simple materials beforehand. A
    tutor can demonstrate an activity on camera and have the child repeat it, and a phone pointed at the notebook
    makes diagram checking possible. It also widens your choice of tutor. Some families use a hybrid: one home
    session for activity-heavy chapters and one online session for revision. Our article on
    <a href="{{ url('/blog/online-vs-offline-tutoring') }}">online versus offline tutoring</a> goes into the trade-offs.
  </p>
