  <section class="nx-guide__sec">
  <h2 id="s6-new">What is new about science in Class 6</h2>
  <p>
    Until Class 5, science sits inside EVS alongside geography and everyday life. In Class 6 it gets its own
    textbook, its own periods and, before long, its own test papers. Three changes catch families out.
  </p>
  <ul>
    <li><strong>Science becomes a method, not just facts.</strong> <em>Curiosity</em> opens every chapter with a situation or a question, and asks children to predict, try an activity, record what happened and explain it. Answers in tests increasingly start with "because".</li>
    <li><strong>Measurement arrives.</strong> Scales, standard units, thermometers and careful reading of instruments appear for the first time. A child who guesses a reading loses marks that a child who reads it correctly keeps.</li>
    <li><strong>Written explanations get longer.</strong> A two-line answer about why ice melts in a warm room needs the right words (heat, temperature, change of state) in the right order.</li>
  </ul>
  <p>
    The first chapter, <em>The Wonderful World of Science</em>, is an introduction to scientific thinking and, as the
    book itself says, is not meant to be assessed. The eleven chapters after it are where school tests come from.
  </p>
  </section>

