    <li><strong>Can the tutor explain it simply?</strong> Class 6 needs plain language. A tutor who uses Class 10 terms to sound impressive is not the right fit.</li>
    <li><strong>A short plan.</strong> By the end, the tutor should be able to say what they would do in the first month.</li>
