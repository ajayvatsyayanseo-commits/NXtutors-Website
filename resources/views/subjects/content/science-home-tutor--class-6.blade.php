  <section class="nx-guide__sec">
  <h2 id="s6-icse">ICSE Class 6 science</h2>
  <p>
    In ICSE schools the picture is less uniform. CISCE does not prescribe a single Class 6 textbook, and many ICSE
    schools already teach science as three strands, physics, chemistry and biology, often from three separate books
    with their own tests. Common Class 6 ICSE topics include matter and its states, simple measurement, light and
    magnetism, elements and mixtures, the cell as a basic unit, plant parts and the human body, but the exact list
    depends on the school and the publisher it uses.
  </p>
  <p>
    Two practical points follow. First, share the school's syllabus sheet or book list when you ask for a tutor, so
    we match someone who knows those books. Second, three separate strands mean three sets of definitions and
    diagrams; the most useful thing a tutor does in ICSE Class 6 is keep one tidy notebook system across all three.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s6-home">Safe science experiments for Class 6 at home</h2>
  <p>
    <em>Curiosity</em> is built around activities, and many of them can be repeated at the kitchen table with
    ordinary materials. Doing one small experiment a week makes the chapter stick far better than rereading it.
    Every activity below should be done with an adult present.
  </p>
  <div class="nx-table-wrap">
  <table class="nx-table">
    <thead>
      <tr><th scope="col">Chapter</th><th scope="col">Activity</th><th scope="col">Safety note</th></tr>
    </thead>
    <tbody>
      <tr><td>Diversity in the Living World</td><td>Collect five fallen leaves, trace them and sort by venation; pull up a weed and a grass tuft to compare tap and fibrous roots</td><td>Wash hands afterwards; avoid unknown berries or sap</td></tr>
      <tr><td>Mindful Eating</td><td>Keep a three-day food diary and group each meal by nutrient; test a slice of potato with a drop of dilute iodine for starch</td><td>Iodine stains and must not be tasted; an adult handles it</td></tr>
      <tr><td>Exploring Magnets</td><td>Sort household objects into magnetic and non-magnetic; float a magnetised needle on a small leaf in a bowl to find north-south</td><td>Keep magnets away from phones and cards; adult handles the needle</td></tr>
      <tr><td>Measurement of Length and Motion</td><td>Measure a table in handspans, then with a scale; measure a curved line on a map using a thread</td><td>None beyond care with scissors</td></tr>
      <tr><td>Temperature</td><td>Record the room temperature morning and evening for a week with a digital thermometer and plot it</td><td>Do not use an old mercury thermometer; if one breaks, an adult clears it</td></tr>
      <tr><td>States of Water</td><td>Put equal water in a plate and a narrow glass, one in sun and one in shade, and compare after a day; watch droplets form on a glass of iced water</td><td>None</td></tr>
      <tr><td>Methods of Separation</td><td>Mix sand, salt and water; separate by filtering through a coffee filter or cloth and leaving the filtrate to evaporate in the sun</td><td>Use sunlight, not the stove</td></tr>
      <tr><td>Living Creatures</td><td>Soak moong seeds and set up four cups: with water, without water, in the fridge and in the dark, to test conditions for germination</td><td>None</td></tr>
      <tr><td>Beyond Earth</td><td>Find the Saptarishi (Big Dipper) or Orion on a clear night and sketch its shape over a few weeks</td><td>An adult accompanies on terraces</td></tr>
    </tbody>
  </table>
  </div>
  <p>
    The point of each activity is the record, not the result. Ask your child to write what they predicted, what
    they did, what they saw and one sentence explaining it. That four-step write-up is exactly the shape of a good
    Class 6 test answer.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s6-skills">Diagrams and practical skills to build in Class 6</h2>
  <p>
    Class 6 is the right time to set habits that will carry marks for the next five years. These are the ones a
    tutor should be working on quietly from the first month:
  </p>
    <div class="nx-guide__cards">
      <div class="nx-guide__card">
  <h3>Neat, labelled diagrams</h3>
  <p>
    A leaf with its venation, a seed with its parts, a bar magnet with field direction, a filtration set-up. Pencil
    only, label lines ruled and not crossing, labels on one side.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Reading instruments</h3>
  <p>
    Starting a measurement from the zero mark, reading at eye level, and writing the unit every single time. Many
    small Class 6 errors are unit errors.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Recording observations</h3>
  <p>
    Simple tables with headings and units, and a line of conclusion. By the end of the year a child should be able
    to draw their own table without being told the columns.
  </p>
      </div>
      <div class="nx-guide__card">
  <h3>Fair testing</h3>
  <p>
    Changing only one thing at a time, as in the seed germination activity. This single idea underpins almost every
    experiment in the years ahead.
  </p>
      </div>
    </div>
  </section>

