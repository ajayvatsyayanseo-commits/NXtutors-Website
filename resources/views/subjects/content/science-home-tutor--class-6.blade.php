  <section class="nx-guide__sec">
  <h2 id="s6-week">A simple weekly plan for Class 6 science</h2>
  <p>
    Class 6 does not need heavy tuition. For most children, two sessions a week of 45 to 60 minutes plus a little
    independent work is plenty. A week might look like this:
  </p>
  <ul>
    <li><strong>Session one (tutor).</strong> Recap last week in five quick questions, go through the current chapter's ideas using the book's activities, and draw the chapter's key diagram together.</li>
    <li><strong>Midweek (child, 20 minutes).</strong> Do one home activity from the table above and write it up in four steps: prediction, method, observation, explanation.</li>
    <li><strong>Session two (tutor).</strong> Check the write-up, answer the end-of-chapter questions aloud first and then in writing, and practise two "why" questions in full sentences.</li>
    <li><strong>Weekend (child, 15 minutes).</strong> Make or update a one-page chapter summary with key words and one diagram.</li>
  </ul>
  <p>
    Before school tests, swap the new-chapter work for revision of summaries and a short timed practice. Keep it
    light. The goal in Class 6 is confidence and good habits, not long hours.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="s6-signs">Signs your Class 6 child needs help with science</h2>
  <ul>
    <li><strong>Answers are memorised word for word.</strong> Change the wording of a question slightly and the answer falls apart.</li>
    <li><strong>Marks lost on measurement and units.</strong> Readings are off, units are missing, or conversions between centimetres and metres go wrong.</li>
    <li><strong>Diagrams are skipped or unlabelled.</strong> The child avoids drawing, or copies without understanding what the parts do.</li>
    <li><strong>"I don't know why" to every why question.</strong> The facts are known, but the explanation is not.</li>
    <li><strong>Science has become the least favourite subject.</strong> In Class 6 that is usually about confidence rather than ability, and it is easiest to fix now.</li>
    <li><strong>Reading is slowing science down.</strong> Some children understand the idea but struggle with the length of the text. A tutor can read and discuss alongside them.</li>
  </ul>
  </section>

