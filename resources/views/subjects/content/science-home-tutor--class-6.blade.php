  <h2 id="s6-choose">Choosing a Class 6 science tutor: a demo checklist</h2>
  <p>
    Every NXTutors shortlist comes with a free demo class. Use it to check the things that matter at this age:
  </p>
  <ul>
    <li><strong>Does the tutor know the new book?</strong> Ask which chapter comes after Temperature in <em>Curiosity</em>, or how they use the book's activities. A tutor still teaching from older notes will struggle with the new question style.</li>
    <li><strong>Does the child do something?</strong> A good Class 6 science demo includes a small activity or demonstration, not just explanation.</li>
