  <p>
    Two details in that document matter for planning. First, Computerised Accounting is compulsory for all commerce
    students in Class 11, but in Class 12 it is an <em>option</em>: a student takes either Part B, Financial
    Statement Analysis, or Part B, Computerised Accounting, with practical work in place of the project. Check which
    one your child's school teaches before you look for a tutor, because the second needs someone comfortable with
    spreadsheets and accounting software as well as the paper-based chapters. Second, the Class 11 syllabus includes
    basic GST calculations in recording transactions, and the CBSE document confines the accounting treatment of GST
    to Class 11.
  </p>
  <p>
    CBSE's suggested question paper design for both years splits the 80 theory marks by type of thinking: about 40%
    for remembering and understanding, 30% for applying, and 30% for analysing, evaluating and creating. In practice
    that means a student who can only reproduce textbook solutions reaches a ceiling. The last 30% rewards students
    who can read an unfamiliar situation, decide which adjustment applies, and explain why.
  </p>
  <p>
    The Class 12 project is a financial statement analysis of a company covering any two of: comparative and common
    size statements, accounting ratios, segment reports and cash flow statements. A tutor can teach the tools and
    check that the student understands them before the viva; the analysis and the file have to be the student's own
    work.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ac-bst">How accountancy sits with Business Studies</h2>
  <p>
    CBSE introduces Business Studies and Accountancy together at the plus-two stage, and most commerce students take
    both. They are separate papers (Business Studies is subject code 054, also 80 theory marks plus a 20-mark
    project), but they talk to each other. Business Studies in Class 11 covers the foundations of business and then
    finance and trade; in Class 12 it covers the principles and functions of management and then business finance
    and marketing. When a Business Studies chapter discusses sources of finance, shares and debentures, the
    accountancy student meets the same instruments as journal entries in the company accounts chapter.
  </p>
  <p>
    The two subjects reward different habits. Accountancy is precise and procedural: a figure is right or wrong.
    Business Studies is written: answers are marked for relevant points, correct terms and application to a case.
    Many students are strong in one and weak in the other. A tutor who teaches both can be convenient, but only if
    they are genuinely good at both; for a student struggling in accountancy, a specialist for that one subject is
    usually the better use of the budget. Tell us which of the two needs the help, or whether both do.
  </p>
  </section>

  <section class="nx-guide__sec">
  <h2 id="ac-isc">ISC Accounts and ISC Commerce</h2>
  <p>
    Under CISCE, the ISC equivalent is <strong>Accounts (858)</strong>, with <strong>Commerce (857)</strong> as a
    separate subject. Both have a three-hour, 80-mark theory paper and 20 marks of project work in each of Classes 11
    and 12, and for both the project work is two projects of 10 marks each, marked on format, content, findings and a
    viva based on the project.
  </p>
  <div class="nx-guide__cards">
    <div class="nx-guide__card">
  <h3>ISC Accounts, Class 11</h3>
  <p>
    The theory paper has a compulsory Part I of 20 marks (short answers across the whole syllabus) and a Part II of
    60 marks where students answer five questions out of eight, each worth 12. The syllabus runs from the
    introduction to accounting and the accounting equation, through journal, ledger and trial balance, bank
    reconciliation, depreciation and rectification of errors, to final accounts, incomplete records and non-trading
    organisations, with an introduction to the use of computers in accounting.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>ISC Accounts, Class 12</h3>
  <p>
    Section A (60 marks, compulsory) covers partnership accounts and joint stock company accounts: a compulsory
    12-mark Question 1, then four questions out of seven at 12 marks each. For the remaining 20 marks, students choose
    either Section B (financial statement analysis and the cash flow statement) or Section C (computerised
    accounting: spreadsheets and database management), answering two questions out of three at 10 marks each.
  </p>
    </div>
    <div class="nx-guide__card">
  <h3>ISC Commerce</h3>
  <p>
    Commerce is descriptive rather than numerical. Class 11 covers the nature and purpose of business, forms of
    business organisation, social responsibility, emerging modes of business, trade, the stock exchange, foreign trade
    and insurance. Class 12 covers the business environment, financing, management and marketing. The paper follows
    the same pattern as Accounts: 20 compulsory short-answer marks, then five questions out of eight.
  </p>
    </div>
  </div>
  <p>
    Because ISC Class 12 gives a choice between Section B and Section C, the same question applies as for CBSE: find
    out which one the school prepares students for. A tutor strong in ratio analysis and cash flow may never have
    taught spreadsheet functions or database queries, and the reverse is just as likely.
  </p>
  </section>

