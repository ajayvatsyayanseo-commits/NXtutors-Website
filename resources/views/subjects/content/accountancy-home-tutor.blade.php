  <h2 id="ac-cambridge">Cambridge IGCSE Accounting and AS &amp; A Level Accounting</h2>
  <p>
    Students in Cambridge schools meet accounting earlier, often in Grade 9 or 10, through IGCSE Accounting (0452).
    It is not tiered: all candidates take the same two papers and can reach any grade from A* to G. The syllabus for
    2027 to 2029 is organised in seven sections, from the fundamentals of accounting and the sources and recording of
    data, through verification of records, accounting procedures and the preparation of financial statements, to
    analysis and interpretation and accounting concepts.
