  <p>
    Partnership accounts deserve a special word. In CBSE Class 12 they are the largest unit, and in ISC they sit inside
    the compulsory Section A. Admission and retirement questions are long, and a small error early on (a reversed
    ratio, a missed reserve) carries through every account that follows. Students who work in a fixed sequence and
    write working notes for each step recover partial marks even when a figure goes wrong; students who do it all in
    one go lose the lot.
  </p>
