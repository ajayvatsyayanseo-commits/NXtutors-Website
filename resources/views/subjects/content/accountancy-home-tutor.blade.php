  <h2 id="ac-why">Why accountancy goes wrong, and why one-to-one fixes it</h2>
  <p>
    Parents often assume a weak accountancy student needs more practice questions. Sometimes that is true. More
    often, the student is practising a method they do not understand, and practice only makes the error faster. The
    problems a tutor meets again and again are specific:
  </p>
  <ul>
    <li><strong>Debit and credit learnt as a rhyme, not a rule.</strong> Students memorise "debit the receiver" without seeing why an expense is debited or why capital sits on the credit side. The accounting equation (assets equal liabilities plus capital) is the idea that makes every rule make sense, and it is often skipped.</li>
    <li><strong>Formats copied, not built.</strong> A trial balance, a trading and profit and loss account and a balance sheet each have a layout. A student who knows why an item goes where can rebuild the layout under exam pressure; a student who memorised a picture cannot.</li>
    <li><strong>Adjustments.</strong> Closing stock, outstanding and prepaid expenses, depreciation, provision for doubtful debts: each adjustment affects two places in the final accounts. Forgetting the second effect is a very common reason a balance sheet does not tally.</li>
    <li><strong>Working notes.</strong> Board papers give marks for working. Students who solve in their heads and write only the answer lose those marks even when the answer is right.</li>
    <li><strong>Theory questions.</strong> Commerce students tend to treat accountancy as all numbers, then lose easy marks on definitions, features and distinctions that the paper asks for in plain words.</li>
  </ul>
  <p>
    A tutor sitting beside the student sees every line of every ledger. That is where accountancy mistakes live: a
    wrong side, a missed posting, a balance carried down to the wrong period. A classroom teacher marking forty
    notebooks cannot catch these one by one; a tutor can, in the moment, and that is why accountancy responds well to
    one-to-one teaching.
  </p>
  </section>

