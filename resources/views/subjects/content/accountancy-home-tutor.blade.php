  <section class="nx-guide__sec">
  <h2 id="ac-cuet">Accountancy in CUET (UG)</h2>
  <p>
    For students aiming at central and participating universities, the NTA's CUET (UG) 2026 information bulletin lists
    <strong>Accountancy / Book Keeping</strong> (code 301) among the domain subjects, alongside Business Studies and
    Economics / Business Economics. Each domain test in that bulletin has 50 questions, all compulsory, in 60
    minutes, and the domain syllabus follows NCERT's Class 12 syllabus. Check the bulletin for the year your child
    will apply, since the NTA publishes a new one each cycle.
  </p>
  <p>
    What changes for tutoring is the style, not the content. Board papers reward complete, well-presented solutions;
    a timed multiple-choice test rewards quick recognition of the right treatment and fast, accurate arithmetic. A
    tutor can add the second skill to the first in the last months before the test, once the board syllabus
    is secure.
  </p>
  </section>

