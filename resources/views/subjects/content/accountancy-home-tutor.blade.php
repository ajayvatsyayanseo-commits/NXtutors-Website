  <h2 id="ac-mode">Home or online accountancy tuition</h2>
  <p>
    Accountancy is written on paper, in columns, and much of the teaching happens by looking over the student's
    shoulder at a ledger. That makes home tuition a natural fit, especially in Class 11 while the basics are being
    built. Online tuition works well too, provided the tutor can see the notebook clearly (a phone camera on a stand,
    or a writing tablet) and the student sends photos of homework before the session rather than during it. For the
    Computerised Accounting option or ISC Section C, online sessions with screen sharing are often better than home
    visits, because both people can work in the same spreadsheet.
  </p>
  <p>
    Many families use a mix: home sessions for the heavy written chapters such as partnership and final accounts, and
    shorter online sessions for theory revision and doubt clearing close to exams. A hybrid plan also helps when the
    nearest specialist lives across town, as it often does in a large city such as
