  <section class="nx-guide__sec">
  <h2 id="ac-session">What a useful accountancy session looks like</h2>
  <p>
    A good session is mostly the student writing. The tutor sets a transaction or a short question, watches the
    student work, and stops them at the first wrong step rather than at the wrong answer. A typical one-hour session
    for a Class 11 or 12 student might run like this:
  </p>
  <ol>
    <li><strong>Ten minutes of recall.</strong> Five quick entries or definitions from earlier chapters, because accountancy forgets itself if it is not revisited.</li>
    <li><strong>Twenty minutes on the new idea.</strong> The tutor explains one concept, such as the treatment of goodwill on admission, then the student does two examples with the tutor watching.</li>
    <li><strong>Twenty minutes of independent work.</strong> The student solves a full question with working notes while the tutor stays quiet, then they check it together line by line.</li>
    <li><strong>Ten minutes on theory and homework.</strong> Two or three short theory answers written in exam language, and a clear list of what to practise before the next session.</li>
  </ol>
  <p>
    Worked example of the kind of thinking a tutor builds: a trial balance shows rent of ₹24,000, and the adjustment
    note says rent for one month is prepaid. The student who understands adjustments makes two moves without being
    told: reduce the rent charged to the profit and loss account by one month's rent, and show the same amount as a
    prepaid expense among the current assets. The student who has only memorised formats usually makes one of the two
    moves and then wonders why the balance sheet is out. That habit, "every adjustment has two effects", is worth more
    than any number of solved questions.
  </p>
  </section>

