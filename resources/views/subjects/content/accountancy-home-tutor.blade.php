  <h2 id="acGuideTitle">Accountancy home tutor: a guide for commerce families</h2>

  <p class="nx-guide__lede">
    Accountancy is the one commerce subject that most students have never met before Class 11. Maths, English and
    even economics build on something from school; accountancy starts from zero, with its own vocabulary, its own
    formats and a logic (every transaction touches two accounts) that either clicks in the first month or quietly
    stops making sense. When it stops, the damage spreads fast, because every later chapter assumes the earlier ones.
    This guide explains what the syllabus actually contains for CBSE, ISC and Cambridge students, where students
    usually lose marks, what a useful tutoring session looks like, and how to judge an accountancy tutor in a single
    demo class.
  </p>

