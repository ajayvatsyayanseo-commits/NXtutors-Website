  <h2 id="phy-board">Physics by board: CBSE, ISC, IB, IGCSE and state boards</h2>
  <p>
    The physics itself is similar across boards; how it is examined is not. A tutor who knows your child's board
    teaches towards the paper they will actually sit.
  </p>
  <ul>
    <li><strong>CBSE.</strong> NCERT textbooks are the syllabus. In Classes 11 and 12 the theory paper is 70 marks and practicals 30. The 2026-27 curriculum weights question design at about 38% remembering and understanding, 32% applying and 30% analysing, evaluating and creating, so nearly two-thirds of the paper asks students to use physics rather than recall it.</li>
    <li><strong>ISC (CISCE).</strong> A theory paper plus practical and project work in Classes 11 and 12. ISC physics expects fuller written explanations and careful derivations; our <a href="{{ url('/blog/isc-class-12-physics-tips') }}">ISC Class 12 physics tips</a> cover the paper in detail.</li>
    <li><strong>IB Diploma Physics, SL and HL.</strong> The current course, first examined in 2025, is organised into five themes: space, time and motion; the particulate nature of matter; wave behaviour; fields; and nuclear and quantum physics. HL adds depth and extra content. Two written papers and an internal scientific investigation make up the assessment. See our <a href="{{ url('/blog/-ib-physics-slhl-iaee') }}">guide to IB physics SL, HL and the IA</a>.</li>
    <li><strong>Cambridge IGCSE Physics (0625).</strong> Six topics: motion, forces and energy; thermal physics; waves; electricity and magnetism; nuclear physics; and space physics. Students sit a multiple-choice paper, a theory paper and a practical or alternative-to-practical paper, at Core or Extended level.</li>
    <li><strong>State boards.</strong> Most follow NCERT-based syllabi in Classes 11 and 12, with their own paper patterns and marking. A tutor should work from the current state textbook and recent papers, not assume CBSE rules.</li>
  </ul>
