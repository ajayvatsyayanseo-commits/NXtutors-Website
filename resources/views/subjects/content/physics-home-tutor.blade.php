  <h2 id="phy-why">Why physics, more than most subjects, benefits from a tutor</h2>
  <p>
    Physics asks students to hold three things in their head at once: a physical picture of what is happening, the
    mathematics that describes it, and the exam technique that turns both into marks. School lessons usually teach
    the first two in sequence and leave the student to connect them alone at home. That connection is exactly what
    breaks down.
  </p>
  <p>
    A one-to-one tutor sees the moment it breaks. When a student draws a free-body diagram with a force pointing the
    wrong way, or writes the right formula but substitutes a value in the wrong unit, the tutor catches it on that line,
    not a fortnight later in a marked test. Over a few months, those corrections add up to a student who can start a
    problem on their own.
  </p>
  <p>
    Physics is also cumulative in a way parents often underestimate. Class 11 mechanics is the foundation for Class
    12 electricity and magnetism; vectors from Class 11 reappear in fields, forces on charges and optics. A gap left
    in April of Class 11 tends to surface, larger, in Class 12 and again in JEE or NEET.
  </p>
  </section>

